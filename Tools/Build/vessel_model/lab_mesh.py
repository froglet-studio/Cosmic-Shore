#!/usr/bin/env python3
"""
lab_mesh - a vessel's MODEL, as a lab page draws it: the FBX's rest-pose hull, triangulated, its four slots kept,
written as one small JavaScript file a studio page loads (`window.VesselLabModels.<Vessel>`), so a lab shows the ship
the game flies instead of a stand-in of spheres and cones (Garrett, 2026-10-18: "have the artifact better represent
the new graphics approach").

    python3 Tools/Build/vessel_model/lab_mesh.py Goby           # write Docs/Studios/VesselStudio/models/goby-model.js
    python3 Tools/Build/vessel_model/lab_mesh.py Goby --check   # exit 1 when the committed file drifted from the model

Runs with the plain `python3` that has bpy (PIPELINE.md). The file it writes is generated: never hand-edit it.

THE FRAME. The FBX imports into Blender's frame (nose -Y, up +Z, the pilot's left +X: rig.py); a lab draws three.js's
(nose -Z, up +Y, the pilot's right +X), so a point (x, y, z) is written as (-x, z, y), a proper rotation. The vessel's
origin is kept: it is the pivot the game flies about.

THE FORMAT. Positions are int16 scaled by `scale`, normals int8 / 127 (the model's split normals, so sharp edges stay
sharp), indices uint16, all base64; `slots` lists [name, first index, index count] in the file's slot order, so the
page builds one geometry with one group per slot. `length` is the hull's nose-to-tail length in model units.
"""

import argparse
import base64
import json
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))

VESSELS = {
    "Goby": ("Assets/_Models/Vessel Models/Goby.fbx", "Docs/Studios/VesselStudio/models/goby-model.js"),
}


def export(vessel):
    import bpy
    import bmesh
    src, _ = VESSELS[vessel]
    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.ops.import_scene.fbx(filepath=os.path.join(REPO, src), ignore_leaf_bones=False, automatic_bone_orientation=False, use_anim=False)
    meshes = [o for o in bpy.data.objects if o.type == "MESH"]
    if len(meshes) != 1:
        raise RuntimeError("%s: expected one mesh, found %d" % (src, len(meshes)))
    obj = meshes[0]
    for a in bpy.data.objects:
        if a.type == "ARMATURE":
            a.data.pose_position = "REST"   # the rest IS the drawn hull (the pipeline bakes the parked pose into it)
    if obj.data.shape_keys:
        for kb in obj.data.shape_keys.key_blocks:
            kb.value = 0.0
    dg = bpy.context.evaluated_depsgraph_get()
    ev = obj.evaluated_get(dg)
    me = ev.to_mesh()
    me.transform(obj.matrix_world)
    bm = bmesh.new()
    bm.from_mesh(me)
    bmesh.ops.triangulate(bm, faces=bm.faces[:])
    bm.to_mesh(me)
    bm.free()
    names = [m.name if m else "Body" for m in obj.data.materials]
    normals = me.corner_normals   # Blender 4.1+: the split (custom or auto-smoothed) normal of every corner
    verts, vkey, tris = [], {}, []
    for poly in me.polygons:
        tri = []
        for li in poly.loop_indices:
            vi = me.loops[li].vertex_index
            n = normals[li].vector
            q = (vi, round(n.x * 127), round(n.y * 127), round(n.z * 127))
            k = vkey.get(q)
            if k is None:
                co = me.vertices[vi].co
                k = vkey[q] = len(verts)
                verts.append(((-co.x, co.z, co.y), (-q[1], q[3], q[2])))   # Blender (x, y, z) -> three (-x, z, y)
            tri.append(k)
        tris.append((poly.material_index, tri))
    ev.to_mesh_clear()
    if len(verts) >= 65536:
        raise RuntimeError("%s: %d vertices do not fit uint16 indices" % (src, len(verts)))
    tris.sort(key=lambda t: t[0])   # stable: one contiguous run per slot, the file's own order within it
    reach = max(max(abs(c) for c in p) for p, _ in verts)
    scale = reach / 32767.0
    pos = b"".join(struct.pack("<3h", *(int(round(c / scale)) for c in p)) for p, _ in verts)
    nrm = b"".join(struct.pack("<3b", *(max(-127, min(127, c)) for c in n)) for _, n in verts)
    idx, slots = bytearray(), []
    for slot in range(len(names)):
        run = [t for s, t in tris if s == slot]
        if run:
            slots.append([names[slot], len(idx) // 2, 3 * len(run)])
            for t in run:
                idx += struct.pack("<3H", *t)
    zs = [p[2] for p, _ in verts]
    model = {"source": src, "length": round(max(zs) - min(zs), 4), "scale": scale, "slots": slots,
             "pos": base64.b64encode(pos).decode(), "nrm": base64.b64encode(nrm).decode(), "idx": base64.b64encode(bytes(idx)).decode()}
    return ("/* generated by Tools/Build/vessel_model/lab_mesh.py %s from %s - do not edit: run the tool */\n"
            "(window.VesselLabModels = window.VesselLabModels || {})[%s] = %s;\n"
            % (vessel, src, json.dumps(vessel), json.dumps(model, separators=(",", ":"))))


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("vessel", choices=sorted(VESSELS))
    ap.add_argument("--check", action="store_true", help="fail when the committed file drifted from the model")
    a = ap.parse_args(argv)
    text = export(a.vessel)
    out = os.path.join(REPO, VESSELS[a.vessel][1])
    if a.check:
        have = open(out, encoding="utf-8").read() if os.path.exists(out) else ""
        if have != text:
            print("DRIFT: %s is not what %s draws (run Tools/Build/vessel_model/lab_mesh.py %s)" % (VESSELS[a.vessel][1], VESSELS[a.vessel][0], a.vessel))
            return 1
        print("OK: %s matches %s" % (VESSELS[a.vessel][1], VESSELS[a.vessel][0]))
        return 0
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d KB)" % (os.path.relpath(out, REPO), os.path.getsize(out) // 1024))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
