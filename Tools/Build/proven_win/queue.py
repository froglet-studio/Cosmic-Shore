#!/usr/bin/env python3
"""
The ONE Proven Win queue: Docs/ProvenWin/QUEUE.json (the data) and QUEUE.md (the human view, written by `render`).
The scout adds to it, /proven-win takes from it, every outcome goes back into it, and every outcome teaches the scout
(LENSES.md). Use this tool for every change to the queue; never edit QUEUE.json or QUEUE.md by hand.

    python Tools/Build/proven_win/queue.py count                      # how many are queued (refill below 3)
    python Tools/Build/proven_win/queue.py stale                      # re-check every queued entry against the code
    python Tools/Build/proven_win/queue.py list [--all]
    python Tools/Build/proven_win/queue.py add <entry.json>           # the scout's output, one entry per file
    python Tools/Build/proven_win/queue.py take [<id>]                # the top queued entry -> measuring
    python Tools/Build/proven_win/queue.py done <id> --outcome won|rejected|inconclusive \
           --reason "<one line with the numbers>" --lesson "<what the scout should do differently next time>"
    python Tools/Build/proven_win/queue.py render
    python Tools/Build/proven_win/queue.py --self-test

An entry (the scout writes these; `add` refuses one with a field missing):
    id, title, where (list of "path:lines"), runtimeWriters, inUse, waste, change, exactness
    ("bit-identical" | "display-identical" | "approximate"), bench ("shader" | "scene"), probes, negativeControl,
    otherStates, owner, lane, gain, confidence ("high" | "medium" | "low"), lens (which LENSES.md lens found it)
`add` records the commit and each file's blob hash, so `stale` can tell when the code under an entry moved.
"""
import argparse
import datetime
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
QUEUE = os.path.join(ROOT, "Docs", "ProvenWin", "QUEUE.json")
VIEW = os.path.join(ROOT, "Docs", "ProvenWin", "QUEUE.md")
LENSES = os.path.join(ROOT, "Docs", "ProvenWin", "LENSES.md")

REQUIRED = ["id", "title", "where", "runtimeWriters", "inUse", "waste", "change", "exactness", "bench",
            "negativeControl", "owner", "lane", "gain", "confidence", "lens"]
EXACTNESS_RANK = {"bit-identical": 0, "display-identical": 1, "approximate": 2}
CONFIDENCE_RANK = {"high": 0, "medium": 1, "low": 2}
REFILL_BELOW = 3


def git(*args):
    return subprocess.run(["git", "-C", ROOT, *args], capture_output=True, text=True).stdout.strip()


def load():
    if not os.path.exists(QUEUE):
        return {"entries": []}
    with open(QUEUE, encoding="utf-8") as f:
        return json.load(f)


def save(q):
    with open(QUEUE, "w", encoding="utf-8") as f:
        json.dump(q, f, indent=1)
    render(q)


def paths_of(entry):
    return sorted({w.split(":")[0].strip() for w in entry.get("where", []) if w.strip()})


def blob(path):
    r = subprocess.run(["git", "-C", ROOT, "rev-parse", "--verify", "--quiet", f"HEAD:{path}"], capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 and r.stdout.strip() else "missing"


def rank_key(e):
    return (EXACTNESS_RANK.get(e.get("exactness"), 9), CONFIDENCE_RANK.get(e.get("confidence"), 9), e.get("added", ""))


def queued(q):
    return sorted([e for e in q["entries"] if e["status"] == "queued"], key=rank_key)


def render(q):
    lines = ["# Proven Win queue", "",
             "Generated by `Tools/Build/proven_win/queue.py render` from `QUEUE.json`. Do not edit by hand.", ""]
    for status, title in (("measuring", "Being measured"), ("queued", "Queued (best first)"), ("stale", "Stale (re-check before taking)"),
                          ("won", "Won"), ("rejected", "Rejected (never re-propose)"), ("inconclusive", "Inconclusive")):
        rows = [e for e in q["entries"] if e["status"] == status]
        if status == "queued":
            rows = queued(q)
        if not rows:
            continue
        lines += [f"## {title}", "", "| id | title | exactness | confidence | owner / lane | note |", "|---|---|---|---|---|---|"]
        for e in rows:
            note = e.get("outcomeReason") or e.get("staleReason") or e.get("gain", "")
            lines.append(f"| {e['id']} | {e['title']} | {e.get('exactness','')} | {e.get('confidence','')} | "
                         f"{e.get('owner','')} / {e.get('lane','')} | {note.replace('|', '/')} |")
        lines.append("")
    with open(VIEW, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def cmd_add(path):
    entry = json.load(open(path, encoding="utf-8"))
    missing = [k for k in REQUIRED if not entry.get(k)]
    if missing:
        sys.exit(f"refused: the entry has no {missing}. Fill them (the scout skill says how) and add it again.")
    if entry["exactness"] not in EXACTNESS_RANK:
        sys.exit(f"refused: exactness must be one of {list(EXACTNESS_RANK)}")
    if entry["bench"] not in ("shader", "scene"):
        sys.exit("refused: bench must be 'shader' or 'scene' (a change neither bench can measure is not a candidate yet)")
    q = load()
    for e in q["entries"]:
        if e["id"] == entry["id"]:
            sys.exit(f"refused: id {entry['id']} already exists ({e['status']})")
        same_place = set(paths_of(e)) & set(paths_of(entry)) and e["title"].lower() == entry["title"].lower()
        if e["status"] == "rejected" and (same_place or e["id"] == entry["id"]):
            sys.exit(f"refused: this is {e['id']}, rejected: {e.get('outcomeReason')}. Propose something different.")
    entry["status"] = "queued"
    entry["added"] = datetime.date.today().isoformat()
    entry["baseCommit"] = git("rev-parse", "--short", "HEAD")
    entry["fileHashes"] = {p: blob(p) for p in paths_of(entry)}
    if any(h == "missing" for h in entry["fileHashes"].values()):
        sys.exit(f"refused: a 'where' path does not exist at HEAD: {entry['fileHashes']}")
    q["entries"].append(entry)
    save(q)
    print(f"queued {entry['id']} ({len(queued(q))} queued)")


def cmd_stale():
    q = load()
    n = 0
    for e in q["entries"]:
        if e["status"] not in ("queued", "stale"):
            continue
        moved = [p for p, h in e.get("fileHashes", {}).items() if blob(p) != h]
        if moved and e["status"] == "queued":
            e["status"] = "stale"
            e["staleReason"] = f"changed since {e.get('baseCommit')}: {', '.join(moved)}"
            n += 1
            print(f"STALE {e['id']}: {e['staleReason']}")
    save(q)
    print(f"{n} newly stale; re-check each against the code, then `add` a corrected entry with a new id or `done --outcome rejected`.")


def cmd_take(eid):
    q = load()
    pool = [e for e in queued(q) if not eid or e["id"] == eid]
    if not pool:
        sys.exit("nothing queued" + (f" with id {eid}" if eid else "") + ": run /proven-win-scout first")
    e = pool[0]
    moved = [p for p, h in e.get("fileHashes", {}).items() if blob(p) != h]
    if moved:
        e["status"] = "stale"
        e["staleReason"] = f"changed since {e.get('baseCommit')}: {', '.join(moved)}"
        save(q)
        sys.exit(f"{e['id']} is stale ({e['staleReason']}): re-check it before measuring; take another")
    e["status"] = "measuring"
    e["taken"] = datetime.date.today().isoformat()
    save(q)
    print(json.dumps(e, indent=1))


def cmd_done(eid, outcome, reason, lesson):
    if not lesson or len(lesson.split()) < 6:
        sys.exit("refused: --lesson must say, in a sentence, what the scout should look for or avoid next time "
                 "(every outcome teaches the scout; that is how the queue gets better)")
    q = load()
    e = next((x for x in q["entries"] if x["id"] == eid), None)
    if not e:
        sys.exit(f"no entry {eid}")
    e["status"] = outcome
    e["outcomeReason"] = reason
    e["finished"] = datetime.date.today().isoformat()
    save(q)
    with open(LENSES, "a", encoding="utf-8") as f:
        f.write(f"- {e['finished']} {eid} ({outcome}, lens: {e.get('lens', '?')}): {lesson}\n")
    print(f"{eid} -> {outcome}. Lesson appended to LENSES.md. {len(queued(q))} queued"
          + (f": BELOW {REFILL_BELOW}, run /proven-win-scout next." if len(queued(q)) < REFILL_BELOW else "."))


def self_test():
    import tempfile
    global QUEUE, VIEW, LENSES
    d = tempfile.mkdtemp()
    QUEUE, VIEW, LENSES = (os.path.join(d, n) for n in ("Q.json", "Q.md", "L.md"))
    open(LENSES, "w").write("# lenses\n")
    base = {k: "x" for k in REQUIRED}
    base.update(id="t1", title="Test", where=["CLAUDE.md:1-5"], exactness="bit-identical",
                bench="shader", confidence="high")
    bad = 0
    def expect_exit(fn, what):
        nonlocal bad
        try:
            fn()
            print("FAIL " + what); bad += 1
        except SystemExit as ex:
            print("ok   " + what + f" ({str(ex)[:60]})")
    p = os.path.join(d, "e.json")
    json.dump(base, open(p, "w")); cmd_add(p)
    expect_exit(lambda: cmd_add(p), "duplicate id refused")
    json.dump({**base, "id": "t2", "runtimeWriters": ""}, open(p, "w"))
    expect_exit(lambda: cmd_add(p), "missing runtimeWriters refused")
    json.dump({**base, "id": "t3", "where": ["No/Such/File.cs:1"]}, open(p, "w"))
    expect_exit(lambda: cmd_add(p), "missing file refused")
    expect_exit(lambda: cmd_done("t1", "won", "r", "short"), "a lesson too short refused")
    cmd_take(None)
    cmd_done("t1", "rejected", "slower on vulkan", "do not propose skips that move existing lines in a shader")
    json.dump({**base, "id": "t4"}, open(p, "w"))
    expect_exit(lambda: cmd_add(p), "re-proposing a rejected candidate refused")
    q = load()
    q["entries"].append({**base, "id": "t5", "status": "queued", "fileHashes": {"CLAUDE.md": "0" * 40}})
    save(q)
    cmd_stale()
    ok = next(e for e in load()["entries"] if e["id"] == "t5")["status"] == "stale"
    print(("ok   " if ok else "FAIL ") + "a moved file marks the entry stale"); bad += not ok
    ok = "do not propose skips" in open(LENSES).read()
    print(("ok   " if ok else "FAIL ") + "the lesson reached LENSES.md"); bad += not ok
    print("self-test:", "PASS" if bad == 0 else f"{bad} FAILED")
    return 0 if bad == 0 else 1


def main():
    if sys.argv[1:] == ["--self-test"]:
        return self_test()
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("count"); sub.add_parser("stale"); sub.add_parser("render")
    s = sub.add_parser("list"); s.add_argument("--all", action="store_true")
    s = sub.add_parser("add"); s.add_argument("entry")
    s = sub.add_parser("take"); s.add_argument("id", nargs="?")
    s = sub.add_parser("done"); s.add_argument("id"); s.add_argument("--outcome", required=True, choices=["won", "rejected", "inconclusive"])
    s.add_argument("--reason", required=True); s.add_argument("--lesson", required=True)
    a = ap.parse_args()
    if a.cmd == "count":
        n = len(queued(load()))
        print(n, "(refill: run /proven-win-scout)" if n < REFILL_BELOW else "")
    elif a.cmd == "stale":
        cmd_stale()
    elif a.cmd == "render":
        render(load()); print("wrote", VIEW)
    elif a.cmd == "list":
        for e in (load()["entries"] if a.all else queued(load())):
            print(f"{e['status']:<12} {e['id']:<28} {e.get('exactness',''):<18} {e['title']}")
    elif a.cmd == "add":
        cmd_add(a.entry)
    elif a.cmd == "take":
        cmd_take(a.id)
    elif a.cmd == "done":
        cmd_done(a.id, a.outcome, a.reason, a.lesson)
    return 0


if __name__ == "__main__":
    sys.exit(main())
