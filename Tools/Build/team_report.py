#!/usr/bin/env python3
"""team_report.py - a report on any shared area, or on one person's work, built fresh from git, the task board
and the area's own report doc, for whoever asks (Yash, 2026-10-15: "if someone asks you about a report of some other
person working on some shared field, you should be able to give those reports to them").

    python3 Tools/Build/team_report.py areas                     # the areas it knows (Docs/Reports/areas.json)
    python3 Tools/Build/team_report.py area regatta-ai           # the area's report, last 14 days
    python3 Tools/Build/team_report.py area regatta-ai --days 30 --write   # also refresh the generated block of its doc
    python3 Tools/Build/team_report.py person Yash               # one person's areas, branches and recent merges
    python3 Tools/Build/team_report.py paths Assets/_Scripts/Controller/AI Docs/AI_SYSTEM   # any paths, no registry
    python3 Tools/Build/team_report.py --self-test

An AREA is a row of Docs/Reports/areas.json: its paths, owner, who it is for, its branch, artifacts, docs, how to test
it, and a hand-written report (Docs/Reports/<NAME>.md) that says what the work IS. This script adds what CHANGED:
  - recent commits on any branch that touch the area's paths, newest first, each with where it is (the area's branch,
    bleeding-edge);
  - what other branches have in flight there (who_works_where.py);
  - the open tasks for the area (Docs/TEAM_TASKS.md).
`--write` puts that block into the report doc between its team_report markers, so the doc a person opens is current.
Run `git fetch origin` first: it reads origin/*. A reader: it changes nothing but, with --write, that block.
"""
import argparse
import datetime
import json
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
REGISTRY = 'Docs/Reports/areas.json'
BEGIN, END = '<!-- team_report:begin (generated by Tools/Build/team_report.py; do not edit) -->', '<!-- team_report:end -->'
MAX_COMMITS = 25


def git(root, *args):
    r = subprocess.run(['git', '-C', root, *args], capture_output=True, text=True)
    return r.stdout if r.returncode == 0 else ''


def load_registry(root):
    with open(os.path.join(root, REGISTRY), encoding='utf-8') as fh:
        return json.load(fh)['areas']


def find_area(areas, name):
    key = name.lower().strip()
    for k, a in areas.items():
        if key == k or key in [x.lower() for x in a.get('aliases', [])] or key == a['title'].lower():
            return k, a
    return None, None


def on_branch(root, sha, branch):
    return subprocess.run(['git', '-C', root, 'merge-base', '--is-ancestor', sha, 'origin/' + branch],
                          capture_output=True).returncode == 0


def recent(root, paths, days, branches):
    """[(date, subject, short sha, [branches it is on])], newest first, one per subject."""
    out = git(root, 'log', '--all', '--no-merges', f'--since={days}.days', '--format=%H\x1f%ct\x1f%s', '--', *paths)
    rows, seen = [], set()
    for line in out.splitlines():
        sha, ts, subject = (line.split('\x1f') + ['', '', ''])[:3]
        if not sha or subject in seen:
            continue
        seen.add(subject)
        where = [b for b in branches if on_branch(root, sha, b)]
        rows.append((datetime.date.fromtimestamp(int(ts)).isoformat(), subject, sha[:9], where))
        if len(rows) >= MAX_COMMITS:
            break
    return rows


def in_flight(root, paths, days, skip):
    try:
        r = subprocess.run([sys.executable, os.path.join(root, 'Tools/Build/who_works_where.py'), '--root', root, 'query',
                            '--days', str(days), '--json', *paths], capture_output=True, text=True, timeout=120)
        data = json.loads(r.stdout or '{}')
    except (OSError, ValueError, subprocess.SubprocessError):
        return []
    return [f for f in data.get('inFlight', []) if f.get('branch') not in skip]


def open_tasks(root, area_names):
    path = os.path.join(root, 'Docs/TEAM_TASKS.md')
    if not os.path.exists(path):
        return []
    sys.path.insert(0, os.path.join(root, 'Tools/Build'))
    try:
        import team_tasks  # noqa: E402
        _, tasks = team_tasks.parse(open(path, encoding='utf-8').read())
    except Exception:
        return []
    names = {n.lower() for n in area_names}
    return [t for t in tasks if t.area.strip().lower() in names and t.is_open]


def block(root, key, a, days):
    branches = [b for b in [a.get('branch'), 'bleeding-edge'] if b]
    lines = [f"_Generated {datetime.date.today().isoformat()} from git (last {days} days), "
             f"who_works_where.py and Docs/TEAM_TASKS.md: `python3 Tools/Build/team_report.py area {key} --days {days}`._", '']
    rows = recent(root, a['paths'], days, branches)
    lines.append(f"### Recent changes ({len(rows)}{'+' if len(rows) >= MAX_COMMITS else ''})")
    if not rows:
        lines.append('- Nothing in the window.')
    for date, subject, sha, where in rows:
        place = ', '.join(where) if where else 'another branch'
        lines.append(f"- {date} `{sha}` {subject} — on {place}")
    flight = in_flight(root, a['paths'], days, set(branches))
    lines += ['', '### Also in flight on other branches']
    if not flight:
        lines.append('- None.')
    for f in flight[:10]:
        who = ', '.join(f.get('people') or []) or 'unattributed'
        lines.append(f"- `{f['branch']}` ({who}, {f.get('date', '')}): {f.get('last', '')}")
    tasks = open_tasks(root, a.get('taskAreas', [a['title']]))
    lines += ['', '### Open tasks (Docs/TEAM_TASKS.md)']
    if not tasks:
        lines.append('- None.')
    for t in tasks:
        lines.append(f"- {t.id} [{t.status}] {t.kind}: {t.fields.get('Task', '').strip()} (who: {t.fields.get('Who can take it', '').strip()})")
    return '\n'.join(lines)


def area_report(root, key, a, days):
    head = [f"# {a['title']} — report", '',
            f"**Owner:** {a.get('owner', '?')}. **For:** {', '.join(a.get('audience', [])) or 'anyone'}. "
            f"**Branch:** `{a.get('branch', 'bleeding-edge')}`" + (f" ({a['branchNote']})" if a.get('branchNote') else '') + '.', '']
    if a.get('summary'):
        head += [a['summary'], '']
    if a.get('artifacts'):
        head.append('**Artifacts:** ' + '; '.join(f"[{x['name']}]({x['url']})" for x in a['artifacts']) + '.')
    if a.get('report'):
        head.append(f"**Full report:** `{a['report']}`. **Docs:** " + ', '.join(f'`{d}`' for d in a.get('docs', [])) + '.')
    if a.get('test'):
        head += ['', '**How to test it:**'] + [f"{i + 1}. {s}" for i, s in enumerate(a['test'])]
    return '\n'.join(head + ['', block(root, key, a, days)])


def write_block(root, a, text):
    path = os.path.join(root, a['report'])
    doc = open(path, encoding='utf-8').read()
    if BEGIN not in doc or END not in doc:
        raise SystemExit(f"{a['report']}: no team_report markers")
    pre, rest = doc.split(BEGIN, 1)
    post = rest.split(END, 1)[1]
    open(path, 'w', encoding='utf-8').write(pre + BEGIN + '\n' + text + '\n' + END + post)


def person_report(root, name, days):
    team = json.load(open(os.path.join(root, 'Docs/TEAM.json'), encoding='utf-8'))
    p = next((x for x in team['people'] if name.lower() in [n.lower() for n in [x['name'], *x.get('names', [])]]), None)
    if not p:
        return f"No one called {name} in Docs/TEAM.json."
    out = [f"# {p['name']} — what they work on", '', p.get('role', ''), '']
    areas = load_registry(root)
    mine = [(k, a) for k, a in areas.items() if p['name'] in (a.get('owner', ''), *a.get('people', []))]
    out.append('## Their areas (Docs/Reports/areas.json)')
    out += [f"- **{a['title']}** (`team_report.py area {k}`): {a.get('summary', '')[:220]}" for k, a in mine] or ['- None registered.']
    refs = git(root, 'for-each-ref', '--sort=-committerdate', '--format=%(refname:short)\x1f%(committerdate:short)\x1f%(subject)',
               'refs/remotes/origin')
    prefixes = p.get('branch_prefixes', [])
    since = (datetime.date.today() - datetime.timedelta(days=days)).isoformat()
    out += ['', f'## Their branches updated in the last {days} days']
    rows = [r.split('\x1f') for r in refs.splitlines()]
    hits = [r for r in rows if len(r) == 3 and r[1] >= since and any(r[0].replace('origin/', '', 1).startswith(x) for x in prefixes)]
    out += [f"- `{r[0].replace('origin/', '', 1)}` ({r[1]}): {r[2]}" for r in hits[:15]] or ['- None.']
    merged = git(root, 'log', 'origin/bleeding-edge', '--merges', f'--since={days}.days', '--format=%an\x1f%cs\x1f%s\x1f%b\x1e')
    names = {n.lower() for n in [p['name'], *p.get('names', [])]}
    ms = []
    for rec in merged.split('\x1e'):
        f = rec.strip('\n').split('\x1f')
        if len(f) >= 3 and f[0].lower() in names:   # a GitHub merge records the person who pressed Merge as its author
            title = (f[3].strip().splitlines() or [''])[0] if len(f) > 3 else ''
            pr = re.search(r'#\d+', f[2])
            ms.append((f[0], f[1], (pr.group(0) + ' ' if pr else '') + (title or f[2])))
    out += ['', f'## Pull requests they merged into bleeding-edge ({len(ms)})']
    out += [f"- {m[1]}: {m[2]}" for m in ms[:15]] or ['- None.']
    return '\n'.join(out)


def self_test():
    with tempfile.TemporaryDirectory() as tmp:
        def sh(*a):
            subprocess.run(a, cwd=tmp, check=True, capture_output=True)
        os.makedirs(os.path.join(tmp, 'Docs/Reports'))
        os.makedirs(os.path.join(tmp, 'src'))
        reg = {'areas': {'demo': {'title': 'Demo', 'owner': 'Yash', 'audience': ['Garrett'], 'branch': 'main', 'paths': ['src'],
                                  'report': 'Docs/Reports/DEMO.md', 'aliases': ['the demo'], 'test': ['Run it.']}}}
        open(os.path.join(tmp, REGISTRY), 'w').write(json.dumps(reg))
        open(os.path.join(tmp, 'Docs/Reports/DEMO.md'), 'w').write('# Demo\n\nWritten by hand.\n\n' + BEGIN + '\nold\n' + END + '\n\nTail.\n')
        sh('git', 'init', '-q', '-b', 'main'); sh('git', 'config', 'user.email', 'a@b'); sh('git', 'config', 'user.name', 'T')
        open(os.path.join(tmp, 'src/a.txt'), 'w').write('1')
        sh('git', 'add', '.'); sh('git', 'commit', '-qm', 'feat(demo): the first change')
        sh('git', 'update-ref', 'refs/remotes/origin/main', 'HEAD')
        areas = load_registry(tmp)
        k, a = find_area(areas, 'The Demo')
        assert k == 'demo', 'an alias finds the area'
        text = area_report(tmp, k, a, 7)
        assert 'the first change' in text and 'on main' in text, text
        assert 'How to test it' in text and 'Run it.' in text, text
        write_block(tmp, a, block(tmp, k, a, 7))
        doc = open(os.path.join(tmp, 'Docs/Reports/DEMO.md')).read()
        assert 'Written by hand.' in doc and 'Tail.' in doc and 'old' not in doc and 'the first change' in doc, doc
        assert find_area(areas, 'nothing')[0] is None, 'an unknown area is not guessed'
    print('team_report self-test: ok')
    return 0


def main(argv):
    if '--self-test' in argv:
        return self_test()
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    sub = ap.add_subparsers(dest='cmd', required=True)
    sub.add_parser('areas')
    pa = sub.add_parser('area'); pa.add_argument('name'); pa.add_argument('--days', type=int, default=14); pa.add_argument('--write', action='store_true')
    pp = sub.add_parser('person'); pp.add_argument('name'); pp.add_argument('--days', type=int, default=14)
    ph = sub.add_parser('paths'); ph.add_argument('paths', nargs='+'); ph.add_argument('--days', type=int, default=14)
    a = ap.parse_args(argv)
    if a.cmd == 'areas':
        for k, x in load_registry(ROOT).items():
            print(f"{k:16} {x['title']} (owner {x.get('owner', '?')}; aliases: {', '.join(x.get('aliases', []))})")
        return 0
    if a.cmd == 'area':
        areas = load_registry(ROOT)
        k, x = find_area(areas, a.name)
        if not k:
            print(f"No area '{a.name}'. Known: {', '.join(areas)}. For any paths: team_report.py paths <paths>.")
            return 1
        print(area_report(ROOT, k, x, a.days))
        if a.write and x.get('report'):
            write_block(ROOT, x, block(ROOT, k, x, a.days))
            print(f"\n(wrote the generated block of {x['report']})")
        return 0
    if a.cmd == 'person':
        print(person_report(ROOT, a.name, a.days))
        return 0
    x = {'title': ', '.join(a.paths), 'paths': a.paths, 'branch': None}
    print(f"# Report on {x['title']}\n\n" + block(ROOT, 'paths', x, a.days))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
