#!/usr/bin/env python3
"""Builds Docs/Studios/ConverterReelLab.html from the SHIPPED converter assets and src/*.js.

The page is a reader of the shipped numbers: the combine data, the converter's ranges, the cadence, the body
material, the domain colours and (through the two extract scripts) the depth prisms and the Charge light are read
here from the assets, never typed into the page. Every module the parity gates measure (src/*.js) is inlined
verbatim, so the page plays exactly the code the gates ran.

    python3 Tools/Build/converter_reel/build.py           # write the page
    python3 Tools/Build/converter_reel/build.py --check   # fail if the page is stale against the assets or src
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUT = ROOT / 'Docs/Studios/ConverterReelLab.html'
DATA = ROOT / 'Assets/_SO_Assets/Environment/OmniCombine/OmniCombineData.json'
CONFIG = ROOT / 'Assets/_SO_Assets/Environment/OmniCombine/OmniCombineConfig.asset'
CADENCE = ROOT / 'Assets/_SO_Assets/Environment/OmniCrystalCadence.asset'
BODY = ROOT / 'Assets/_Graphics/Materials/CrystalMaterials/OmniCrystalBody.mat'
DOMAINS = ROOT / 'Docs/Studios/VesselStudio/studio-domains.js'
MODULES = ['combineCore.js', 'chargeArcs.js', 'chargeArcsShader.js', 'depthPrisms.js', 'depthPrismsShader.js',
           'reelExtras.js', 'reelCharge.js', 'reel.js', 'render.js']


def yaml_fields(path):
    """The top-level `key: value` lines of a Unity YAML asset (scalars and {x:, y:} pairs)."""
    out = {}
    for line in path.read_text().splitlines():
        m = re.match(r'^  (\w+): (.*)$', line)
        if not m:
            continue
        key, val = m.groups()
        pair = re.match(r'\{x: ([-\d.e]+), y: ([-\d.e]+)\}', val)
        if pair:
            out[key] = [float(pair.group(1)), float(pair.group(2))]
            continue
        try:
            out[key] = float(val) if re.search(r'[.e]', val) else int(val)
        except ValueError:
            out[key] = val
    return out


def material_colour(path, name):
    m = re.search(r'- ' + name + r': \{r: ([-\d.e]+), g: ([-\d.e]+), b: ([-\d.e]+), a: ([-\d.e]+)\}', path.read_text())
    if not m:
        raise SystemExit(f'{path.name}: no {name}')
    return [float(m.group(i)) for i in range(1, 4)]


def material_float(path, name):
    m = re.search(r'- ' + name + r': ([-\d.e]+)', path.read_text())
    if not m:
        raise SystemExit(f'{path.name}: no {name}')
    return float(m.group(1))


def to_hex(rgb):
    """A material colour as the colour picker shows it. Unity stores colour properties gamma-encoded."""
    return '#' + ''.join(f'{max(0, min(255, round(c * 255))):02x}' for c in rgb)


def build():
    cfg = yaml_fields(CONFIG)
    config = {k: cfg[k] for k in ('lead', 'spread', 'layoutYawDegrees', 'flight', 'staggerOfFlight', 'arc', 'swirl', 'tumble',
                                  'siteSpread', 'suck', 'socketSpacing', 'socketSeconds', 'massRaise',
                                  'approachAboveCameraDegrees', 'layout', 'ease', 'morphStart', 'morphLength', 'effectFade',
                                  'fadeInSeconds', 'handOffSeconds', 'omniWorldRadius')}
    # OmniCombineConfigSO.MaxStartRadii
    config['maxStartRadii'] = max(config['spread']) * (1 + max(config['arc'])) + 1
    cad = yaml_fields(CADENCE)
    cadence = {k: cad[k] for k in ('pentagonTurnSeconds', 'triangleTurnSeconds', 'gapSeconds', 'waveActiveSeconds', 'waveSpeed',
                                   'pentagonLift', 'triangleLift', 'triangleSide', 'plateThickness')}
    spread = material_colour(BODY, '_Spread')
    materials = {'body': {'bright': to_hex(material_colour(BODY, '_BrightColor')), 'dark': to_hex(material_colour(BODY, '_DarkColor')),
                          'spread': spread[0], 'fresnelPower': material_float(BODY, '_FresnelPower')}}
    domains = [dict(key=m.group(1), name=m.group(2), color=m.group(3)) for m in
               re.finditer(r"\{ key: '(\w+)', name: '(\w+)', id: \d+, color: '(#[0-9a-f]{6})'", DOMAINS.read_text())]
    if len(domains) != 4:
        raise SystemExit('studio-domains.js: expected four domains')
    assets = {
        'data': json.loads(DATA.read_text()),
        'config': config, 'cadence': cadence, 'materials': materials, 'domains': domains,
        'depth': json.loads((HERE / 'data/depth.json').read_text()),
        'arcs': json.loads((HERE / 'data/charge_arcs.json').read_text()),
    }
    page = (HERE / 'page.html').read_text()
    blob = json.dumps(assets, separators=(',', ':'))
    scripts = '\n'.join(f'<script>\n// ---- Tools/Build/converter_reel/src/{m}\n{(HERE / "src" / m).read_text()}</script>' for m in MODULES)
    header = ('<!-- GENERATED by Tools/Build/converter_reel/build.py from the shipped converter assets and src/*.js. '
              'Do not edit by hand: edit the sources and rebuild (--check fails when this page is stale). -->\n')
    page = page.replace('<!--ASSETS-->', '<script>globalThis.REEL_ASSETS = ' + blob + ';</script>')
    page = page.replace('<!--MODULES-->', scripts)
    page = page.replace('<!--APP-->', f'<script>\n// ---- Tools/Build/converter_reel/src/app.js\n{(HERE / "src/app.js").read_text()}</script>')
    return header + page


def main():
    page = build()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text() != page:
            print(f'STALE  {OUT.relative_to(ROOT)}: run python3 Tools/Build/converter_reel/build.py')
            return 1
        print(f'OK     {OUT.relative_to(ROOT)} matches the assets and src')
        return 0
    OUT.write_text(page)
    print(f'wrote {OUT.relative_to(ROOT)} ({len(page) / 1e6:.2f} MB)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
