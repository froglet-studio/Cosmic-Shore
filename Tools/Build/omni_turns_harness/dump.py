#!/usr/bin/env python3
"""
Dumps what the omni turns harness runs the SHIPPED C# on, as Unity sees it:
  - the omni body (OmniCrystalExport1_8-21-25.fbx) imported the way Unity imports it: x negated, one vertex per
    polygon corner (the importer splits this flat-shaded model by normal), polygons fanned into triangles, each
    vertex carrying its polygon's normal;
  - OmniSpaceSquares.asset: anchors, body radius and the three keys (deltas, stackedOn).
Writes body.json next to this file (gitignored scratch, regenerated by run.sh).
"""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "Tools", "Build"))
import author_omni_crystal_triangles as A   # noqa: E402

verts, faces = A._load(A.OMNI_FBX)
P, N, T = [], [], []
for f in faces:
    pts = [(-verts[i][0], verts[i][1], verts[i][2]) for i in f]
    a, b, c = pts[0], pts[1], pts[2]
    u = [b[k] - a[k] for k in range(3)]; v = [c[k] - a[k] for k in range(3)]
    n = [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]]
    l = sum(x * x for x in n) ** 0.5 or 1.0
    n = [x / l for x in n]
    # the polygon's normal must face away from the plate's own side of the crystal is not needed: turned normals are
    # compared with themselves
    base = len(P)
    for p in pts:
        P.append(p); N.append(n)
    for k in range(1, len(pts) - 1):
        T += [base, base + k + 1, base + k]   # x negated flips the winding back to Unity's
text = open(os.path.join(ROOT, "Assets/_SO_Assets/Environment/OmniSpaceSquares.asset")).read()
vec = lambda s: [float(x) for x in re.findall(r"[xyz]: ([-0-9.eE+]+)", s)]
head, keys_text = text.split("\n  keys:\n")
anchors = [vec(l) for l in head.split("\n  anchors:\n")[1].splitlines() if l.startswith("  - {")]
radius = float(re.search(r"bodyRadius: (\S+)", text).group(1))
keys = []
for block in re.split(r"\n  - name: ", "\n" + keys_text)[1:]:
    name = block.splitlines()[0].strip()
    stacked = int(re.search(r"stackedOn: (-?\d+)", block).group(1))
    deltas = [vec(l) for l in block.split("deltas:\n")[1].splitlines() if l.strip().startswith("- {")]
    keys.append({"name": name, "stackedOn": stacked, "deltas": deltas})
    if len(deltas) != len(anchors): raise SystemExit(f"key {name}: {len(deltas)} deltas for {len(anchors)} anchors")
json.dump({"positions": P, "normals": N, "triangles": T, "anchors": anchors, "bodyRadius": radius, "keys": keys},
          open(os.path.join(HERE, "body.json"), "w"))
print(f"body: {len(P)} vertices, {len(T)//3} triangles; squares: {len(anchors)} anchors, {len(keys)} keys")
