#!/usr/bin/env python3
"""Write siege_fixture.json - what the substrate harness's group `siege` asserts the game's SIEGE port against
(Docs/SUBSTRATE_FAUNA.md §10):

  * "defaults": the lab's SIEGE_DEFAULTS, read out of flight/src/70_siege.js;
  * "inline": the numbers the lab's act() writes inline (the glow delay, the dive's lead, the separation, the
    accelerations...), each read by a pattern that must match exactly once - a lab rewrite FAILS here rather than
    silently keeping an old number;
  * "scenarios": the lab's own encounters (siege_trace.js run on the lab's flight/sim.js): a snapshot at the step a
    GATHER starts, the pilot track, the phase events and member positions until the encounter's SCATTER ends;
  * "eval": the lab's siege_eval.json rows (what the four scripted pilots pay per encounter).

    python3 Tools/Build/substrate_harness/siege_fixture.py [<git ref of the lab branch>]

Default ref: origin/cece/gifted-curie-x2cpd0 (fetch it first: git fetch origin cece/gifted-curie-x2cpd0). The lab is
read with `git show`, nothing is checked out. Needs node. When the ref is not reachable the committed JSON is kept and
the harness still checks the C# against it.
"""
import json
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "siege_fixture.json")
REF = sys.argv[1] if len(sys.argv) > 1 else "origin/cece/gifted-curie-x2cpd0"
FLIGHT = "Tools/Ecology/flight"

# (key, regex with ONE number group) over 70_siege.js - each must match exactly once
INLINE = [
    ("glow_delay", r"!\(phase === 'close' && this\.tp < ([\d.]+)\)"),
    ("predict_s", r"const tau = ([\d.]+), prx"),
    ("swerve_r", r"if \(phase === 'gather' && d < ([\d.]+)\)"),
    ("sep_r", r"this\.sepInto\(i, ([\d.]+), des"),
    ("sep_w", r"phase === 'dive' \? [\d.]+ : ([\d.]+)\);"),
    ("sep_w_dive", r"phase === 'dive' \? ([\d.]+) : [\d.]+\);"),
    ("accel", r"const acc = phase === 'dive' \? [\d.]+ : ([\d.]+);"),
    ("accel_dive", r"const acc = phase === 'dive' \? ([\d.]+) : [\d.]+;"),
    ("roam_jitter", r"\(gx - xi\) \* [\d.]+ \+ this\.rng\.normal\(0, ([\d.]+)\)"),
    ("roam_cohesion", r"qx - gx \+ \(gx - xi\) \* ([\d.]+)"),
    ("contact_pad", r"if \(d < r0 \+ this\.size\[i\] \+ ([\d.]+)\)"),
    ("min_members", r"pd < K\.DETECT && live >= (\d+)\)"),
    ("first_cool", r"this\.prog = 0; this\.cool = ([\d.]+);"),
]


def git_show(path):
    return subprocess.run(["git", "show", f"{REF}:{path}"], check=True, capture_output=True, text=True).stdout


def defaults(src):
    m = re.search(r"const SIEGE_DEFAULTS = \{(.*?)\};", src, re.S)
    if not m:
        raise SystemExit("70_siege.js: SIEGE_DEFAULTS not found")
    return {k: float(v) for k, v in re.findall(r"([A-Z_0-9]+): ([-\d.]+)", m.group(1))}


def inline(src):
    out, bad = {}, []
    for key, pat in INLINE:
        hits = re.findall(pat, src)
        if len(hits) != 1:
            bad.append(f"{key}: {len(hits)} matches of {pat!r}")
            continue
        out[key] = float(hits[0])
    if bad:
        raise SystemExit("70_siege.js changed shape:\n  " + "\n  ".join(bad))
    return out


def main():
    try:
        src = git_show(f"{FLIGHT}/src/70_siege.js")
    except subprocess.CalledProcessError:
        print(f"{REF} is not reachable - keeping the committed {os.path.basename(OUT)}")
        return 0
    with tempfile.TemporaryDirectory() as d:
        for f in ("sim.js", "params.json"):
            with open(os.path.join(d, f), "w") as fh:
                fh.write(git_show(f"{FLIGHT}/{f}"))
        trace = json.loads(subprocess.run(["node", os.path.join(HERE, "siege_trace.js"), d],
                                          check=True, capture_output=True, text=True).stdout)
    ev = json.loads(git_show(f"{FLIGHT}/results/siege_eval.json"))
    rev = subprocess.run(["git", "rev-parse", REF], check=True, capture_output=True, text=True).stdout.strip()
    fx = {"_note": f"generated by siege_fixture.py from {REF} @ {rev[:12]} - do not edit",
          "defaults": defaults(src), "inline": inline(src), "scenarios": trace["scenarios"],
          "eval": {"headline": ev["headline"], "rows": {p: {k: r[k] for k in (
              "burned_per_min", "burned_per_encounter", "encounters_per_min", "escape_share", "breach_share",
              "dive_bites_per_dive", "telegraphed_share", "first_lead_s_median")} for p, r in ev["rows"].items()}}}
    with open(OUT, "w") as fh:
        json.dump(fx, fh, separators=(",", ":"))
    print(f"wrote {OUT} ({os.path.getsize(OUT) // 1024} KB): {len(fx['defaults'])} defaults, {len(fx['inline'])} inline, "
          + ", ".join(f"{s['policy']} {len(s['steps'])} steps" for s in fx["scenarios"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
