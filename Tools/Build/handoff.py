def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--self-test', action='store_true')
    sub = ap.add_subparsers(dest='cmd')
    for k in ('to', 'open', 'test', 'claim', 'keep'):
        p = sub.add_parser(k)
        if k == 'to':
            p.add_argument('person')
        if k == 'claim':
            p.add_argument('lane_pos', nargs='?')
        p.add_argument('--lane')
        p.add_argument('--by')
        p.add_argument('--note', default='')
        p.add_argument('--pr', type=int)
        p.add_argument('--brief', help='a JSON file: the hand-off brief the recipient sees on For you (summary, decisions, '
                       'open [[where, what]], steps [..], reading [[doc, how]], doc)')
        p.add_argument('--source', default='cli', help='where the hand-off was written (a doc path when recorded from one)')
        if k == 'test':
            p.add_argument('--what', required=True, help='the tester\'s brief: steps, branch or build, what good looks like')
    p = sub.add_parser('feedback')
    p.add_argument('target', help='a handoff id, or a lane key (its open test)')
    p.add_argument('verdict', choices=['good', 'back'])
    p.add_argument('--note', default='')
    p.add_argument('--by')
    p = sub.add_parser('seen')
    p.add_argument('target')
    p.add_argument('--by')
    p = sub.add_parser('list')
    p.add_argument('--person')
    p.add_argument('--all', action='store_true')
    p.add_argument('--json', action='store_true')
    p = sub.add_parser('suggest')
    p.add_argument('--me')
    p.add_argument('--lane')
    p.add_argument('--json', action='store_true')
    p = sub.add_parser('import')
    p.add_argument('file')
    p = sub.add_parser('skills')
    p.add_argument('--check', action='store_true')
    a = ap.parse_args()
    if a.self_test:
        return 1 if self_test() else 0
    root = repo_root()
    people = People(root)
    if a.cmd in ('to', 'open', 'test', 'claim', 'keep'):
        by = people.me(a.by)
        if not by:
            raise SystemExit('who are you? pass --by <name> (Docs/TEAM.json), or set FROGLET_PERSON')
        lane = resolve_lane(root, a.lane or getattr(a, 'lane_pos', None))
        branch = approvals(root).current_branch(root)
        to = None
        if a.cmd == 'to':
            to = people.resolve(a.person)
            if not to:
                raise SystemExit(f'"{a.person}" is not a person in Docs/TEAM.json (names: {", ".join(people.names())})')
        if a.cmd == 'test':
            to = (config(root).get('testers') or ['Andrew'])[0]
        sig = signals(root, lane.kind, branch)
        brief = None
        if a.brief:
            brief = json.load(open(a.brief, encoding='utf-8'))
            unknown = set(brief) - {'summary', 'decisions', 'open', 'steps', 'reading', 'doc'}
            if unknown:
                raise SystemExit(f'--brief has keys a page cannot show: {sorted(unknown)}')
        r = record(root, a.cmd, lane, by, to=to, note=a.note, what=getattr(a, 'what', ''),
                   branch=None if a.source != 'cli' or branch in ('HEAD', 'bleeding-edge') else branch,
                   pr=a.pr, sig=sig, source=a.source, brief=brief)
        print(f'{DIR}/{r["id"]}.json written: {lane.name} ' + {'to': f'handed to {to} (NEW on their board)',
              'open': 'back on the open list', 'test': f'sent for test to {to}', 'claim': f'claimed by {by}',
              'keep': 'kept (recorded so /ship learns when to ask)'}[a.cmd] + '. Commit Docs/Handoffs/ and push it.')
        return 0
    if a.cmd in ('feedback', 'seen'):
        by = people.me(a.by)
        recs = read_all(root)
        cur = current(recs)
        h = next((r for r in recs if r['id'] == a.target), None) or cur.get(a.target.lower())
        if not h:
            raise SystemExit(f'no handoff "{a.target}" (`handoff.py list` shows them)')
        if a.cmd == 'feedback':
            if a.verdict == 'back' and not a.note:
                raise SystemExit('`back` needs --note: what failed and how to reproduce it is the next person\'s brief')
            e = answer(root, h['id'], 'feedback', by, a.verdict, a.note)
            print(f'{h["laneName"]}: ' + ('good to go (the lane opens, marked tested)' if a.verdict == 'good' else
                                          'back to the open list with your note') + '. Commit Docs/Handoffs/ and push it.')
        else:
            answer(root, h['id'], 'seen', by)
            print(f'{h["laneName"]}: read by {by}. Commit Docs/Handoffs/ and push it.')
        return 0
    if a.cmd == 'list':
        recs = read_all(root)
        if a.json:
            print(json.dumps({'current': current(recs), 'all': recs}, indent=1, ensure_ascii=False))
        else:
            print_list(recs, people.resolve(a.person) if a.person else None, a.all)
        return 0
    if a.cmd == 'suggest':
        me = people.me(a.me)
        lane = resolve_lane(root, a.lane)
        branch = approvals(root).current_branch(root)
        s = suggest(read_all(root), me, lane, signals(root, lane.kind, branch), config(root).get('testers') or ['Andrew'])
        if a.json:
            print(json.dumps(s, indent=1))
        else:
            print(('ASK' if s['ask'] else 'MENTION') + f' - {s["laneName"]} looks finished for now. Suggested, best first:')
            for i, o in enumerate(s['ranked'], 1):
                print(f'  {i}. {o["skill"]}')
            for r in s['reasons']:
                print(f'  because {r}')
        return 0
    if a.cmd == 'import':
        rows = json.load(open(a.file, encoding='utf-8'))
        rows = rows.get('docs', rows) if isinstance(rows, dict) else rows
        applied, refused = import_actions(root, [r for r in rows if not r.get('synced')], people)
        print(json.dumps({'applied': applied, 'refused': refused}, indent=1))
        return 0
    if a.cmd == 'skills':
        drift, stale = sync_skills(root, people.names(confirmed_only=True), a.check)
        if a.check:
            if drift or stale:
                print('handoff skills drift: ' + ', '.join(drift + stale) + ' (run `handoff.py skills`)')
                return 1
            print('handoff skills: ok')
        else:
            print('handoff skills written: ' + (', '.join(drift + stale) if drift or stale else 'none changed'))
        return 0
    ap.print_help()
    return 0


if __name__ == '__main__':
    sys.exit(main())
