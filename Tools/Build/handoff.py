def wanted_skills(people):
    out = {}
    for name in people:
        s = slug(name, 20)
        out[f'handoff-to-{s}'] = TO_SKILL.format(slug=s, name=name, pronoun_ref='they', mark=GENERATED_MARK)
    for k, body in FIXED_SKILLS.items():
        out[k] = body.format(mark=GENERATED_MARK)
    return out


def sync_skills(root, people, check):
    want = wanted_skills(people)
    drift = []
    for k, body in want.items():
        p = os.path.join(root, SKILL_DIR, k, 'SKILL.md')
        have = open(p, encoding='utf-8').read() if os.path.isfile(p) else None
        if have != body:
            drift.append(k)
            if not check:
                os.makedirs(os.path.dirname(p), exist_ok=True)
                with open(p, 'w', encoding='utf-8', newline='\n') as fh:
                    fh.write(body)
    stale = []
    base = os.path.join(root, SKILL_DIR)
    for d in sorted(os.listdir(base)) if os.path.isdir(base) else []:
        p = os.path.join(base, d, 'SKILL.md')
        if d.startswith('handoff-to-') and d not in want and os.path.isfile(p) and GENERATED_MARK in open(p, encoding='utf-8').read():
            stale.append(d)
            if not check:
                os.remove(p)
                os.rmdir(os.path.dirname(p)) if not os.listdir(os.path.dirname(p)) else None
    return drift, stale


# --- import: the page's clicks ----------------------------------------------------------------------------------------

def import_actions(root, actions, people):
    """Apply the Swim Lanes page's action rows (ArtifactData list of `actions`, unsynced ones) as handoff and approval
    files. Returns the action ids applied and the ones refused (with why)."""
    _, lanes = lanes_of(root)
    applied, refused = [], []
    ap = approvals(root)
    queue = None
    for a in sorted(actions, key=lambda a: a.get('at', '')):
        aid, t = a.get('_id') or a.get('id'), a.get('type')
        by = people.resolve(a.get('by') or '')
        try:
            when = datetime.datetime.fromisoformat((a.get('at') or '').replace('Z', '+00:00')).replace(microsecond=0)
        except ValueError:
            when = now_utc()
        if not by:
            refused.append((aid, f'"{a.get("by")}" is not a person in Docs/TEAM.json'))
            continue
        if t in ('approve', 'discuss', 'resolve'):
            if queue is None:
                queue = ap.read_queue(root, 60)
            try:
                ap.reply(root, ap.tools(root)[0].Team.load(root), a.get('entry'), t, by, a.get('note', ''), queue)
                applied.append(aid)
            except SystemExit as e:
                refused.append((aid, str(e)))
            continue
        if t == 'feedback':
            recs = read_all(root)
            hid = a.get('handoff') or (current(recs).get(a.get('lane')) or {}).get('id')
            if not hid or a.get('verdict') not in ('good', 'back'):
                refused.append((aid, 'feedback needs a handoff id and a verdict good|back'))
                continue
            answer(root, hid, 'feedback', by, a['verdict'], a.get('note', ''), when, source='page')
            applied.append(aid)
            continue
        if t == 'seen':
            answer(root, a.get('handoff'), 'seen', by, None, '', when, source='page')
            applied.append(aid)
            continue
        ln = find_lane(lanes, a.get('lane') or '')
        if not ln or t not in ('to', 'open', 'test', 'claim'):
            refused.append((aid, f'unknown lane "{a.get("lane")}" or action "{t}"'))
            continue
        to = people.resolve(a.get('to') or '') if t == 'to' else (config(root).get('testers') or ['Andrew'])[0] if t == 'test' else None
        if t == 'to' and not to:
            refused.append((aid, f'"{a.get("to")}" is not a person in Docs/TEAM.json'))
            continue
        record(root, t, ln, by, to=to, note=a.get('note', ''), what=a.get('what', ''), when=when, source='page')
        applied.append(aid)
    return applied, refused


# --- print ----------------------------------------------------------------------------------------------------------

LABEL = {'new': 'NEW', 'taken': 'taken', 'open': 'open', 'testing': 'FOR TEST', 'passed': 'tested: good to go',
         'back': 'tested: back to open', 'claimed': 'claimed', 'kept': 'kept'}


def line(h):
    who = {'to': f'{h["by"]} -> {h.get("to")}', 'open': f'{h["by"]} -> open', 'test': f'{h["by"]} -> {h.get("to")} (test)',
           'claim': f'{h["by"]} claimed', 'keep': f'{h["by"]} kept it'}[h['kind']]
    s = f'[{LABEL.get(h.get("status"), h.get("status"))}] {h["laneName"]} ({h["lane"]}): {who}, {h["on"][:10]}'
    s += f', on {h["where"]}' if h.get('where') not in (None, 'local', 'landed') else ''
    s += f'\n      id {h["id"]}'
    if h.get('note'):
        s += f'\n      note: {h["note"]}'
    if h.get('what'):
        s += f'\n      test: {h["what"]}'
    for e in h.get('events', []):
        if e['event'] == 'feedback':
            s += f'\n      feedback ({e["by"]}, {e["on"][:10]}): {e.get("verdict")}' + (f' - {e["note"]}' if e.get('note') else '')
    return s


def print_list(recs, person=None, show_all=False):
    cur = current(recs)
    rows = sorted(cur.values(), key=lambda h: h['on'], reverse=True)
    if person:
        mine = [h for h in rows if h.get('to') == person and h['status'] in ('new', 'testing', 'taken')]
        sent = [h for h in rows if h.get('by') == person and h not in mine]
        print(f'Handed to {person}: {len(mine)}' + ('' if mine else ' (nothing waits for you)'))
        for h in mine:
            print('  ' + line(h))
        print(f'\nHanded off by {person}: {len(sent)}')
        for h in sent[:None if show_all else 8]:
            print('  ' + line(h))
        return
    active = [h for h in rows if show_all or h['status'] in ('new', 'testing', 'taken', 'claimed', 'open', 'back')]
    print(f'Handoffs: {len(active)} active' + (f' of {len(rows)}' if not show_all else ''))
    for h in active:
        print('  ' + line(h))


# --- self-test ------------------------------------------------------------------------------------------------------

def self_test():
    bad = []
    t0 = datetime.datetime(2026, 11, 13, 10, tzinfo=datetime.timezone.utc)

    def rec(kind, lane, by, to=None, days=0, sig=None, events=()):
        return {'id': make_id(kind, lane, by, t0 + datetime.timedelta(days=days)), 'kind': kind, 'lane': lane, 'laneName': lane,
                'laneKind': 'shell', 'by': by, 'to': to, 'on': (t0 + datetime.timedelta(days=days)).isoformat(),
                'signals': sig or {}, 'events': list(events)}
    now = t0 + datetime.timedelta(days=2)
    a = rec('to', 'voyages', 'Shombith', 'Garrett')
    if status(a, now) != 'new':
        bad.append('a handoff to a person is not NEW before they read it')
    a['events'] = [{'event': 'seen', 'by': 'Garrett', 'on': now.isoformat()}]
    if status(a, now) != 'taken':
        bad.append('a handoff the recipient read is not taken')
    a['events'] = [{'event': 'seen', 'by': 'Yash', 'on': now.isoformat()}]
    if status(a, now) != 'new':
        bad.append('someone other than the recipient marked a handoff seen')                     # negative control
    t = rec('test', 'hangar', 'Caleb', 'Andrew')
    if status(t, now) != 'testing' or holder(dict(t, status='testing')) != 'Andrew':
        bad.append('a lane sent for test is not with the tester')
    t['events'] = [{'event': 'feedback', 'by': 'Andrew', 'on': now.isoformat(), 'verdict': 'back'}]
    if status(t, now) != 'back' or holder(dict(t, status='back')) is not None:
        bad.append('a lane the tester sent back is not open')
    c = rec('claim', 'settings', 'Yash', days=-10)
    if current([c], now):
        bad.append('a claim older than the window still holds its lane')                         # negative control
    later = rec('open', 'voyages', 'Garrett', days=1)
    if current([a, later], now)['voyages']['kind'] != 'open':
        bad.append('the newest handoff of a lane does not win')
    k = rec('keep', 'voyages', 'Shombith', days=1.5)
    if current([a, later, k], now)['voyages']['kind'] != 'open':
        bad.append('a "keep it" record changed a lane')                                         # negative control

    class L:
        key, name, kind, note = 'hangar', 'Hangar', 'shell', ''
    sig = {'laneKind': 'shell', 'handTests': True, 'merged': False}
    s = suggest([], 'Shombith', L, sig, ['Andrew'])
    if s['ranked'][0]['kind'] != 'test' or not s['ask']:
        bad.append(f'a branch with new hand tests and no history does not ask, first suggesting the tester: {s}')
    hist = [rec('keep', 'hangar', 'Shombith', days=-i, sig={'laneKind': 'shell', 'handTests': False, 'merged': False}) for i in range(5)]
    s2 = suggest(hist, 'Shombith', L, {'laneKind': 'shell', 'handTests': False, 'merged': False}, ['Andrew'])
    if s2['ask']:
        bad.append('a person who always keeps going under these signals is still asked')
    hist2 = [rec('to', 'hangar', 'Shombith', 'Caleb', days=-i, sig={'laneKind': 'shell', 'handTests': False, 'merged': False}) for i in range(4)]
    s3 = suggest(hist2, 'Shombith', L, {'laneKind': 'shell', 'handTests': False, 'merged': False}, ['Andrew'])
    if not s3['ask'] or s3['ranked'][0] != {'kind': 'to', 'to': 'Caleb', 'skill': '/handoff-to-caleb'}:
        bad.append(f'a person who always hands this lane to Caleb is not offered Caleb first: {s3["ranked"]}')
    want = wanted_skills(['Garrett', 'Andrew'])
    if set(want) != {'handoff-to-garrett', 'handoff-to-andrew', 'handoff-open', 'handoff-for-test', 'handoff-feedback'} \
            or 'name: handoff-to-garrett' not in want['handoff-to-garrett']:
        bad.append(f'the generated skills are wrong: {sorted(want)}')
    print('self-test: ' + ('ok' if not bad else 'FAILED: ' + '; '.join(bad)))
    return bad


