#!/usr/bin/env python3
"""Handoffs: pass a swim lane to a person, back to the open list, or to the tester - and read what was passed to you.

    python3 Tools/Build/handoff.py to Garrett [--lane voyages] [--note "..."] [--by Shombith]   # /handoff-to-<person>
    python3 Tools/Build/handoff.py open [--lane voyages] [--note "..."]                          # /handoff-open
    python3 Tools/Build/handoff.py test [--lane voyages] --what "fly a voyage, dock home"         # /handoff-for-test
    python3 Tools/Build/handoff.py feedback <id|lane> good|back --note "..." [--by Andrew]        # /handoff-feedback
    python3 Tools/Build/handoff.py claim <lane> [--by Shombith]          # take a lane (the page's Claim button)
    python3 Tools/Build/handoff.py seen <id|lane>                        # a NEW handoff to you: you have read it
    python3 Tools/Build/handoff.py list [--person Shombith] [--all] [--json]
    python3 Tools/Build/handoff.py suggest [--me Shombith] [--json]      # /ship asks this when a task looks finished
    python3 Tools/Build/handoff.py keep [--lane voyages]                 # the person said "keep it": learn from that
    python3 Tools/Build/handoff.py import actions.json                   # the Swim Lanes page's clicks, into files
    python3 Tools/Build/handoff.py skills [--check]                      # write the /handoff-to-<person> skills
    python3 Tools/Build/handoff.py --self-test

What a handoff is (Shombith, 2026-11-13). A swim lane (/swimlanes: a vessel, game, app-shell section or system) is
held by whoever has unmerged work in it. When that work is done for now, its person hands the lane on:

  to <person>   the lane is that person's: it shows on THEIR board as NEW until they read it (`seen`) or push work in
                it, and it counts as theirs (occupied) for the approvals collision check.
  open          the lane goes back to the open list, with a note on where the work stands and the branch to start from.
  test          the lane goes to the tester (Docs/Handoffs/config.json `testers`: Andrew). The tester answers with
                `feedback good` (good to go: the lane opens, marked tested) or `feedback back` (it goes back to the open
                list with the tester's note at the top of its work).
  claim         a person takes a lane before pushing anything (the page's Claim button). Lapses after the window.

THE FILES. One small JSON per handoff, Docs/Handoffs/<id>.json, and one per answer, <id>.<stamp>.<event>.json, committed
on the branch that makes them, so they land with the work and never conflict. `list` reads them from the working tree,
bleeding-edge and every branch pushed in the last 60 days, exactly as approvals.py reads Docs/Approvals.

LEARNING WHEN TO ASK. Every handoff and every "keep it" records the signals the session saw (lane kind, editor hand
tests added, a PR, the lane's owner). `suggest` ranks the three choices from what this person chose before under the
same signals, and says whether to ASK (they usually hand off here) or only MENTION it (they usually keep going).

A READER except for the commands that write a handoff file. Its numbers come from git and Docs/TEAM.json.
"""
import argparse, collections, datetime, hashlib, importlib.util, json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DIR = 'Docs/Handoffs'
CONFIG = DIR + '/config.json'
BASE = 'origin/bleeding-edge'
KINDS = ('to', 'open', 'test', 'claim', 'keep')
EVENTS = ('seen', 'feedback')
ID_RE = re.compile(r'^H-\d{8}-[a-z0-9-]+-[0-9a-f]{6}$')
CLAIM_DAYS = 7
SKILL_DIR = '.claude/skills'
GENERATED_MARK = '<!-- GENERATED by Tools/Build/handoff.py skills; edit the template there, not this file. -->'


def repo_root():
    r = subprocess.run(['git', 'rev-parse', '--show-toplevel'], cwd=HERE, capture_output=True, text=True)
    return r.stdout.strip() or os.path.abspath(os.path.join(HERE, '..', '..'))


def git(*a, cwd):
    r = subprocess.run(['git'] + list(a), cwd=cwd, capture_output=True, text=True, encoding='utf-8', errors='replace')
    return r.stdout if r.returncode == 0 else ''


def load_module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def approvals(root):
    return load_module('approvals', os.path.join(root, 'Tools', 'Build', 'approvals.py'))


def now_utc():
    return datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0)


def config(root):
    try:
        return json.load(open(os.path.join(root, CONFIG), encoding='utf-8'))
    except (OSError, ValueError):
        return {'testers': ['Andrew']}


def write_json(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        json.dump(data, fh, indent=2, ensure_ascii=False)
        fh.write('\n')


def slug(text, n=30):
    return re.sub(r'[^a-z0-9]+', '-', (text or '').lower()).strip('-')[:n].rstrip('-') or 'lane'


def make_id(kind, lane, by, when):
    h = hashlib.sha1(f'{kind}|{lane}|{by}|{when.isoformat()}'.encode('utf-8')).hexdigest()[:6]
    return f'H-{when.strftime("%Y%m%d")}-{slug(lane)}-{h}'


# --- people and lanes -----------------------------------------------------------------------------------------------

class People:
    """Docs/TEAM.json through approvals.py's resolver: the one place a name becomes a person."""
    def __init__(self, root):
        self.root = root
        try:
            self.ap = approvals(root)
            wwh, _ = self.ap.tools(root)
            self.team = wwh.Team.load(root)
        except Exception:                            # tests and a moved tool: names pass through as written
            self.ap, self.team = None, None

    def names(self, confirmed_only=False):
        if not self.team:
            return []
        return [p['name'] for p in self.team.data.get('people', []) if p.get('confirmed') or not confirmed_only]

    def resolve(self, text):
        if not text:
            return None
        if self.ap and self.team:
            who = self.ap.person_of(self.team, text)
            if who:
                return who
        for n in self.names():
            if n.lower() == text.strip().lower():
                return n
        return None

    def me(self, given=None):
        if given:
            who = self.resolve(given)
            if not who:
                raise SystemExit(f'"{given}" is not a person in Docs/TEAM.json (names: {", ".join(self.names())})')
            return who
        if self.ap and self.team:
            try:
                return self.ap.me_of(self.team, self.root, None)
            except SystemExit:
                return None
        return None


def lanes_of(root):
    sw = load_module('swimlanes', os.path.join(root, '.claude', 'skills', 'swimlanes', 'swimlanes.py'))
    catalog = json.load(open(sw.CATALOG, encoding='utf-8'))
    return sw, sw.load_lanes(root, catalog)


def find_lane(lanes, text):
    t = (text or '').strip().lower()
    for ln in lanes:
        if t in (ln.key.lower(), ln.name.lower()):
            return ln
    hits = [ln for ln in lanes if t and (t in ln.key.lower() or t in ln.name.lower())]
    return hits[0] if len(hits) == 1 else None


def branch_lane(root, lanes):
    """The lane this branch's change is most about (approvals.lane_hits over the diff from bleeding-edge)."""
    ap = approvals(root)
    files = ap.changed_files(root, BASE) if git('rev-parse', '--verify', '-q', BASE, cwd=root).strip() else []
    hits = ap.lane_hits(files, lanes)
    if not hits:
        return None, files
    key = max(hits, key=lambda k: len(hits[k]))
    return next(ln for ln in lanes if ln.key == key), files


def resolve_lane(root, text):
    _, lanes = lanes_of(root)
    if text:
        ln = find_lane(lanes, text)
        if not ln:
            raise SystemExit(f'no lane "{text}". Lanes: ' + ', '.join(sorted(l.key for l in lanes)))
        return ln
    ln, files = branch_lane(root, lanes)
    if not ln:
        raise SystemExit('this branch changes no lane (' + (f'{len(files)} files, none in a lane' if files else 'no changes from bleeding-edge')
                         + '): name one with --lane <key> (`swimlanes.py --json` lists them)')
    return ln


# --- signals: what a session sees when a task looks finished ----------------------------------------------------------

def signals(root, lane_kind, branch):
    diff = git('diff', f'{BASE}...HEAD', '--', 'Docs/UNITY_VERIFICATION_CHECKLIST.md', cwd=root)
    hand_tests = sum(1 for l in diff.splitlines() if l.startswith('+') and 'NOT EDITOR-VERIFIED' in l)
    merged = bool(branch) and bool(git('rev-parse', '--verify', '-q', BASE, cwd=root).strip()) and \
        subprocess.run(['git', 'merge-base', '--is-ancestor', 'HEAD', BASE], cwd=root).returncode == 0
    return {'laneKind': lane_kind, 'handTests': hand_tests > 0, 'merged': merged}


# --- write ----------------------------------------------------------------------------------------------------------

def record(root, kind, lane, by, to=None, note='', what='', branch=None, pr=None, sig=None, when=None, source='cli', brief=None):
    when = when or now_utc()
    rid = make_id(kind, lane.key, by, when)
    data = {k: v for k, v in {
        'id': rid, 'kind': kind, 'lane': lane.key, 'laneName': lane.name, 'laneKind': lane.kind,
        'by': by, 'to': to, 'on': when.isoformat(), 'branch': branch, 'pr': pr, 'note': note, 'what': what,
        'signals': sig, 'source': source, 'brief': brief}.items() if v not in (None, '', {})}
    write_json(os.path.join(root, DIR, rid + '.json'), data)
    return data


def answer(root, hid, event, by, verdict=None, note='', when=None, source='cli'):
    when = when or now_utc()
    data = {k: v for k, v in {'id': hid, 'event': event, 'by': by, 'on': when.isoformat(), 'verdict': verdict,
                              'note': note, 'source': source}.items() if v not in (None, '')}
    write_json(os.path.join(root, DIR, f'{hid}.{when.strftime("%Y%m%dT%H%M%S")}.{event}.json'), data)
    return data


# --- read -----------------------------------------------------------------------------------------------------------

def recent_refs(root, days):
    cutoff = now_utc() - datetime.timedelta(days=days)
    out = []
    for line in git('for-each-ref', '--sort=-committerdate', '--format=%(refname:short)\t%(committerdate:iso-strict)',
                    'refs/remotes/origin', cwd=root).splitlines():
        ref, date = (line.split('\t') + [''])[:2]
        if ref in ('origin/HEAD', 'origin', BASE):
            continue
        try:
            if datetime.datetime.fromisoformat(date.replace('Z', '+00:00')) < cutoff:
                break
        except ValueError:
            continue
        out.append(ref)
    return out


def read_all(root, days=60, refs=True):
    """Every handoff and answer under Docs/Handoffs: the working tree, bleeding-edge, then every branch pushed in the
    last `days` (one file is one record wherever it is; a handoff's `where` is the first place it was found)."""
    recs, evs, seen = {}, {}, set()

    def take(name, text, where):
        base = os.path.basename(name)
        if not base.startswith('H-') or not base.endswith('.json'):
            return
        try:
            d = json.loads(text)
        except ValueError:
            return
        if base[:-5] == d.get('id') and d.get('kind') in KINDS:
            if d['id'] not in recs:
                recs[d['id']] = dict(d, where=where)
        elif d.get('event') in EVENTS:
            evs.setdefault(base, d)

    full = os.path.join(root, DIR)
    if os.path.isdir(full):
        for f in sorted(os.listdir(full)):
            try:
                take(f, open(os.path.join(full, f), encoding='utf-8').read(), 'local')
            except OSError:
                pass
    if refs:
        order = ([BASE] if git('rev-parse', '--verify', '-q', BASE, cwd=root).strip() else []) + recent_refs(root, days)
        blobs = []
        for ref in order:
            for line in git('ls-tree', '-r', ref, '--', DIR + '/', cwd=root).splitlines():
                meta, _, name = line.partition('\t')
                parts = meta.split()
                if len(parts) < 3 or parts[2] in seen or not os.path.basename(name).startswith('H-'):
                    continue
                seen.add(parts[2])
                blobs.append((parts[2], name, 'landed' if ref == BASE else ref[len('origin/'):]))
        if blobs:
            r = subprocess.run(['git', 'cat-file', '--batch'], cwd=root, capture_output=True,
                               input=''.join(b[0] + '\n' for b in blobs).encode('ascii'))
            out, i = r.stdout, 0
            for sha, name, where in blobs:
                nl = out.find(b'\n', i)
                if nl < 0:
                    break
                hdr = out[i:nl].split()
                if len(hdr) < 3 or hdr[1] == b'missing':
                    i = nl + 1
                    continue
                size = int(hdr[2])
                take(name, out[nl + 1:nl + 1 + size].decode('utf-8', 'replace'), where)
                i = nl + 1 + size + 1
    by_id = collections.defaultdict(list)
    for e in evs.values():
        by_id[e['id']].append(e)
    for rid, r in recs.items():
        r['events'] = sorted(by_id.get(rid, []), key=lambda e: e['on'])
    return list(recs.values())


def status(r, now=None):
    """new | taken | open | testing | passed | back | claimed | lapsed | kept"""
    now = now or now_utc()
    ev = r.get('events', [])
    if r['kind'] == 'keep':
        return 'kept'
    if r['kind'] == 'claim':
        on = datetime.datetime.fromisoformat(r['on'])
        return 'claimed' if now - on <= datetime.timedelta(days=CLAIM_DAYS) else 'lapsed'
    if r['kind'] == 'to':
        return 'taken' if any(e['event'] == 'seen' and e['by'] == r.get('to') for e in ev) else 'new'
    if r['kind'] == 'test':
        fb = [e for e in ev if e['event'] == 'feedback']
        if fb:
            return 'passed' if fb[-1].get('verdict') == 'good' else 'back'
        return 'testing'
    return 'open'


def current(recs, now=None):
    """lane key -> the lane's latest handoff (keep records never change a lane), with its status."""
    out = {}
    for r in sorted(recs, key=lambda r: r['on']):
        if r['kind'] == 'keep':
            continue
        st = status(r, now)
        if st == 'lapsed':
            continue
        out[r['lane']] = dict(r, status=st)
    return out


def holder(h):
    """Who holds a lane by its handoff, for occupancy: the recipient, the tester, the claimer; nobody when open."""
    if h['status'] in ('new', 'taken'):
        return h.get('to')
    if h['status'] == 'testing':
        return h.get('to')
    if h['status'] == 'claimed':
        return h.get('by')
    return None


# --- suggest: learn when this person hands off -----------------------------------------------------------------------

def suggest(recs, me, lane, sig, testers):
    """Rank to / open / test from this person's own history under matching signals; ASK when they usually hand off."""
    mine = [r for r in recs if r.get('by') == me and r['kind'] in ('to', 'open', 'test', 'keep')]

    def score(r):
        s = r.get('signals') or {}
        return (r.get('lane') == lane.key) * 3 + (s.get('laneKind') == sig['laneKind']) + \
            (s.get('handTests') == sig['handTests']) * 2 + (s.get('merged') == sig['merged'])
    near = sorted(mine, key=score, reverse=True)[:12]
    votes = collections.Counter()
    for r in near:
        votes[(r['kind'], r.get('to') if r['kind'] == 'to' else None)] += 1 + score(r)
    reasons, prior = [], collections.Counter()
    if sig['handTests']:
        prior[('test', None)] += 4
        reasons.append('this branch added editor hand tests that nobody has run: a tester can run them')
    if sig['merged']:
        prior[('open', None)] += 2
        reasons.append('the work is merged into bleeding-edge')
    owner = (lane.note or '')
    named = re.findall(r"\b(Garrett|Caleb|Shombith|Yash|Iggy|Andrew)'s\b|\b(Garrett|Caleb|Shombith|Yash)\b", owner)
    for a, b in named:
        p = a or b
        if p and p != me:
            prior[('to', p)] += 2
            reasons.append(f'the lane names {p} as its owner')
            break
    prior[('open', None)] += 1
    total = votes + prior
    ranked = [k for k, _ in total.most_common()]
    keeps = sum(1 for r in near if r['kind'] == 'keep')
    hands = len(near) - keeps
    ask = len(near) < 3 or hands >= keeps                       # little history: ask; mostly kept going: mention only
    if near:
        reasons.append(f'you handed off {hands} and kept {keeps} of your {len(near)} closest past cases')
    def label(k):
        kind, to = k
        return {'to': f'/handoff-to-{(to or "").lower()}', 'open': '/handoff-open',
                'test': f'/handoff-for-test (goes to {testers[0] if testers else "the tester"})', 'keep': 'keep it'}[kind]
    return {'lane': lane.key, 'laneName': lane.name, 'signals': sig, 'ask': ask,
            'ranked': [{'kind': k[0], 'to': k[1], 'skill': label(k)} for k in ranked if k[0] != 'keep'][:3],
            'reasons': reasons}


