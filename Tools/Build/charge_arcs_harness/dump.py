#!/usr/bin/env python3
"""
Dumps what the charge arcs harness runs the SHIPPED C# on, as Unity imports it: the Charge crystal
(ChargeCrystalExport1_7-11-25.fbx) and the omni body (OmniCrystalExport1_8-21-25.fbx), x negated, one vertex per
polygon corner (the importer splits these flat-shaded models by normal), polygons fanned into triangles.
Writes meshes.json next to this file (gitignored scratch, regenerated by run.sh).
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "Tools", "Build"))
import author_omni_crystal_triangles as A   # noqa: E402

CHARGE_FBX = "Assets/_Models/ChargeCrystalExport1_7-11-25.fbx"


def unity_mesh(path):
    verts, faces = A._load(path)
    P, T = [], []
    for f in faces:
        base = len(P)
        P += [(-verts[i][0], verts[i][1], verts[i][2]) for i in f]
        for k in range(1, len(f) - 1):
            T += [base, base + k + 1, base + k]   # x negated flips the winding back to Unity's
    return {"positions": P, "triangles": T}


out = {"charge": unity_mesh(CHARGE_FBX), "omni": unity_mesh(A.OMNI_FBX)}
json.dump(out, open(os.path.join(HERE, "meshes.json"), "w"))
print("meshes: " + ", ".join(f"{k} {len(v['positions'])} vertices, {len(v['triangles']) // 3} triangles" for k, v in out.items()))
