# ── asset reading ────────────────────────────────────────────────────────────────────────────

_GUIDS = None


def guid_index():
    global _GUIDS
    if _GUIDS is None:
        _GUIDS = {}
        for meta in (ROOT / "Assets").rglob("*.meta"):
            try:
                with open(meta, encoding="utf-8", errors="ignore") as fh:
                    head = fh.read(400)
            except OSError:
                continue
            m = re.search(r"^guid: ([0-9a-f]{32})", head, re.M)
            if m:
                _GUIDS.setdefault(m.group(1), []).append(meta.with_suffix(""))
    return _GUIDS


def asset(guid):
    """The ONE asset whose .meta owns this guid (Docs/VESSEL_CONSTRUCTION.md §2: never take the
    first grep hit - a .meta can remap a guid it does not own)."""
    paths = guid_index().get(guid) or []
    assert len(paths) == 1, f"guid {guid} is owned by {len(paths)} .meta files: {paths}"
    return paths[0]


def read(p):
    return Path(p).read_text(encoding="utf-8", errors="ignore")


def docs(text):
    """{fileID: (class_id, body)} for every document in a Unity YAML file."""
    out = {}
    for m in re.finditer(r"^--- !u!(\d+) &(-?\d+)[^\n]*\n(.*?)(?=^--- !u!|\Z)", text, re.M | re.S):
        out[m.group(2)] = (int(m.group(1)), m.group(3))
    return out


def script_name(body):
    m = re.search(r"m_Script: \{fileID: 11500000, guid: ([0-9a-f]{32})", body)
    if not m:
        return None
    return asset(m.group(1)).stem


_SCALAR = re.compile(r"^-?\d+(\.\d+)?([eE][-+]?\d+)?$")


def _vec(s):
    m = re.match(r"\{x: ([^,]+), y: ([^,]+), z: ([^,}]+)(?:, w: ([^}]+))?\}", s.strip())
    if not m:
        return None
    return [float(v) for v in m.groups() if v is not None]


def fields(body):
    """The component's serialized VALUE fields (numbers, bools-as-ints, vectors, vector/number
    lists). Object references are skipped: the harness never follows one except a child
    generator, which `generator_node` resolves itself."""
    out, lines, i = {}, body.split("\n"), 0
    skip = {"m_ObjectHideFlags", "m_CorrespondingSourceObject", "m_PrefabInstance", "m_PrefabAsset",
            "m_GameObject", "m_Enabled", "m_EditorHideFlags", "m_Script", "m_Name", "m_EditorClassIdentifier"}
    while i < len(lines):
        m = re.match(r"^  ([A-Za-z_]\w*):(.*)$", lines[i])
        i += 1
        if not m or m.group(1) in skip:
            continue
        key, rest = m.group(1), m.group(2).strip()
        if rest == "":
            items = []
            while i < len(lines) and lines[i].startswith("  - "):
                items.append(lines[i][4:].strip())
                i += 1
            vals = [_vec(s) for s in items]
            if items and all(v is not None for v in vals):
                out[key] = vals
            elif items and all(_SCALAR.match(s) for s in items):
                out[key] = [float(s) for s in items]
            continue
        if rest == "[]":
            continue  # an empty list keeps the C# default, which is what Unity does too
        if _SCALAR.match(rest) or re.match(r"^[0-9a-f]+$", rest):
            # Kept as the RAW TOKEN: Unity writes a bool/int/float ARRAY as one hex blob
            # (`bandDomains: 03000000...`), which int() would silently mangle (it drops the
            # leading zero). The harness converts by the C# field's own type.
            out[key] = rest
        elif rest.startswith("{x:"):
            v = _vec(rest)
            if v is not None and len(v) == 3:
                out[key] = v
    return out


def prefab_generator(prefab_path, file_id=None):
    """(component body, script name, doc map) of a prefab's generator component - the one whose
    script name starts with Spawnable or ends in Generator, or the named fileID."""
    d = docs(read(prefab_path))
    if file_id is not None:
        cls, body = d[str(file_id)]
        return body, script_name(body), d
    for fid, (cls, body) in d.items():
        if cls != 114:
            continue
        name = script_name(body)
        if name and (name.startswith("Spawnable") or name.endswith("Generator")):
            return body, name, d
    raise AssertionError(f"{prefab_path}: no generator component")


def position_sets(body, key):
    """A List<CrystalPositionSet> (`key:` then `- positions:` blocks of vectors)."""
    m = re.search(rf"^  {key}:\n((?:  [- ].*\n)+)", body, re.M)
    if not m:
        return None
    sets = []
    for line in m.group(1).split("\n"):
        if line.startswith("  - positions:"):
            sets.append({"positions": []})
        elif sets and line.startswith("    - {x:"):
            sets[-1]["positions"].append(_vec(line[6:]))
    return sets


def generator_node(prefab_path, file_id=None, overrides=None):
    body, name, d = prefab_generator(prefab_path, file_id)
    node = {"kind": "generator", "type": name, "fields": fields(body)}
    wp = position_sets(body, "waypoints")
    if wp is not None:
        node["fields"]["waypoints"] = wp
    if overrides:
        node["fields"].update(overrides)
    m = re.search(r"^  children:\n((?:  - .*\n)+)", body, re.M)
    if m:
        kids = []
        for ref in re.findall(r"- \{fileID: (-?\d+)(?:, guid: ([0-9a-f]{32}))?", m.group(1)):
            fid, guid = ref
            if guid:
                kids.append(generator_node(asset(guid)))
            else:
                kids.append(generator_node(prefab_path, fid))
        if kids:
            node["children"] = kids
    return node


def root_scale(prefab_path):
    """localScale.x of the prefab's ROOT transform (the membrane's radius, the nucleus's scale)."""
    for fid, (cls, body) in docs(read(prefab_path)).items():
        if cls == 4 and re.search(r"m_Father: \{fileID: 0\}", body):
            m = re.search(r"m_LocalScale: \{x: ([^,]+)", body)
            return float(m.group(1)) if m else 1.0
    return 1.0


def membrane_radius(prefab_path):
    """Cell.MembraneRadius: a CapsuleMembrane's own `radius` field when it has one, else the root
    transform's scale. The capsule membrane is authored at scale 1 with radius 1200, so reading
    the scale alone silently models every forest at a cell radius of ONE unit."""
    for fid, (cls, body) in docs(read(prefab_path)).items():
        if cls == 114 and script_name(body) == "CapsuleMembrane":
            m = re.search(r"^  radius: ([\d.]+)", body, re.M)
            if m:
                return float(m.group(1))
    return root_scale(prefab_path)


def ref(body, key):
    m = re.search(rf"^  {key}: \{{fileID: -?\d+(?:, guid: ([0-9a-f]{{32}}))?", body, re.M)
    return asset(m.group(1)) if m and m.group(1) else None


