#!/usr/bin/env python3
"""Render every live arcade/arena card's BACKGROUND from its mode's own intensity-2 arena.

WHY THIS EXISTS
---------------
A card's backdrop is `SO_ArcadeGame.CardBackground`, and 22 of the 25 live cards shared four
legacy images from the retired single-player era (`Docs/HomeHub/ARCHITECTURE.md` §3.8). The
obvious fix - fly each mode and press 0 - needs the running editor, twenty-five times, and has to
be re-done by hand every time an arena changes. But an arena is DATA: the shipped generators emit
prism poses, the course generators emit gates, the spawn profile says what grows where. So the
picture can be made the way the mode preview's scale model is made (`CellMiniatureBuilder`,
`ModePreviewPlantingModel`), offline, by RUNNING that same data, and re-made whenever it moves.

WHERE EACH CARD'S GEOMETRY COMES FROM - three tiers, stated per card in the report
---------------------------------------------------------------------------------
  RUN      The shipped generator is COMPILED AND RUN (`card_art_harness/`, Roslyn + a faithful
           UnityEngine shim), with every serialized field read off the environment prefab the
           mode's intensity-2 cell config names. What is drawn is what the arena lays, prism for
           prism, in the domain and tier it lays them. (Boneyard, Swell, Wildlife cage,
           Switchyard, Skein rails, Regatta rails, Hopf, concentric shells, waypoint track.)
  COURSE   A controller-built course is generated by the shipped pure course generator at
           intensity 2 on a fixed seed (Switchback, Headlong, Redline, Regatta gates, Breakwater
           stations - the station builder is shipped code too). The SEED is the card's own; a
           live match rolls its own, so the shape is representative, not the one you will fly.
  MODEL    What only exists once a match is running - a grown forest, a court a controller
           builds, a ball - is MODELLED: the planting is drawn exactly as
           `ModePreviewPlantingModel` draws it (species counts through the profile's scale, the
           cell's planting band, volume-uniform radii), and each plant is a species GLYPH rather
           than the plant, because a grown plant's shape is emergent. Say so when you show one.

Vessels and their trails are added as STAGING on most cards (a dart plus the prism ribbon it
lays), because a card with no pilot in it reads as a level select rather than a game.

OUTPUT
------
    Assets/_Graphics/ARCADE/CardBackgrounds/<CardName>.png      (768 x 510, the plate's aspect)

then `author_card_backgrounds.py` imports each as a Sprite and rewires the card. Everything is
deterministic: the same sources give the same bytes, so `--check` re-renders and byte-compares.

    python3 Tools/Build/render_card_backgrounds.py                 # render all + import + rewire
    python3 Tools/Build/render_card_backgrounds.py Rampage Cleave  # just these cards
    python3 Tools/Build/render_card_backgrounds.py --check         # fail if any committed card is stale
    python3 Tools/Build/render_card_backgrounds.py --report        # where each card's geometry comes from
    python3 Tools/Build/render_card_backgrounds.py --sheet         # also write a labelled contact sheet

Needs a dotnet 8 SDK reachable through DOTNET_ROOT (default ~/.dotnet). A NEW MODE needs nothing
when its intensity-2 cell names an EnvironmentPrefab whose generator is in SOURCES; otherwise one
branch in recipe() and a CAMERAS row (see the /cardart skill) - never a hand-painted PNG.
"""
