def png(path, w, h, rgb):
    raw = b"".join(b"\x00" + rgb[y * w * 3:(y + 1) * w * 3] for y in range(h))

    def chunk(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    data = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))
    Path(path).write_bytes(data)


MAELSTROM = "Assets/_SO_Assets/Maelstrom/MaelstromData.asset"


def maelstrom_pool():
    """The modes Maelstrom can DRAW at INTENSITY: its IntensityTiers ladder is CUMULATIVE
    (Docs/MaelstromSystem/ARCHITECTURE.md §1.1), so every tier up to and including this one."""
    body = read(ROOT / MAELSTROM)
    stems = []
    for block in body.split("  - Intensity: ")[1:]:
        level = int(block.split("\n")[0])
        if level > INTENSITY:
            continue
        for g in re.findall(r"guid: (\w+)", block.split("Games:")[1].split("  - Intensity")[0].split("LobbySceneName")[0]):
            p = asset(g)
            stems.append(p.stem[len("ArcadeGame"):] if p.stem.startswith("ArcadeGame") else p.stem)
    return stems


def montage(images, stems, strips=5):
    """Maelstrom has no arena - it draws OTHER modes - so its card is those modes' own cards,
    cut into slanted strips: the picture says 'a different game every round'."""
    pick = [s for s in stems if s in images]
    step = max(1, len(pick) // strips)
    pick = pick[::step][:strips]
    assert pick, "Maelstrom montage: none of its pool's cards were rendered"
    out = bytearray(WIDTH * HEIGHT * 3)
    n, slant = len(pick), 0.28
    for y in range(HEIGHT):
        for x in range(WIDTH):
            u = (x + (HEIGHT - y) * slant) / (WIDTH + HEIGHT * slant) * n
            k = min(n - 1, int(u))
            edge = u - int(u)
            o = (y * WIDTH + x) * 3
            src = images[pick[k]]
            if 0 < k and edge < 0.012 * n:
                out[o:o + 3] = bytes((235, 240, 255))   # a hairline seam between rounds
            else:
                out[o:o + 3] = src[o:o + 3]
    return bytes(out), pick


def contact_sheet(path, images, cols=4, down=2):
    """Tile rendered cards (name -> rgb bytes, in roster order) at 1/down scale into one PNG, so a
    whole roster is judged at once - and at close to the size a card is SEEN, which is the size a
    card must be judged at (Docs/PALETTE.md §4.3)."""
    w, h = WIDTH // down, HEIGHT // down
    names = list(images)
    rows = (len(names) + cols - 1) // cols
    W, H = cols * w + (cols + 1) * 4, rows * h + (rows + 1) * 4
    out = bytearray(b"\x10\x10\x14" * (W * H))
    for k, name in enumerate(names):
        src = images[name]
        ox, oy = 4 + (k % cols) * (w + 4), 4 + (k // cols) * (h + 4)
        for y in range(h):
            for x in range(w):
                r = g = b = 0
                for j in range(down):
                    base = ((y * down + j) * WIDTH + x * down) * 3
                    for i in range(down):
                        r += src[base + 3 * i]; g += src[base + 3 * i + 1]; b += src[base + 3 * i + 2]
                n = down * down
                o = ((oy + y) * W + ox + x) * 3
                out[o] = r // n; out[o + 1] = g // n; out[o + 2] = b // n
    png(path, W, H, bytes(out))


def source_hash():
    h = hashlib.sha256()
    for rel in SOURCES + HASHED_ONLY + HARNESS_FILES + ["Tools/Build/render_card_backgrounds.py"]:
        h.update(rel.encode())
        h.update((ROOT / rel).read_bytes())
    return h.hexdigest()


def build_spec(only=None):
    pal = palette()
    ends = end_conditions()
    cards, report = [], []
    for stem, path in roster():
        if (only and stem not in only) or stem in HAND_CAPTURED:
            continue
        r = recipe(stem, path, pal, ends)
        if r["tier"] == "MONTAGE":
            report.append((stem, r["tier"], None, None, None))
            continue
        card = {"name": stem, "width": WIDTH, "height": HEIGHT, "supersample": SUPERSAMPLE,
                "camera": r["camera"], "look": r["look"], "layers": r["layers"]}
        if r["stage"]:
            card["stage"] = r["stage"]
        cards.append(card)
        report.append((stem, r["tier"], r["cell"], r["env"], r["track"]))
    return {"palette": pal, "cards": cards}, report


def run(spec, out_dir, names):
    spec_path = Path(out_dir) / "spec.json"
    spec_path.write_text(json.dumps(spec))
    env = dict(os.environ)
    env.setdefault("DOTNET_ROOT", str(Path.home() / ".dotnet"))
    res = subprocess.run(["bash", str(HARNESS), str(spec_path), str(out_dir)] + names, env=env)
    if res.returncode != 0:
        sys.exit(f"card-art harness failed ({res.returncode})")
    return json.loads((Path(out_dir) / "stats.json").read_text())


def main(argv):
    if "--list-sources" in argv:
        print("\n".join(SOURCES))
        return 0
    check = "--check" in argv
    names = [a for a in argv if not a.startswith("--")]
    wanted = set(names) if names else None
    if wanted and "Maelstrom" in wanted:
        wanted |= set(maelstrom_pool())   # its card is built FROM those cards
    spec, report = build_spec(wanted)
    if "--report" in argv:
        for stem, tier, cell, envp, track in report:
            print(f"  {stem:20s} {tier or '-':7s} cell={cell}  env={envp}  track={track}")
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        stats = run(spec, tmp, sorted(wanted) if wanted else [])
        by_name = {s["name"]: s for s in stats}
        stale = []
        OUT_DIR.mkdir(parents=True, exist_ok=True)
        images = {c["name"]: (Path(tmp) / f"{c['name']}.rgb").read_bytes() for c in spec["cards"]}
        for stem, tier, *_ in report:
            if tier == "MONTAGE":
                images[stem], pick = montage(images, maelstrom_pool())
                by_name[stem] = {"name": stem, "montage": pick}
        if "--sheet" in argv:
            sheet = Path(os.environ.get("CARD_SHEET", Path(tempfile.gettempdir()) / "card_backgrounds_sheet.png"))
            contact_sheet(sheet, {s: images[s] for s, *_ in report if s in images})
            print(f"contact sheet: {sheet} (roster order, {len(images)} cards)")
        for name in [s for s, *_ in report if (not names or s in names)]:
            rgb = images[name]
            target = OUT_DIR / f"{name}.png"
            if check:
                fresh = Path(tmp) / f"{name}.png"
                png(fresh, WIDTH, HEIGHT, rgb)
                if not target.exists() or target.read_bytes() != fresh.read_bytes():
                    stale.append(name)
            else:
                png(target, WIDTH, HEIGHT, rgb)
        if check:
            if stale:
                print(f"render_card_backgrounds --check: STALE {stale} - re-run without --check")
                return 1
            print(f"render_card_backgrounds --check: OK {len([s for s, *_ in report if (not names or s in names)])} cards match their sources")
            return 0
    manifest = {"source_hash": source_hash(), "intensity": INTENSITY, "size": [WIDTH, HEIGHT],
                "cards": {stem: {"tier": tier, "cell": cell, "environment": envp, "track": track,
                                 **{k: v for k, v in by_name.get(stem, {}).items() if k != "name"}}
                          for stem, tier, cell, envp, track in report}}
    if not names:
        MANIFEST.write_text(json.dumps(manifest, indent=1, sort_keys=True) + "\n")
    for stem, tier, cell, envp, track in report:
        s = by_name.get(stem, {})
        print(f"  {stem:20s} {tier or '-':7s} {s.get('prisms', 0):6d} prisms  cell={cell} env={envp}")
    return subprocess.run([sys.executable, str(ROOT / "Tools/Build/author_card_backgrounds.py")]).returncode


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
