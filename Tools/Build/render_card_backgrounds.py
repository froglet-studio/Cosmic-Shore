def domain_signal(pal, dom, gain=1.0):
    """The domain's UI signal colour (rim with its brightest channel driven to 1)."""
    rim = pal["domains"][str(dom)]["plain"][1]
    peak = max(rim) or 1.0
    return [c / peak * gain for c in rim]


# ── modelled layers (MODEL tier) ─────────────────────────────────────────────────────────────

class Rng:
    """xorshift32 - specified, so a model draws the same thing on every machine and Python."""

    def __init__(self, seed):
        self.s = (seed & 0xFFFFFFFF) or 0x9E3779B9

    def u(self):
        s = self.s
        s ^= (s << 13) & 0xFFFFFFFF
        s ^= s >> 17
        s ^= (s << 5) & 0xFFFFFFFF
        self.s = s
        return s / 4294967296.0

    def range(self, a, b):
        return a + (b - a) * self.u()

    def unit(self):
        z = self.range(-1, 1)
        t = self.range(0, 2 * math.pi)
        r = math.sqrt(max(0.0, 1 - z * z))
        return [r * math.cos(t), z, r * math.sin(t)]


def stable_seed(key):
    """ModePreviewPlantingModel.StableSeed's recurrence, masked to a non-negative int32 so it is a
    valid seed on both sides of the harness boundary."""
    h = 17
    for c in key:
        h = (h * 31 + ord(c)) & 0xFFFFFFFF
    return h & 0x7FFFFFFF


def v_add(a, b): return [a[0] + b[0], a[1] + b[1], a[2] + b[2]]
def v_sub(a, b): return [a[0] - b[0], a[1] - b[1], a[2] - b[2]]
def v_mul(a, k): return [a[0] * k, a[1] * k, a[2] * k]
def v_dot(a, b): return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]
def v_cross(a, b): return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]


def v_norm(a):
    l = math.sqrt(v_dot(a, a))
    return v_mul(a, 1 / l) if l > 1e-12 else [0.0, 0.0, 1.0]


def basis_quat(x, y, z):
    """Quaternion (x,y,z,w) of the rotation whose columns are the given orthonormal axes."""
    m00, m01, m02 = x[0], y[0], z[0]
    m10, m11, m12 = x[1], y[1], z[1]
    m20, m21, m22 = x[2], y[2], z[2]
    tr = m00 + m11 + m22
    if tr > 0:
        s = math.sqrt(tr + 1) * 2
        return [(m21 - m12) / s, (m02 - m20) / s, (m10 - m01) / s, 0.25 * s]
    if m00 > m11 and m00 > m22:
        s = math.sqrt(1 + m00 - m11 - m22) * 2
        return [0.25 * s, (m01 + m10) / s, (m02 + m20) / s, (m21 - m12) / s]
    if m11 > m22:
        s = math.sqrt(1 + m11 - m00 - m22) * 2
        return [(m01 + m10) / s, 0.25 * s, (m12 + m21) / s, (m02 - m20) / s]
    s = math.sqrt(1 + m22 - m00 - m11) * 2
    return [(m02 + m20) / s, (m12 + m21) / s, 0.25 * s, (m10 - m01) / s]


def look_quat(fwd, up=(0, 1, 0)):
    z = v_norm(fwd)
    x = v_cross(list(up), z)
    if v_dot(x, x) < 1e-10:
        x = v_cross([1, 0, 0], z)
    x = v_norm(x)
    y = v_cross(z, x)
    return basis_quat(x, y, z)


def prism(pos, fwd, up, scale, dom, kind=PLAIN):
    return list(pos) + look_quat(fwd, up) + list(scale) + [dom, kind]


