def vessels(spec):
    out = []
    for dom, r, tilt, a0, sweep in spec:
        v = {"domain": dom, "sweep": sweep}
        if r is not None: v["r"] = r
        if tilt is not None: v["tilt"] = tilt
        if a0 is not None: v["a0"] = a0
        out.append(v)
    return out


