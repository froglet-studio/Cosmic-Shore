def arena_for(card_path):
    """(cell config, track spawnable or None) the mode builds at INTENSITY."""
    body = read(card_path)
    scene = re.search(r"^  SceneName: (.*)$", body, re.M).group(1).strip()
    mode = int(re.search(r"^  Mode: (\d+)", body, re.M).group(1))
    configs, choice = scene_cell_configs(scene)
    track = None
    pdef = preview_definition(mode)
    if pdef:
        track = list_at(pdef, "TrackSpawnablesByIntensity", INTENSITY - 1)
    if configs:
        # IntensityWise (1) picks by intensity; a single-config cell is that config.
        cfg = configs[min(INTENSITY - 1, len(configs) - 1)] if choice == 1 else configs[0]
        return cfg, track, mode
    if pdef:
        cfg = list_at(pdef, "PreviewCellsByIntensity", INTENSITY - 1) or ref(pdef, "PreviewCell")
        return cfg, track, mode
    return None, track, mode


