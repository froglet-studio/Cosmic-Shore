def domain_signal(pal, dom, gain=1.0):
    """The domain's UI signal colour (rim with its brightest channel driven to 1)."""
    rim = pal["domains"][str(dom)]["plain"][1]
    peak = max(rim) or 1.0
    return [c / peak * gain for c in rim]


