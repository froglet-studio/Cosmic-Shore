#!/usr/bin/env python3
"""Bake the Mandelbulb flora's spherical-harmonic surface basis.

The fractal is evaluated EXACTLY ONCE, here. The game never touches one: the shipped
table is four SH coefficient vectors per element (a mean plus three modes), which
`MandelbulbSurface.Reconstruct` turns into a height field and `MandelbulbSurface.Growth`
walks. A whole plant is therefore the shared basis plus THREE FLOATS.

Why this shape, in three measurements (each reproducible with --measure):

  * The distance estimator's GRADIENT is unusable as an orientation at prism scale --
    48 degrees of swing between surface points 0.013 apart on a unit bulb -- so curves
    traced against it die on any turn gate. A height field's normal is analytic, and its
    smoothing is an explicit dial.
  * The fit does NOT converge and does not need to. R(theta,phi) has cliffs where the
    march jumps sheets. Degree 16 lands at R^2 0.90-0.97 per element, degree 12 lands
    at 0.11 for the power-12 bulb (its structure sits exactly at l=12 and aliases), and
    degree 24 buys 0.9926 for four times the table. 16 is the knee.
  * Three modes explain the response to the Julia constant. They ARE dR/dc, so FOUR
    marches recover what fifty-six do.

Two normalisations happen in the bake and nowhere else, because both are pure scales in
coefficient space: the mean radius is driven to exactly 1 (so a species' RadiusMin/Max
mean the same thing at every fractal order), and the non-DC band is multiplied by a
per-element RELIEF gain. The relief gain is not decoration -- MEASURED, the true outer
surface's radial relief is 6.7% of the radius at power 12 and 23% at power 3, and at the
bottom of that range the plant is a ball of curves however the growth rule is tuned. The
gains below are solved so every element lands at a relief standard deviation of 0.22.

  bake_mandelbulb_surface.py            # rewrite the shipped table
  bake_mandelbulb_surface.py --check    # fail the build if the shipped table has drifted
"""
import argparse
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HARNESS = os.path.join(ROOT, "Tools", "Build", "mandelbulb_surface_harness", "run.sh")
TABLE = os.path.join(ROOT, "Assets", "_Scripts", "Controller", "Environment",
                     "FloraAndFauna", "MandelbulbSurfaceTables.cs")

DEGREE = 16
GRID_W, GRID_H = 256, 128
ITERATIONS = 12
BAILOUT = 2.0
DELTA = 0.03          # the Julia offset each mode is the response to

# element -> (fractal order, smoothing sigma in radians, relief gain)
#
# sigma tracks the ORDER: the features of a power-n bulb are ~2*pi/n apart, so a fixed
# sigma either leaves the power-12 field with most of its energy above degree 16 (it did:
# R^2 0.11) or flattens the power-3 field that degree 16 can represent outright.
ELEMENTS = {
    "Charge": (8,  0.040, 1.95),
    "Mass":   (5,  0.028, 1.31),
    "Space":  (3,  0.020, 1.00),
    "Time":   (12, 0.055, 3.30),
}
ORDER = ["Charge", "Mass", "Space", "Time"]


def bake(power, sigma, relief):
    out = subprocess.run(
        [HARNESS, "bake", str(power), "0", "0", "0", str(DELTA),
         str(GRID_W), str(GRID_H), str(DEGREE), str(ITERATIONS), str(BAILOUT),
         str(sigma), str(relief), "1"],
        capture_output=True, text=True, check=True).stdout
    rows = {}
    for line in out.splitlines():
        t = line.split()
        if not t:
            continue
        rows[t[0]] = t[1:]
    for key in ("mean", "mode0", "mode1", "mode2", "fiterror", "recon"):
        if key not in rows:
            raise SystemExit(f"harness produced no '{key}' row; output was:\n{out}")
    return rows


def emit(results):
    n = (DEGREE + 1) ** 2
    lines = []
    w = lines.append
    w("// GENERATED by Tools/Build/bake_mandelbulb_surface.py -- do not edit by hand.")
    w("// Re-bake with that script; `--check` fails the build on any hand edit.")
    w("//")
    w("// One element per block: a MEAN surface and three MODES. A plant is this basis plus")
    w("// three weights in [-1, 1], composed in coefficient space (MandelbulbSurface.Compose)")
    w("// and reconstructed once per (element, weights). The modes are dR/dc for the Julia")
    w("// constant of the same triplex map, so moving the weights moves the whole plant")
    w("// through a family of real fractal surfaces rather than through an invented blend.")
    w("namespace CosmicShore.Gameplay")
    w("{")
    w("    public static class MandelbulbSurfaceTables")
    w("    {")
    w(f"        public const int Degree = {DEGREE};")
    w(f"        public const int CoefficientCount = {n};")
    w("")
    w("        /// <summary>The Julia offset each mode is the first-order response to. A weight")
    w("        /// of 1 IS a step of this much along that axis of c.</summary>")
    w(f"        public const float ModeDelta = {DELTA}f;")
    w("")
    for name in ORDER:
        power, sigma, relief = ELEMENTS[name]
        r = results[name]
        rms, r2 = r["fiterror"][0], r["fiterror"][1]
        rmin, rmax, rmean, rstd = r["recon"]
        w(f"        // {name}: order {power}, smoothing sigma {sigma}, relief x{relief}.")
        w(f"        //   fit rms {float(rms):.5f}, R^2 {float(r2):.4f}")
        w(f"        //   surface r {float(rmin):.4f}..{float(rmax):.4f}, "
          f"mean {float(rmean):.4f}, relief sd {float(rstd):.4f}")
        w(f"        public static readonly float[][] {name} =")
        w("        {")
        for key in ("mean", "mode0", "mode1", "mode2"):
            vals = r[key]
            w("            new float[]")
            w("            {")
            for i in range(0, len(vals), 6):
                chunk = ", ".join(f"{float(v):.9g}f" for v in vals[i:i + 6])
                w(f"                {chunk},")
            w("            },")
        w("        };")
        w("")
    w("        /// <summary>Basis for an element, falling back to Charge (the classic bulb) for")
    w("        /// a plant with no element -- a toy clone or a microscene release.</summary>")
    w("        public static float[][] For(CosmicShore.Data.Element element)")
    w("        {")
    w("            switch (element)")
    w("            {")
    for name in ORDER:
        w(f"                case CosmicShore.Data.Element.{name}: return {name};")
    w("                default: return Charge;")
    w("            }")
    w("        }")
    w("    }")
    w("}")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="fail if the shipped table differs from a fresh bake")
    args = ap.parse_args()

    if not os.access(HARNESS, os.X_OK):
        raise SystemExit(f"harness not executable: {HARNESS}")

    results = {}
    for name in ORDER:
        power, sigma, relief = ELEMENTS[name]
        print(f"  baking {name:6s} order {power:2d} sigma {sigma} relief {relief} ...",
              end="", flush=True)
        results[name] = bake(power, sigma, relief)
        r2 = float(results[name]["fiterror"][1])
        sd = float(results[name]["recon"][3])
        print(f" R^2 {r2:.4f}  relief sd {sd:.4f}")
        if r2 < 0.85:
            raise SystemExit(
                f"{name}: fit R^2 {r2:.4f} is below 0.85 -- the reconstructed surface would "
                f"be a sphere wearing the fit's residue. Raise DEGREE or sigma for order "
                f"{power}.")
        if not 0.19 <= sd <= 0.26:
            raise SystemExit(
                f"{name}: relief sd {sd:.4f} is outside 0.19..0.26. The four elements must "
                f"read at one amplitude or the ladder describes the fractal order rather "
                f"than the species; re-solve the relief gain.")

    text = emit(results)
    if args.check:
        if not os.path.exists(TABLE):
            raise SystemExit(f"missing {TABLE}")
        if open(TABLE).read() != text:
            raise SystemExit(
                f"{TABLE} has drifted from what this script bakes. Re-run without --check.")
        print("OK: shipped table matches a fresh bake.")
        return
    with open(TABLE, "w") as f:
        f.write(text)
    print(f"wrote {TABLE} ({len(text)} bytes)")


if __name__ == "__main__":
    sys.exit(main())
