// Measures every Cleave arena by RUNNING the shipped generator and emitting JSON.
//
// Why this rather than an analytic Python model: three of the four arenas cull prisms with value
// noise, so an offline model would have to re-implement that noise (and the float path into it)
// to be exact, and would be an ESTIMATE the day it drifted. Compiling the real sources and
// counting what they emit has no drift surface at all - and the same run measures the jittered
// volume exactly rather than through an E[k^3] expectation.
//
// The output is committed. Tools/Build/cleave_budget.py reads it and re-hashes every source that
// could move the numbers, so a stale measurement fails loudly instead of being believed.
using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Security.Cryptography;
using System.Text;
using CosmicShore.Data;
using CosmicShore.Gameplay;
using UnityEngine;

static class Program
{
    /// <summary>Repo-relative sources whose contents can move an arena's prism count. Hashed into
    /// the manifest so the measurement can never be believed after one of them changes.</summary>
    static readonly string[] HashedSources =
    {
        "Assets/_Scripts/Controller/Environment/MiniGameObjects/SliceArenaGeometry.cs",
        "Assets/_Scripts/Controller/Environment/MiniGameObjects/SpawnablePanes.cs",
        "Assets/_Scripts/Controller/Environment/MiniGameObjects/SpawnableSwell.cs",
        "Assets/_Scripts/Controller/Environment/MiniGameObjects/SpawnableRibcage.cs",
        "Assets/_Scripts/Controller/Environment/MiniGameObjects/SpawnableTwistbands.cs",
        // The noise the culls run on is copied into PlatformShim.cs; hashing the real file is what
        // makes that copy safe.
        "Assets/_Scripts/Controller/Toys/PaintingStrokeToolkit.cs",
        "Tools/Build/cleave_arena_harness/PlatformShim.cs",
        "Tools/Build/cleave_arena_harness/UnityShim.cs",
        // This file too: the Ladder below owns each arena's SEED and shell count, which decide
        // what the generators emit as surely as the generators do.
        "Tools/Build/cleave_arena_harness/Program.cs",
    };

    /// <summary>The ladder, in intensity order. `shells` applies to the ribcage alone.</summary>
    static readonly (string key, string label, string type, int seed, int shells)[] Ladder =
    {
        ("panes",      "The Panes",      "SpawnablePanes",      391, 0),
        ("swell",      "The Swell",      "SpawnableSwell",      392, 0),
        ("cage",       "The Cage",       "SpawnableRibcage",     39, 3),
        ("twistbands", "The Twistbands", "SpawnableTwistbands", 394, 0),
    };

    static int Main(string[] args)
    {
        // The binary is built into $TMPDIR (run.sh; no .csproj, because the repo gitignores
        // *.csproj), so AppContext.BaseDirectory says nothing about where the repo is. Walk up
        // from THIS SOURCE FILE's compile-time path instead - it is baked in by the compiler and
        // is correct however the harness is invoked.
        string repo = RepoRootFromSource();
        if (repo == null || !Directory.Exists(Path.Combine(repo, "Assets")))
        {
            Console.Error.WriteLine("Could not locate the repo root from this file's path.");
            return 2;
        }

        var sb = new StringBuilder();
        sb.AppendLine("{");
        sb.AppendLine("  \"_note\": \"GENERATED by Tools/Build/cleave_arena_harness - do not hand-edit. Re-run: bash Tools/Build/cleave_arena_harness/run.sh\",");
        sb.AppendLine($"  \"outerRadius\": {F(SliceArenaGeometry.OuterRadius)},");
        sb.AppendLine($"  \"aiStationStandoff\": {F(SliceArenaGeometry.AiStationStandoff)},");

        sb.AppendLine("  \"sourceHashes\": {");
        for (int i = 0; i < HashedSources.Length; i++)
        {
            string path = Path.Combine(repo, HashedSources[i]);
            if (!File.Exists(path)) { Console.Error.WriteLine($"missing source: {HashedSources[i]}"); return 2; }
            string hash = Sha(File.ReadAllBytes(path));
            sb.AppendLine($"    \"{HashedSources[i]}\": \"{hash}\"{(i + 1 < HashedSources.Length ? "," : "")}");
        }
        sb.AppendLine("  },");

        sb.AppendLine("  \"arenas\": [");
        for (int i = 0; i < Ladder.Length; i++)
        {
            var (key, label, typeName, seed, shells) = Ladder[i];
            var arena = Build(typeName, shells);
            var lays = arena.Measure(seed, 1f);

            double volume = lays.Sum(l => (double)l.Point.Scale.x * l.Point.Scale.y * l.Point.Scale.z);
            double maxReach = lays.Count == 0 ? 0 : lays.Max(l => (double)l.Point.Position.magnitude);
            // The envelope claim is about GEOMETRY, not about lay points: a prism is a box
            // with its own extent, so the honest number is how far its far corner reaches.
            double maxReachWithExtent = lays.Count == 0 ? 0 : lays.Max(l =>
                (double)l.Point.Position.magnitude + 0.5 * (double)l.Point.Scale.magnitude);

            var byKind = Enum.GetValues(typeof(PrismKind)).Cast<PrismKind>()
                .ToDictionary(k => k, k => lays.Count(l => l.Kind == k));
            var byDomain = Enum.GetValues(typeof(Domains)).Cast<Domains>()
                .ToDictionary(d => d, d => lays.Count(l => l.Domain == d));

            sb.AppendLine("    {");
            sb.AppendLine($"      \"key\": \"{key}\",");
            sb.AppendLine($"      \"label\": \"{label}\",");
            sb.AppendLine($"      \"type\": \"{typeName}\",");
            sb.AppendLine($"      \"intensity\": {i + 1},");
            sb.AppendLine($"      \"seed\": {seed},");
            sb.AppendLine($"      \"shellCount\": {shells},");
            sb.AppendLine($"      \"prisms\": {lays.Count},");
            sb.AppendLine($"      \"volume\": {F(volume)},");
            sb.AppendLine($"      \"maxReach\": {F(maxReach)},");
            sb.AppendLine($"      \"maxReachWithExtent\": {F(maxReachWithExtent)},");
            sb.AppendLine($"      \"layCapacity\": {arena.LayCapacityForHarness},");
            sb.AppendLine($"      \"byKind\": {{ {string.Join(", ", byKind.Select(p => $"\"{p.Key}\": {p.Value}"))} }},");
            sb.AppendLine($"      \"byDomain\": {{ {string.Join(", ", byDomain.Select(p => $"\"{p.Key}\": {p.Value}"))} }}");
            sb.AppendLine("    }" + (i + 1 < Ladder.Length ? "," : ""));
        }
        sb.AppendLine("  ]");
        sb.AppendLine("}");

        if (Harness.Faults > 0)
        {
            Console.Error.WriteLine($"{Harness.Faults} authoring guard(s) fired - nothing written.");
            return 1;
        }

        string outPath = Path.Combine(repo, "Tools/Build/cleave_arena_measurements.json");
        string text = sb.ToString().Replace("\r\n", "\n");
        bool check = args.Contains("--check");

        if (check)
        {
            if (!File.Exists(outPath)) { Console.Error.WriteLine("measurements file missing"); return 1; }
            if (File.ReadAllText(outPath).Replace("\r\n", "\n") != text)
            {
                Console.Error.WriteLine("cleave_arena_measurements.json is STALE - re-run without --check.");
                return 1;
            }
            Console.WriteLine("cleave_arena_measurements.json is current.");
            return 0;
        }

        File.WriteAllText(outPath, text);
        Console.WriteLine(text);
        return 0;
    }

    /// <summary>Instantiates an arena and, for the ribcage, sets its private serialized shell
    /// count - the one generation parameter that lives on the prefab rather than in code.</summary>
    /// <summary>Repo root, walked up from this file's own compile-time path.</summary>
    static string RepoRootFromSource([System.Runtime.CompilerServices.CallerFilePath] string self = "")
    {
        // <repo>/Tools/Build/cleave_arena_harness/Program.cs: GetDirectoryName lands on
        // cleave_arena_harness, so THREE more steps reach the repo root.
        var dir = Path.GetDirectoryName(Path.GetFullPath(self));
        for (int i = 0; i < 3 && dir != null; i++) dir = Path.GetDirectoryName(dir);
        return dir;
    }

    static CellEnvironmentSpawnableBase Build(string typeName, int shells)
    {
        var type = typeof(SliceArenaGeometry).Assembly.GetTypes()
            .First(t => t.Name == typeName && typeof(CellEnvironmentSpawnableBase).IsAssignableFrom(t));
        var arena = (CellEnvironmentSpawnableBase)Activator.CreateInstance(type);

        if (shells > 0)
        {
            var field = type.GetField("shellCount", BindingFlags.Instance | BindingFlags.NonPublic)
                ?? throw new InvalidOperationException($"{typeName} has no shellCount field");
            field.SetValue(arena, shells);
        }
        return arena;
    }

    static string Sha(byte[] bytes) =>
        Convert.ToHexString(SHA256.HashData(bytes)).ToLowerInvariant().Substring(0, 16);

    static string F(double v) => v.ToString("0.####", CultureInfo.InvariantCulture);
}
