#!/usr/bin/env python3
"""
The editor's themes, from the game's colour sets: writes FrogletSeaTheme.Themes.cs, the colours a themed Froglet editor
window draws with (FrogletTools > Build > Source Control is the first, Shombith 2026-11-06: "make it modern, use the
Photic colour set and the sea lines theme").

    python3 Tools/Build/author_editor_themes.py            # write the C# file
    python3 Tools/Build/author_editor_themes.py --check    # exit 1 if it drifted from the game
    python3 Tools/Build/author_editor_themes.py --self-test

One source for every theme: the colours come from Tools/Analytics/console/make_themes.py, which reads the shipped
colour sets (ColorSetCatalog: Nocturne, Photic, Dart Frog) the way Docs/PALETTE.md section 3 says and re-hues the
style guide's Deep Sea steps with each set's signature face (Docs/UI_STYLE_GUIDE.md: "a colour set changes how you see
the HyperSea"). The analytics console and the editor therefore wear the same Photic, and a colour-set change reaches
both by re-running their writers. The sea lines' numbers are the menu's SeaLines (make_themes.SEA).

Editor IMGUI colours are screen (gamma) colours, so each token is written as its sRGB hex.
"""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'Tools', 'Analytics', 'console'))
import make_themes as mt  # noqa: E402  (pure functions + readers; importing has no side effects)

OUT = os.path.join(ROOT, 'Assets', '_Scripts', 'Editor', 'FrogletTools', 'FrogletSeaTheme.Themes.cs')

# C# field <- the make_themes token it is.
FIELDS = [
    ('Ground', '--fs-ground'), ('GroundDeep', '--fs-ground-deep'), ('Surface', '--fs-surface'),
    ('SurfaceRaised', '--fs-surface-raised'), ('Line', '--fs-line'), ('Text', '--fs-text'),
    ('TextSoft', '--fs-text-soft'), ('TextOff', '--fs-text-off'), ('Cta', '--fs-cta'), ('CtaFill', '--fs-cta-fill'),
    ('OnFill', '--fs-on-fill'), ('Danger', '--fs-danger'), ('Selection', '--fs-selection'), ('Jade', '--cs-jade'),
    ('Ruby', '--cs-ruby'), ('Gold', '--cs-gold'), ('Blue', '--cs-blue'), ('Data', '--data'), ('DataText', '--data-text'),
    ('Rim', '--rim'), ('Face', '--face'), ('Sea1', '--sea-1'), ('Sea2', '--sea-2'), ('Sea3', '--sea-3'),
    ('SeaWash', '--sea-wash'), ('SeaGlow', '--sea-glow'),
]


def themes():
    """[(id, name, line, {field: '#RRGGBB'})] for every colour set, in the catalog's order, and the live set's id."""
    tokens = mt.json.load(open(mt.TOKENS, encoding='utf-8'))
    base = tokens['themes'][mt.BASE]
    sets = mt.catalog()
    out = []
    for s in sets:
        vals, _ = mt.theme_tokens(base, s['colours'], s['id'] == mt.AUTHORED_SET)
        out.append((s['id'], s['name'], s['line'], {f: vals[t] for f, t in FIELDS}))
    return out, mt.live_set(sets)


def cs_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def render(rows, live):
    lines = [
        '// GENERATED by Tools/Build/author_editor_themes.py from the game\'s colour sets (ColorSetCatalog), through',
        '// Tools/Analytics/console/make_themes.py. Do not edit by hand: re-run the writer (--check is the drift gate).',
        'namespace CosmicShore.Editor.Froglet',
        '{',
        '    public static partial class FrogletSeaTheme',
        '    {',
        '        /// <summary>The colour set the game runs on (ThemeManagerDataContainer.ColorSet).</summary>',
        f'        public const string LiveSet = {cs_string(live)};',
        '',
        '        /// <summary>The menu\'s SeaLines (Sea_Window.mat): lines 46 apart on a 480-unit loop, three layers.</summary>',
        f'        const float SeaSpacing = {mt.SEA["spacing"]}f, SeaLoop = {mt.SEA["loop"]}f, SeaAmplitude = {mt.SEA["amplitude"]}f;',
        '',
        '        static readonly SeaLayer[] SeaLayers =',
        '        {',
    ]
    for layer in mt.SEA['layers']:
        lines.append(f'            new SeaLayer({layer["alpha"]}f, {layer["width"]}f, {layer["seconds"]}f),')
    lines += ['        };', '', '        static readonly Palette[] Generated =', '        {']
    for sid, name, line, cols in rows:
        lines.append('            new Palette')
        lines.append('            {')
        lines.append(f'                Id = {cs_string(sid)}, Name = {cs_string(name)}, Tagline = {cs_string(line)},')
        for f, _ in FIELDS:
            lines.append(f'                {f} = Rgb(0x{cols[f].lstrip("#").upper()}),')
        lines.append('            },')
    lines += ['        };', '    }', '}', '']
    return '\n'.join(lines)


def build():
    rows, live = themes()
    return render(rows, live)


def self_test():
    errs = []
    rows, live = themes()
    ids = [r[0] for r in rows]
    if 'photic' not in ids:
        errs.append(f'no Photic colour set in the catalog: {ids}')
    if live not in ids:
        errs.append(f'the live set {live} is not a theme')
    for sid, _, _, cols in rows:
        bad = [f for f, v in cols.items() if not (len(v) == 7 and v.startswith('#'))]
        if bad:
            errs.append(f'{sid}: not a #RRGGBB colour: {bad}')
        # The theme keeps the style guide's readability: text on a panel at 4.5:1, marks at 3:1 (make_themes fits them).
        # The authored set wears the authored Deep Sea as it is (make_themes.AUTHORED_SET), so it is not fitted.
        if sid == mt.AUTHORED_SET:
            continue
        surface = mt.hx(cols['Surface'])
        for f, ratio in (('Text', 4.5), ('TextSoft', 4.5), ('Danger', 4.5), ('Selection', 3.0), ('Cta', 3.0)):
            c = mt.contrast(mt.hx(cols[f]), surface)
            if c < ratio - 0.01:
                errs.append(f'{sid}.{f} is {c:.2f}:1 on a panel, under {ratio}:1')
    # Photic is the authored Deep Sea (Garrett, 2026-11-10: Photic holds the values the game was authored in): its
    # selection is the style guide's Jade (controlActive, D3) and its panels the authored navy.
    photic = dict((r[0], r[3]) for r in rows).get('photic', {})
    if photic and (photic.get('Selection') != '#00D4FF' or photic.get('Surface') != '#222645'):
        errs.append(f'Photic is not the authored Deep Sea: selection {photic.get("Selection")}, panels '
                    f'{photic.get("Surface")} (make_themes changed?)')
    text = render(rows, live)
    if text.count('new Palette') != len(rows) or 'Rgb(0x' not in text:
        errs.append('render() lost a theme')
    # Negative control: a drifted file is caught.
    if text == text.replace('Rgb(0x222645)', 'Rgb(0x222646)') and '222645' in text:
        errs.append('drift control did not change the text')
    for e in errs:
        print('FAIL:', e)
    print('author_editor_themes self-test:', 'OK' if not errs else f'{len(errs)} failure(s)')
    return 1 if errs else 0


def main(argv):
    if '--self-test' in argv:
        return self_test()
    text = build()
    if '--check' in argv:
        cur = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else None
        if cur != text:
            print(f'author_editor_themes: {os.path.relpath(OUT, ROOT)} is stale: run python3 Tools/Build/author_editor_themes.py')
            return 1
        print('author_editor_themes: FrogletSeaTheme.Themes.cs matches the game\'s colour sets')
        return 0
    with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)
    print(f'author_editor_themes: wrote {os.path.relpath(OUT, ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
