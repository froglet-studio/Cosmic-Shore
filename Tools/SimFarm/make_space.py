#!/usr/bin/env python3
"""make_space.py - write a coevo genome space from the code: the vessel genes from EscortGeneRegistry.cs (by key
prefix, with the registry's own defaults and ranges), the fauna genes from the escort's tier populations
(ArkEscort.asset) and the fauna params with known shipped values (Docs: fauna_params_DONE).

    python Tools/SimFarm/make_space.py --vessel sparrow --squad Sparrow,Sparrow,Sparrow --out Tools/SimFarm/space_sparrow.json
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REGISTRY = ROOT / "Assets/_Scripts/Controller/Voyages/EscortGeneRegistry.cs"
ESCORT = ROOT / "Assets/_SO_Assets/Toys/ArkEscort.asset"

# Fauna params whose shipped value is known (a gene at its default is not sent, so the default genome is the game).
FAUNA = {
    "fauna.all.capScale": (1.0, 0.5, 2.0),
    "fauna.all.floorScale": (1.0, 0.5, 2.0),
    "fauna.shark.huntInterval": (20.0, 5.0, 60.0),
    "fauna.shark.huntDuration": (10.0, 3.0, 30.0),
    "fauna.shark.pursuitSpeed": (1.5, 1.0, 3.0),
    "fauna.shark.territory": (600.0, 200.0, 1500.0),
    "fauna.tadpole.huntSpeed": (10.0, 3.0, 20.0),
    "fauna.wormcolony.cruiseSpeed": (18.0, 8.0, 40.0),
    "fauna.wormcolony.lungeSpeed": (70.0, 30.0, 140.0),
    "fauna.wormcolony.aggroRadius": (220.0, 100.0, 600.0),
    "fauna.wormcolony.huntInterval": (26.0, 8.0, 60.0),
}


# Switches (0/1) among the registry's genes, and genes the vessel brief freezes at their defaults at first.
SWITCHES = {"cultivate", "ringOnRunup", "useStance"}
FROZEN = {"ai.escort.retargetSeconds", "ai.escort.threatW_dist", "ai.sparrow.leadSeconds"}


def registry_genes(prefixes: list[str]) -> dict:
    text = REGISTRY.read_text(encoding="utf-8")
    out = {}
    for key, d, lo, hi in re.findall(r'Define\("([a-zA-Z_.]+)",\s*([-0-9.]+)f?,\s*([-0-9.]+)f?,\s*([-0-9.]+)f?', text):
        if any(key.startswith(p) for p in prefixes):
            d, lo, hi = float(d), float(lo), float(hi)
            if key in FROZEN:
                continue
            switch = key.rsplit(".", 1)[-1] in SWITCHES
            out[key] = {"type": "int" if switch else "float", "min": lo, "max": hi, "default": int(d) if switch else d}
    return out


def tier_populations(diffs: list[int]) -> dict:
    pops = [float(x) for x in re.findall(r"- Population: ([0-9.]+)", ESCORT.read_text(encoding="utf-8"))]
    out = {}
    for d in diffs:
        p = pops[d - 1]
        out[f"tier.{d}.population"] = {"type": "float", "min": round(p * 0.5, 3), "max": round(min(2.0, p * 1.8), 3),
                                       "default": p}
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--vessel", default="sparrow", help="the ai.<vessel>.* genes (plus ai.escort.*)")
    ap.add_argument("--squad", default="Sparrow,Sparrow,Sparrow")
    ap.add_argument("--difficulties", default="2,4,6,8")
    ap.add_argument("--no-escort", action="store_true", help="leave out the shared ai.escort.* genes")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    prefixes = [f"ai.{a.vessel}."] + ([] if a.no_escort else ["ai.escort."])
    vessel = {"__squad": {"type": "choice", "choices": [a.squad], "default": a.squad}}
    vessel.update(registry_genes(prefixes))
    fauna = tier_populations([int(x) for x in a.difficulties.split(",")])
    fauna.update({k: {"type": "float", "min": lo, "max": hi, "default": d} for k, (d, lo, hi) in FAUNA.items()})
    space = {"_note": f"generated by make_space.py from {REGISTRY.name} and {ESCORT.name}",
             "vessel": {"genes": vessel}, "fauna": {"genes": fauna}}
    Path(a.out).write_text(json.dumps(space, indent=1), encoding="utf-8")
    print(f"{a.out}: {len(vessel) - 1} vessel genes, {len(fauna)} fauna genes")


if __name__ == "__main__":
    main()
