"""The board: what every machine has found, per job, merged - `compute.py board [--write]`.

Writes Docs/Compute/BOARD.md (people read it) and Docs/Compute/board.json (sessions and the scout read it). Both are
GENERATED; never edit them by hand.
"""
import json
import os
import time

import compute_lib as L
import worker as W

BOARD_MD = "Docs/Compute/BOARD.md"
BOARD_JSON = "Docs/Compute/board.json"


def _fmt_loss(x):
    return "-" if x is None or not L.finite(x) else f"{x:.5g}"


def build(jobs, machines, caps):
    rows = W.ranked(jobs, machines, caps)
    t = L.now()
    out = {"generated": t, "machines": [], "jobs": []}
    for m in machines:
        hb = m.get("heartbeat") or {}
        out["machines"].append({"machine": f"{m['user']}/{m['host']}", "updated": hb.get("updated"),
                                "current": hb.get("current"), "cores": hb.get("cores"),
                                "caps": [k for k, v in (hb.get("caps") or {}).items() if v is True],
                                "active": t - int(hb.get("updated", 0) or 0) < 3 * 3600 and bool((hb.get("current") or {}).get("job"))})
    for r in rows:
        j, e = r["job"], r["merged"] or {}
        best = (e or {}).get("best")
        base = None
        for m in machines:
            s = ((m["jobs"].get(j["id"]) or {}).get(r["epoch"]) or {}).get("summary") or {}
            if s.get("baseline"):
                base = s["baseline"]
                break
        out["jobs"].append({
            "id": j["id"], "title": j["title"], "status": j["status"], "plan": j.get("plan"), "stage": j.get("stage"),
            "owner": j.get("area_owner"), "value": j.get("value"), "priority": r["score"], "why": r["why"],
            "blocked": r["reason"], "epoch": r["epoch"], "evals": (e or {}).get("evals", 0),
            "machine_hours": round((e or {}).get("seconds", 0) / 3600, 2), "machines": sorted(set((e or {}).get("machines", []))),
            "best": best, "baseline": base, "converged": L.converged(j, e) if e else False,
            "archive": {"filled": len((e or {}).get("archive", {}))} if (e or {}).get("archive") else None,
            "units": (e or {}).get("units") or None})
    return out


def markdown(b):
    lines = ["# Froglet Compute board", "",
             "GENERATED by `python3 Tools/Compute/compute.py board --write` from every machine's results branch "
             "(`compute/<user>/<host>`). Do not edit by hand. How it works: `Docs/Compute/README.md`; how to join: `/compute`.", "",
             f"Built {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime(b['generated']))}."]
    active = [m for m in b["machines"] if m["active"]]
    hours = sum(j["machine_hours"] for j in b["jobs"])
    lines += ["", f"**{len(active)} machine(s) working now, {len(b['machines'])} have ever published; "
                  f"{hours:.1f} machine-hours in the current epochs.**", ""]
    lines += ["## The queue, in the order a machine takes it", "",
              "| # | Job | Status | Priority | Best (shipped) | Evals | Machine-h | Why it waits |", "|---:|---|---|---:|---|---:|---:|---|"]
    for k, j in enumerate(b["jobs"], 1):
        best = _fmt_loss((j["best"] or {}).get("loss"))
        base = _fmt_loss((j["baseline"] or {}).get("loss"))
        conv = " converged" if j["converged"] else ""
        lines.append(f"| {k} | `{j['id']}` {j['title']} | {j['status']}{conv} | {j['priority']} | {best} ({base}) | "
                     f"{j['evals']} | {j['machine_hours']} | {j['blocked'] or 'runnable'} |")
    plans = {}
    for j in b["jobs"]:
        if j.get("plan"):
            plans.setdefault(j["plan"], []).append(j)
    for plan, js in plans.items():
        lines += ["", f"## Plan: {plan}", ""]
        for j in sorted(js, key=lambda j: (j.get("stage") or 0, j["id"])):
            state = "converged" if j["converged"] else j["status"]
            lines.append(f"- stage {j.get('stage')}: `{j['id']}` - {state}; best {_fmt_loss((j['best'] or {}).get('loss'))}"
                         f" vs shipped {_fmt_loss((j['baseline'] or {}).get('loss'))}")
    ready = [j for j in b["jobs"] if j["converged"] and j["status"] == "ready"]
    if ready:
        lines += ["", "## Converged: ready to promote (a session runs `compute.py promote <id>` with the owner's go-ahead)", ""]
        for j in ready:
            lines.append(f"- `{j['id']}` (owner: {j.get('owner') or 'see the job'})")
    if b["machines"]:
        lines += ["", "## Machines", "", "| Machine | Last seen | On | Cores | Can run |", "|---|---|---|---:|---|"]
        for m in sorted(b["machines"], key=lambda m: -(m["updated"] or 0)):
            seen = time.strftime("%Y-%m-%d %H:%M", time.gmtime(m["updated"])) if m["updated"] else "-"
            cur = (m["current"] or {}).get("job") or "-"
            lines.append(f"| {m['machine']} | {seen} | {cur} | {m['cores'] or '-'} | {', '.join(m['caps'])} |")
    return "\n".join(lines) + "\n"


def run(args):
    if not args.no_fetch:
        queue = [r.replace("origin/", "") for r in (args.queue or L.QUEUE_REFS)]
        L.fetch(queue, results=True, quiet=True)
    jobs = L.load_jobs(local=True) if args.local else L.load_jobs([q if q.startswith("origin/") else "origin/" + q for q in (args.queue or L.QUEUE_REFS)])
    machines = L.gather()
    b = build(jobs, machines, L.capabilities())
    md = markdown(b)
    if args.write:
        with open(os.path.join(L.REPO, BOARD_MD), "w", encoding="utf-8") as fh:
            fh.write(md)
        L.write_json(os.path.join(L.REPO, BOARD_JSON), b)
        print(f"wrote {BOARD_MD} and {BOARD_JSON}")
    else:
        print(md)
    return 0
