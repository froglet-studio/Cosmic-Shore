#!/usr/bin/env python3
"""game_catalog.py - GENERATE Docs/Studios/VesselStudio/studio-game.js: the game's vessels and mini-games, read from the
project, for the hub's "+ New studio" panel (/vessel-studio D34). The panel never types a vessel or a mode name: it
offers what the game has, so a request names real assets.

  vessels  VesselClassType (Assets/_Scripts/Data/Enums/VesselClassType.cs), minus Any / Random; per hull: its enum
           value, whether its class asset exists (Assets/_SO_Assets/Classes/SO_Class_<Name>.asset), the studio it
           has (studios.json), and the mini-games whose card lists it
  games    every arcade card (Assets/_SO_Assets/Games/ArcadeGame*.asset; an "_"-prefixed card is retired and left
           out): DisplayName, its GameModes name and value, scene, the hulls it seats, and which menu lists it
           (ArcadeGames / ArenaGames)

    python3 .claude/skills/vessel-studio/game_catalog.py            # write studio-game.js
    python3 .claude/skills/vessel-studio/game_catalog.py --check    # exit 1 when the file is stale
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
OUT = os.path.join(ROOT, 'Docs/Studios/VesselStudio/studio-game.js')
ENUM_VESSEL = os.path.join(ROOT, 'Assets/_Scripts/Data/Enums/VesselClassType.cs')
ENUM_MODES = os.path.join(ROOT, 'Assets/_Scripts/Data/Enums/GameModes.cs')
CLASSES = os.path.join(ROOT, 'Assets/_SO_Assets/Classes')
GAMES = os.path.join(ROOT, 'Assets/_SO_Assets/Games')
STUDIOS = os.path.join(ROOT, 'Docs/Studios/VesselStudio/studios.json')


def read(p):
    with open(p, encoding='utf-8') as fh:
        return fh.read()


def enum_members(path, name):
    src = re.sub(r'//[^\n]*|/\*.*?\*/', '', read(path), flags=re.S)
    body = re.search(r'enum\s+' + name + r'\s*(?::\s*\w+)?\s*\{(.*?)\}', src, re.S).group(1)
    return [(m.group(1), int(m.group(2))) for m in re.finditer(r'(\w+)\s*=\s*(-?\d+)', body)]


def guid_of(asset):
    m = re.search(r'^guid:\s*([0-9a-f]{32})', read(asset + '.meta'), re.M)
    return m.group(1) if m else None


def field(text, name):
    m = re.search(r'^  ' + name + r':[ \t]*(.*)$', text, re.M)
    return m.group(1).strip() if m else ''


def list_guids(text, name):
    m = re.search(r'^  ' + name + r':\s*\n((?:  - \{[^\n]*\n)*)', text, re.M)
    return re.findall(r'guid: ([0-9a-f]{32})', m.group(1)) if m else []


def build():
    modes = {v: n for n, v in enum_members(ENUM_MODES, 'GameModes')}
    class_by_guid, vessels = {}, []
    for name, value in enum_members(ENUM_VESSEL, 'VesselClassType'):
        if value <= 0:
            continue   # Any, Random
        asset = os.path.join(CLASSES, 'SO_Class_%s.asset' % name)
        has = os.path.exists(asset)
        if has:
            class_by_guid[guid_of(asset)] = name
        vessels.append({'name': name, 'value': value, 'hasClass': has, 'studio': None, 'games': []})
    lists = {}
    for key, fname in (('arcade', 'ArcadeGames'), ('arena', 'ArenaGames')):
        p = os.path.join(GAMES, 'GameLists', fname + '.asset')
        lists[key] = set(list_guids(read(p), 'Games')) if os.path.exists(p) else set()
    games = []
    for p in sorted(glob.glob(os.path.join(GAMES, 'ArcadeGame*.asset'))):
        text = read(p)
        mode_v = field(text, 'Mode')
        if not mode_v.lstrip('-').isdigit():
            continue
        g = guid_of(p)
        hulls = [class_by_guid[x] for x in list_guids(text, 'Vessels') if x in class_by_guid]
        games.append({
            'name': field(text, 'DisplayName') or os.path.basename(p)[len('ArcadeGame'):-len('.asset')],
            'mode': modes.get(int(mode_v), mode_v), 'modeValue': int(mode_v),
            'card': os.path.basename(p), 'scene': field(text, 'SceneName'), 'vessels': hulls,
            'menu': 'arena' if g in lists['arena'] else 'arcade' if g in lists['arcade'] else '',
        })
    by_name = {v['name']: v for v in vessels}
    for gm in games:
        for h in gm['vessels']:
            by_name[h]['games'].append(gm['name'])
    for s in json.loads(read(STUDIOS)).get('studios', []):
        if s.get('name') in by_name:
            by_name[s['name']]['studio'] = s['id']
    games.sort(key=lambda x: x['name'].lower())
    return {'vessels': vessels, 'games': games}


def render(data):
    body = json.dumps(data, indent=1, ensure_ascii=True)
    return ('/* studio-game.js - GENERATED by .claude/skills/vessel-studio/game_catalog.py; do not edit by hand.\n'
            ' * The game\'s vessels (VesselClassType, their class assets and studios) and mini-games (every arcade card,\n'
            ' * its GameModes name, scene and seated hulls), for the hub\'s "+ New studio" panel. Re-run after adding a\n'
            ' * vessel, a card or a studio; --check fails when this file is stale.\n'
            ' */\n'
            '(function () {\n'
            '  \'use strict\';\n'
            '  window.VesselStudioGame = ' + body.replace('\n', '\n  ') + ';\n'
            '})();\n')


def main():
    want = render(build())
    if '--check' in sys.argv:
        have = read(OUT) if os.path.exists(OUT) else ''
        print('game_catalog: ' + ('up to date' if have == want else 'STALE - run without --check'))
        return 0 if have == want else 1
    with open(OUT, 'w', encoding='utf-8', newline='') as fh:
        fh.write(want)
    d = build()
    print('game_catalog: wrote %s (%d vessels, %d mini-games)' % (os.path.relpath(OUT, ROOT), len(d['vessels']), len(d['games'])))
    return 0


if __name__ == '__main__':
    sys.exit(main())
