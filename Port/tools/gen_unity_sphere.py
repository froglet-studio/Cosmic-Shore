#!/usr/bin/env python3
"""Generate Port/src/CosmicShore.Engine/Rendering/UnitySphereMesh.g.cs from
Port/parity/unity-primitives.json: Unity 6000.3.17f1's built-in Sphere primitive (what
GameObject.CreatePrimitive and the builtin mesh fileID 10207 give, "New-Sphere.fbx": 515 vertices,
768 triangles, radius 0.5), exported on Gbox. NOT "Sphere.fbx", an older unit-radius 439-vertex
mesh. The blast shell (RippleGraph) displaces each vertex by a hash noise of its object-space
position, so its outline matches Unity's only on Unity's vertices. --check fails when the .g.cs
is stale."""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "Port/parity/unity-primitives.json"
OUT = ROOT / "Port/src/CosmicShore.Engine/Rendering/UnitySphereMesh.g.cs"


def fl(xs):
    return ", ".join(f"{x!r}f".replace("e", "E") if x != int(x) else f"{int(x)}f" for x in xs)


def flat(rows):
    return [c for r in rows for c in r]


def render() -> str:
    d = json.loads(SRC.read_text())
    m = next(x for x in d["primitives"] if x["name"] == "Sphere")
    idx = m["submeshes"][0]["triangles"]
    rows = lambda xs, n: "\n".join("            " + fl(xs[i:i + n]) + "," for i in range(0, len(xs), n))
    irows = "\n".join("            " + ", ".join(map(str, idx[i:i + 24])) + "," for i in range(0, len(idx), 24))
    return f"""// <auto-generated> by Port/tools/gen_unity_sphere.py from Port/parity/unity-primitives.json
// (Unity {d['unityVersion']} built-in Sphere primitive, {m['vertexCount']} vertices, {len(idx)//3} triangles). Do not edit.
namespace CosmicShore.Engine
{{
    internal static class UnitySphereMesh
    {{
        internal static readonly float[] Positions =
        {{
{rows(flat(m['vertices']), 12)}
        }};

        internal static readonly float[] Normals =
        {{
{rows(flat(m['normals']), 12)}
        }};

        internal static readonly float[] Tangents =
        {{
{rows(flat(m['tangents']), 16)}
        }};

        internal static readonly float[] Uv =
        {{
{rows(flat(m['uv']), 16)}
        }};

        internal static readonly int[] Indices =
        {{
{irows}
        }};
    }}
}}
"""


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("ok" if ok else f"stale: run python3 Port/tools/{pathlib.Path(__file__).name}")
        sys.exit(0 if ok else 1)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
