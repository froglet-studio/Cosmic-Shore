        /// <summary>
        /// RGBA8 atlas pixels (white glyphs, transparent background), row 0 = TOP.
        /// The last grid cell (index 95, unused by the 95 glyphs) is baked SOLID white
        /// so rects and text share one texture — a single batch, no state changes.
        /// </summary>
        public static byte[] BuildAtlas()
        {
            var pixels = new byte[AtlasWidth * AtlasHeight * 4];
            for (int code = FirstChar; code <= LastChar; code++)
            {
                int index = code - FirstChar;
                int cellX = (index % AtlasColumns) * GlyphWidth;
                int cellY = (index / AtlasColumns) * GlyphHeight;
                for (int row = 0; row < GlyphHeight; row++)
                {
                    byte bits = Glyphs[index * 8 + row];
                    for (int col = 0; col < GlyphWidth; col++)
                    {
                        if ((bits & (1 << col)) == 0) continue;
                        int p = ((cellY + row) * AtlasWidth + cellX + col) * 4;
                        pixels[p] = pixels[p + 1] = pixels[p + 2] = pixels[p + 3] = 255;
                    }
                }
            }

            // Solid cell: grid position (col 15, row 5).
            const int solidX = (AtlasColumns - 1) * GlyphWidth;
            const int solidY = (AtlasRows - 1) * GlyphHeight;
            for (int row = 0; row < GlyphHeight; row++)
                for (int col = 0; col < GlyphWidth; col++)
                {
                    int p = ((solidY + row) * AtlasWidth + solidX + col) * 4;
                    pixels[p] = pixels[p + 1] = pixels[p + 2] = pixels[p + 3] = 255;
                }
            return pixels;
        }

        /// <summary>Centre of the solid-white cell — the UV every solid-rect vertex uses.</summary>
        public static (float u, float v) SolidUv =>
            ((AtlasColumns - 1 + 0.5f) * GlyphWidth / (float)AtlasWidth,
             (AtlasRows - 1 + 0.5f) * GlyphHeight / (float)AtlasHeight);

        /// <summary>UV rect (u0, v0, u1, v1) of a character's cell; v0 is the TOP edge.</summary>
        public static (float u0, float v0, float u1, float v1) GlyphUv(char c)
        {
            int code = c < FirstChar || c > LastChar ? '?' : c;
            int index = code - FirstChar;
            float u0 = (index % AtlasColumns) * GlyphWidth / (float)AtlasWidth;
            float v0 = (index / AtlasColumns) * GlyphHeight / (float)AtlasHeight;
            return (u0, v0, u0 + GlyphWidth / (float)AtlasWidth, v0 + GlyphHeight / (float)AtlasHeight);
        }
