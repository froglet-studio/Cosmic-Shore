    /// <summary>
    /// The non-Euclidean tile of the Schwarz P minimal surface, and the arithmetic that
    /// lays it out across the surface exactly.
    ///
    /// <para><b>The surface is hyperbolic, so it carries no Euclidean lattice.</b> That is
    /// why the assembler's original approach - step a tangent direction, Newton-project
    /// back onto the zero level set, repeat - could only ever be a QUASI-square array: it
    /// drifts, it never closes up, and it has no repeat unit, so nothing can be baked,
    /// verified, or reasoned about. The surface does carry an exact non-Euclidean tiling,
    /// the hyperbolic <b>{6,4}</b> (hexagons with 90-degree corners, four to a vertex),
    /// and on this surface it is startlingly concrete:</para>
    ///
    /// <para><b>THE TILE IS THE PATCH OF SURFACE INSIDE ONE HALF-PERIOD CUBE.</b></para>
    ///
    /// <para>The {100} mirror planes (x, y, z in pi*Z) cut space into cubes of side pi -
    /// half a period. Each cube contains exactly one FLAT POINT of the surface (Gaussian
    /// curvature 0, normal along a body diagonal), and the patch inside it is one
    /// hyperbolic hexagon: six edges, one on each cube face, every one a planar geodesic
    /// because the face is a mirror; six corners, on the six cube edges whose ends straddle
    /// the surface, every one a 4-fold point lying exactly in the flat point's TANGENT
    /// PLANE at the vertices of a regular hexagon; and six neighbours - the six
    /// face-adjacent cubes.</para>
    ///
    /// <para><b>Tile adjacency is therefore simple-cubic adjacency</b>, so a tile is keyed
    /// by a <see cref="Vector3Int"/> and occupancy is exact integer bookkeeping. There is
    /// no float quantization anywhere in the growth path, and no iterative projection: a
    /// site's position is integer arithmetic on a baked offset.</para>
    ///
    /// <para>Each hexagon is 12 copies of the <b>*246 Schwarz triangle</b> - measured
    /// (30, 45, 90) degrees, the signature of the triangle group the P surface's symmetry
    /// quotients onto - whose corners are the flat point (order 6), a tile corner (order 4)
    /// and a tile edge midpoint (order 2). Per cubic unit cell the tiling closes at F=8,
    /// E=24, V=12, Euler characteristic -4: genus 3, exactly as the P surface must be.</para>
    ///
    /// <para><b>Adjacent tiles are MIRROR IMAGES across their shared cube face</b>, so tile
    /// (i,j,k) is the canonical tile carried by T_ijk, which acts one axis at a time:
    /// <c>x -> x + pi*i</c> when i is even, <c>x -> pi*(i+1) - x</c> when i is odd. The
    /// implicit function is invariant under every T_ijk, so the whole surface is one baked
    /// patch plus a sign flip per odd axis (<see cref="AxisSigns"/>).</para>
    ///
    /// <para><b>No rotation is ever baked.</b> Half of the T_ijk are reflections, and a
    /// baked quaternion carried through one is silently wrong - the failure that cost the
    /// gyroid's seed rotations five playtests (Docs/ECOSYSTEM.md 32.7). Positions and
    /// tangents are vectors and transform correctly under a reflection; the surface normal
    /// is recomputed from the closed-form gradient at the transformed point
    /// (<see cref="SurfaceNormalParam"/>), so orientation is derived, never carried.</para>
    ///
