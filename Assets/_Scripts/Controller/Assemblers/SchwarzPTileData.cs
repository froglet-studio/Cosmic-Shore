        public static int LevelCount => LevelTable.Length;

        public static int SiteCount(int level) => LevelTable[Clamp(level)].Sites.Length;

        /// <summary>Mean nearest-neighbour distance between sites, in parameter radians.</summary>
        public static float MeanParamSpacing(int level) => LevelTable[Clamp(level)].MeanParamSpacing;

        static int Clamp(int level) => Mathf.Clamp(level, 0, LevelTable.Length - 1);

        /// <summary>
        /// The subdivision whose measured site spacing lands closest to the flora's authored
        /// <c>separationDistance</c>. The tile itself is fixed by the surface; how finely it
        /// is filled with prisms is the one free parameter, and this is where it is chosen.
        /// </summary>
        public static int ResolveLevel(float separationDistance, float periodScale)
        {
            float worldScale = periodScale / ParamPeriod;
            if (worldScale <= 1e-5f || separationDistance <= 1e-5f) return 0;

            int best = 0;
            float bestError = float.MaxValue;
            for (int level = 0; level < LevelTable.Length; level++)
            {
                float error = Mathf.Abs(LevelTable[level].MeanParamSpacing * worldScale - separationDistance);
                if (error >= bestError) continue;
                bestError = error;
                best = level;
            }
            return best;
        }

        /// <summary>World-space distance between neighbouring prisms at this level.</summary>
        public static float WorldSpacing(int level, float periodScale) =>
            MeanParamSpacing(level) * (periodScale / ParamPeriod);

        /// <summary>The flat point at the centre of tile (i,j,k), in parameter space.</summary>
        public static Vector3 TileCenterParam(Vector3Int tile) => new(
            TileParamSize * (tile.x + 0.5f),
            TileParamSize * (tile.y + 0.5f),
            TileParamSize * (tile.z + 0.5f));

        /// <summary>
        /// The linear part of T_ijk: -1 on every odd axis, because a tile is the mirror
        /// image of each of its face neighbours. Also the direction of the tile's flat
        /// point normal.
        /// </summary>
        public static Vector3 AxisSigns(Vector3Int tile) => new(
            (tile.x & 1) == 0 ? 1f : -1f,
            (tile.y & 1) == 0 ? 1f : -1f,
            (tile.z & 1) == 0 ? 1f : -1f);

        /// <summary>
        /// The tile a bond step leads to. <b>Not <c>tile + delta</c>.</b>
        ///
        /// <para>Bond deltas are measured in the CANONICAL tile, and carrying one into tile
        /// (i,j,k) means composing tile transforms - which do not add. Per axis,
        /// <c>T_a(T_b(x)) = T_(a + b)</c> when a is even but <c>T_(a - b)</c> when a is odd,
        /// because an odd tile is a MIRROR image and a mirror reverses the step through it.
        /// So a bond delta is negated on exactly the axes <see cref="AxisSigns"/> negates,
        /// and the neighbour's SITE INDEX is unchanged.</para>
        ///
        /// <para>Getting this wrong is silent and survives every static check: the offsets
        /// are still exact, every prism still lands on the surface, occupancy still keys
        /// cleanly - odd-indexed tiles simply bond to the tile on the wrong side. It shows
        /// up only as geometry, as prisms with no neighbour within seven times the spacing,
        /// and it was caught by simulating a plant's growth to its authored budget rather
        /// than by reading the code.</para>
        /// </summary>
        public static Vector3Int NeighbourTile(Vector3Int tile, Vector3Int delta) => new(
            tile.x + ((tile.x & 1) == 0 ? delta.x : -delta.x),
            tile.y + ((tile.y & 1) == 0 ? delta.y : -delta.y),
            tile.z + ((tile.z & 1) == 0 ? delta.z : -delta.z));

        public static SchwarzPTileSite GetSite(int level, int site)
        {
            var sites = LevelTable[Clamp(level)].Sites;
            var s = sites[Mathf.Clamp(site, 0, sites.Length - 1)];
            return new SchwarzPTileSite(s.Offset, s.Tangent);
        }

        /// <summary>Parameter-space position of a site of a given tile. Pure arithmetic.</summary>
        public static Vector3 SiteParam(Vector3Int tile, int level, int site)
        {
            Vector3 signs = AxisSigns(tile);
            Vector3 offset = GetSite(level, site).ParamOffset;
            return TileCenterParam(tile) + new Vector3(
                signs.x * offset.x, signs.y * offset.y, signs.z * offset.z);
        }

        /// <summary>Parameter-space tangent of a site of a given tile.</summary>
        public static Vector3 SiteTangentParam(Vector3Int tile, int level, int site)
        {
            Vector3 signs = AxisSigns(tile);
            Vector3 tangent = GetSite(level, site).ParamTangent;
            return new Vector3(signs.x * tangent.x, signs.y * tangent.y, signs.z * tangent.z);
        }

        /// <summary>
        /// Unit surface normal from the closed-form gradient of
        /// <c>f = cos x + cos y + cos z</c>. Derived at the transformed point, so it is
        /// correct under the reflections half the tile transforms carry.
        /// </summary>
        public static Vector3 SurfaceNormalParam(Vector3 param)
        {
            Vector3 gradient = new(-Mathf.Sin(param.x), -Mathf.Sin(param.y), -Mathf.Sin(param.z));
            return gradient.sqrMagnitude > 1e-8f ? gradient.normalized : Vector3.up;
        }

        /// <summary>The growth steps available from a site: its touching neighbours, nearest
        /// first, each tagged with the tile it belongs to (zero for a sibling in the same
        /// tile, a unit axis step for one across a seam).</summary>
        public static SchwarzPBond[] GetBonds(int level, int site)
        {
            var bonds = BuildBonds(Clamp(level));
            return bonds[Mathf.Clamp(site, 0, bonds.Length - 1)];
        }

        static SchwarzPBond[][] BuildBonds(int level)
        {
            if (BondCache.TryGetValue(level, out var cached)) return cached;

            var sites = LevelTable[level].Sites;
            int count = sites.Length;

            // Every site of the tile and of its 26 neighbours, in parameter space. The tile
            // is only pi across, so the whole block is a few thousand points at worst.
            var deltas = new List<Vector3Int>(27);
            for (int x = -1; x <= 1; x++)
                for (int y = -1; y <= 1; y++)
                    for (int z = -1; z <= 1; z++)
                        deltas.Add(new Vector3Int(x, y, z));

            var origin = Vector3Int.zero;
            var positions = new Vector3[deltas.Count][];
            for (int d = 0; d < deltas.Count; d++)
            {
                positions[d] = new Vector3[count];
                for (int s = 0; s < count; s++)
                    positions[d][s] = SiteParam(deltas[d], level, s);
            }

            var result = new SchwarzPBond[count][];
            var scratch = new List<(float distance, int site, int delta)>(count * deltas.Count);
            for (int s = 0; s < count; s++)
            {
                Vector3 self = SiteParam(origin, level, s);
                scratch.Clear();
                float nearest = float.MaxValue;
                for (int d = 0; d < deltas.Count; d++)
                {
                    for (int other = 0; other < count; other++)
                    {
                        if (d == 13 && other == s) continue;    // deltas[13] is (0,0,0)
                        float distance = Vector3.Distance(self, positions[d][other]);
                        if (distance < 1e-5f) continue;
                        scratch.Add((distance, other, d));
                        if (distance < nearest) nearest = distance;
                    }
                }

                float limit = nearest * BondRadiusFactor;
                scratch.Sort((a, b) => a.distance.CompareTo(b.distance));

                var picked = new List<SchwarzPBond>(8);
                foreach (var (distance, other, delta) in scratch)
                {
                    if (distance > limit) break;
                    picked.Add(new SchwarzPBond(other, deltas[delta]));
                }
                result[s] = picked.ToArray();
            }

            BondCache[level] = result;
            return result;
        }
    }
