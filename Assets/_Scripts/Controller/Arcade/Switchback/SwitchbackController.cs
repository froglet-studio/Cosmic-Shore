                 "the lead off. Dolphin 2.5: the fleet lead.")]
        [SerializeField] AINoseLeadRow[] aiNoseLead = { new AINoseLeadRow(VesselClassType.Dolphin, 2.5f) };

        protected override AINoseLeadRow[] AINoseLeadTable => aiNoseLead;

        [Header("Switchback course")]
        [Tooltip("Where gate 1 sits, as a distance along the spawn formation's POLE. Pilots spawn " +
                 "on an equatorial ring, so a point on that ring's axis is the only place every " +
                 "pilot is equidistant from - which is what makes the start fair.")]
        [SerializeField, Min(1f)] float firstGateDistance = SwitchbackCourseSource.DefaultFirstGateDistance;

        [Header("Blast Run")]
        [Tooltip("Lays Blast Run's doors and block fields along the course (SwitchbackBlastRun) on every peer.")]
        [SerializeField] SpawnableSwitchbackFeatures featuresPrefab;
        [Tooltip("u: the radius of the I4 gauntlet's path rays (SwitchbackPathRays), the beams of light down the way through " +
                 "each blocked gate - key to key, to the door and through the ring. 0 = no rays.")]
        [SerializeField, Min(0f)] float pathRayRadius = 1.2f;

        [Header("Fauna corridor")]
        [Tooltip("Per intensity (I1..I4): u round the gate-to-gate path no fauna is born in, steers into or eats in " +
                 "(Cell.SetFaunaPathCorridor - a diet + steering pen, never a wall). Keeps the path free for prism " +
                 "obstacles and takes fauna body-sync / animator cost off where pilots fly. 0 = no corridor (fauna as before). " +
                 "220 sits just past PrismColliderLodManager's 200 u collider radius. Docs/perf/SWITCHBACK_PRISM_BUDGET.md.")]
        [SerializeField] float[] faunaCorridorRadiusByIntensity = { 220f, 220f, 220f, 220f };

        [Tooltip("u past the corridor wall that a fauna goal or birth pushed out of the corridor lands (FaunaCorridor.GoalStandoff). " +
                 "A goal parked on the wall itself is crossed by every creature overshooting it between steering ticks; the " +
                 "2026-11-02 playtest found light fauna 139-190 u from the path inside a 220 u corridor. 0 = on the wall.")]
        [SerializeField, Min(0f)] float faunaCorridorGoalStandoff = 50f;

        [Header("Blast Run AI")]
        [Tooltip("The AI's blast planner (SWITCHBACK.md \"AI: the blast planner\"): at each blocked gate an AI chooses to thread " +
                 "the eye or take the key crystal and blast the door, by its difficulty. Off = the old crystal detour.")]
        [SerializeField] bool aiBlastPlanner = true;
        [Tooltip("Use the four skills below (Easy, Medium, Hard, Legendary) instead of the built-in table " +
                 "(SwitchbackAISkill.ForLevel).")]
        [SerializeField] bool aiSkillOverride;
        [SerializeField] SwitchbackAISkill[] aiSkills =
        {
            SwitchbackAISkill.ForLevel(1), SwitchbackAISkill.ForLevel(2), SwitchbackAISkill.ForLevel(3), SwitchbackAISkill.ForLevel(4),
        };
        [Tooltip("The AI dodges only Danger prisms and flies straight through plain ones (SwitchbackPrismAvoidance.Dodges). " +
