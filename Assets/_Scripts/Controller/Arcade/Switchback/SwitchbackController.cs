        [SerializeField] bool aiSenseDebug;

        /// <summary>u a course feature keeps outside the nucleus.</summary>
        const float NucleusMargin = 30f;

        static readonly Unity.Profiling.ProfilerMarker s_featuresSpawnMarker = new("Switchback.Features.Spawn");

        protected override string ModeName => "Switchback";

        /// <summary>
        /// Whether I4 lays the GAUNTLET (SWITCHBACK.md "The I4 gauntlet": zig-zag keys, plugged tunnels, sealed eyes,
        /// the path rays) - built for the Dolphin's key blast. A mode that reuses Switchback's course for a hull without
        /// that blast overrides it false and keeps I4 as it was before 2026-11-03 (Scarab Rally). No effect at I1-I3.
        /// </summary>
        protected virtual bool BlastRunGauntlet => true;

        /// <summary>
        /// Whether this intensity lays Blast Run at all (doors, block fields, movers, key crystals, path rays). Switchback is
        /// Blast Run at every intensity (Yash, 2026-10-29). A mode that reuses Switchback's course for a hull without the
        /// Dolphin's key blast overrides it to fly the bare ring course where Blast Run is not its question (Scarab Rally,
        /// I1-I3): the layout is then empty, so no key replaces the passive crystals and the blast planner has no station.
        /// </summary>
        protected virtual bool LaysBlastRun(int intensity) => true;

        /// <summary>
        /// Switchback flies Regatta's gate steering (<see cref="GateRaceController.AICommitFromApproachPoint"/>): commit no
        /// earlier than the approach point, which now always lies inside the commit radius; aim through the ring's CENTRE
        /// from where the pilot is; re-attack at once after a missed mouth. Switchback is the Dolphin's training minigame
        /// (Docs/AI_SYSTEM/MINIGAME_TRAINING_PLAN.md, Yash 2026-10-26), and with the shipped steering its AI Dolphins
        /// threaded 0-2 of 20 rings in every recorded race: they orbited gate 0's approach point (outside the commit
        /// radius), and a drift committed off-axis locked a line beside the mouth. Offline on the six recorded courses
        /// (<c>Tools/Build/switchback_dolphin_sim.py</c>): 0 rings on each before, 20 of 20 on each after.
        /// </summary>
        protected override bool AICommitFromApproachPoint => true;

        /// <summary>Blast Run's race NEEDS its key crystals: an AI takes the one on its leg (they sit on the line, so the
        /// detour costs nothing) and its blast opens the door.</summary>
        protected override bool AIDetoursForCrystals => true;

        /// <summary>With the blast planner on, the planner decides which key an AI takes (and when not to): no blind detour.</summary>
        protected override float AICrystalDetourSlack => aiBlastPlanner && _blastAI != null ? 0f : base.AICrystalDetourSlack;

        protected override bool TryOverrideAim(IPlayer pilot, out Vector3 target)
        {
            target = default;
            if (!IsServer || _blastAI == null) return false;
            long t = SwitchbackAIClock.Begin();
            bool r = _blastAI.TryAim(pilot, out target);
            SwitchbackAIClock.End(t);
            return r;
        }

        protected override bool TryOverrideDriftLook(IPlayer pilot, out Vector3 look)
        {
            look = default;
            if (!IsServer || _blastAI == null) return false;
            long t = SwitchbackAIClock.Begin();
            bool r = _blastAI.TryDriftLook(pilot, out look);
            SwitchbackAIClock.End(t);
            return r;
        }

        /// <summary>Each AI's own lane through an open ring, so no two AIs fly one line (and its fresh trail).</summary>
        protected override AIPilot.EmergencySteer AIEmergencySteerFor(IPlayer pilot) =>
            (Vector3 position, Vector3 velocity, Vector3 forward, out Vector3 steerTo) =>
            {
                steerTo = default;
                if (aiSenseDebug) SwitchbackBlastAI.DebugSense = true;
                if (!IsServer || _blastAI == null) return false;
                long t = SwitchbackAIClock.Begin();
                bool r = _blastAI.Emergency(pilot, position, velocity, forward, out steerTo);
                SwitchbackAIClock.End(t);
                return r;
            };

        protected override Vector3 AILaneOffset(IPlayer pilot, int ringNo, in RaceGate gate)
        {
            if (!IsServer || _blastAI == null) return Vector3.zero;
            long t = SwitchbackAIClock.Begin();
            var r = _blastAI.LaneOffset(pilot, ringNo, gate);
            SwitchbackAIClock.End(t);
            return r;
        }

        /// <summary>The AI nose follow rate for an intensity (1..4) and a difficulty level (1 Easy .. 4 Legendary):
        /// <see cref="aiNoseFollowByIntensity"/>, or -1 (the fleet lag) for an intensity or level the table does not cover.</summary>
        public static float NoseFollowFor(SwitchbackNoseFollow[] byIntensity, int intensity, int level) =>
            byIntensity != null && intensity >= 1 && intensity <= byIntensity.Length ? byIntensity[intensity - 1].For(level) : -1f;

        /// <summary>The same, with the I4 gauntlet's own row (<paramref name="gauntlet"/>) wherever the course lays the
        /// gauntlet (<paramref name="gauntletOn"/> at I4); every other intensity, and I4 without it, read the table.</summary>
        public static float NoseFollowFor(SwitchbackNoseFollow[] byIntensity, in SwitchbackNoseFollow gauntlet, bool gauntletOn,
                                          int intensity, int level) =>
            SwitchbackBlastRun.HasGauntlet(intensity, gauntletOn) ? gauntlet.For(level) : NoseFollowFor(byIntensity, intensity, level);

        protected override void OnRacerArmed(IPlayer pilot)
        {
            var transformer = pilot?.Vessel?.VesselStatus?.VesselTransformer;
            if (transformer == null) return;
            transformer.AINoseFollowPerSecond = NoseFollowFor(aiNoseFollowByIntensity, aiNoseFollowGauntlet, BlastRunGauntlet,
                                                              Intensity, (int)gameData.AIDifficultyFor(pilot));
        }

        SwitchbackAvoidSkill AvoidSkillFor(IPlayer pilot) => SwitchbackAvoidSkill.ForLevel((int)gameData.AIDifficultyFor(pilot));

        SwitchbackAISkill SkillFor(IPlayer pilot)
        {
            int level = (int)gameData.AIDifficultyFor(pilot);
            if (aiSkillOverride && aiSkills != null && aiSkills.Length >= 4 && level >= 1 && level <= 4) return aiSkills[level - 1];
            return SwitchbackAISkill.ForLevel(level);
        }

        void OnDrawGizmosSelected()
        {
            if (aiPlanGizmos && _blastAI != null) _blastAI.DrawGizmos(GizmoLineSink.Instance);
        }

        void OnDrawGizmos()
        {
            if (aiSenseDebug && _blastAI != null) _blastAI.DrawSenseGizmos(GizmoLineSink.Instance);
        }

        // The in-game Third Eye (AI Diagnose panel, Overlays) draws the same two views in the Game view. Registering is a list
        // add; nothing runs unless the overlay is switched on in a dev build, where ThirdEye exists at all.
        ThirdEyeOverlays.Overlay _planOverlay, _senseOverlay;
        ThirdEyeReadouts.Readout _hitsReadout;

        void RegisterThirdEyeOverlays()
        {
            if (_planOverlay != null) return;
            _hitsReadout = ThirdEyeReadouts.Register("Hits", SwitchbackHitStats.Readout);
            _planOverlay = ThirdEyeOverlays.Register("AI plan (Switchback)",
                "Each AI's blast plan: line to its key, fire line, gape axis, aim point (server only).",
                sink => { if (_blastAI != null) _blastAI.DrawGizmos(sink); });
            _senseOverlay = ThirdEyeOverlays.Register("AI sense (Switchback)",
                "Each AI's prism sense tube, emergency sweep and dodge. Also turns on aiSenseDebug's lines and logs.",
                sink => { if (_blastAI != null) _blastAI.DrawSenseGizmos(sink); },
                on => { aiSenseDebug = on; SwitchbackBlastAI.DebugSense = on; },
                aiSenseDebug);
        }

        void UnregisterThirdEyeOverlays()
        {
            ThirdEyeOverlays.Unregister(_planOverlay);
            ThirdEyeOverlays.Unregister(_senseOverlay);
            ThirdEyeReadouts.Unregister(_hitsReadout);
            _planOverlay = _senseOverlay = null;
            _hitsReadout = null;
        }

        public override void OnDestroy()
        {
            UnregisterThirdEyeOverlays();
            base.OnDestroy();
        }

        protected override RaceCourseSource CreateCourseSource() =>
            new SwitchbackCourseSource { FirstGateDistance = firstGateDistance };

        /// <summary>The launch panel's FIXED SEED: each intensity flies one known course
        /// (<see cref="SwitchbackBlastRun.FixedSeed"/>, 45_501-45_504), so a tester can compare runs. An authored seed
        /// or a forced one still wins.</summary>
        protected override int PickCourseSeed()
        {
            if (gameData && gameData.SwitchbackFixedSeed && courseSeed == 0 && CourseSeedOverride.Forced == 0)
                return SwitchbackBlastRun.FixedSeed(Intensity);
            return base.PickCourseSeed();
        }

        // ── The hit counter (SWITCHBACK.md "AI: the hit counter") ──────────────────────

        SwitchbackHitStats _hits;
        float _nextHitNote;

        protected override void OnCountdownTimerEnded()
        {
            base.OnCountdownTimerEnded();
            if (IsServer) _hits?.BeginRace();
        }

        protected override void OnServerTick()
        {
            base.OnServerTick();
            if (_hits != null && !_hits.Running && !_hits.Ended && gameData && gameData.IsTurnRunning) _hits.BeginRace();
            if (_hits == null || !_hits.Running || Time.time < _nextHitNote) return;
            _nextHitNote = Time.time + 0.25f;
            NoteHits();
        }

        void NoteHits()
        {
            if (_hits == null || gameData == null) return;
            int length = RaceLength;
            foreach (var p in gameData.Players)
            {
                if (p == null) continue;
                bool ai = p.IsInitializedAsAI;
#if UNITY_EDITOR || DEVELOPMENT_BUILD
                // PilotControl (the AI-flies switch) exists only in editor and development builds; in a release build
                // no human's hull can be handed to the AI, so the AI flag alone is the whole answer.
                if (!ai && p is Player human) ai = PilotControl.IsHeldByAI(human);
#endif
                int avoids = 0, blasts = 0, emerg = 0;
                _blastAI?.TryCounts(p, out avoids, out blasts, out emerg);
                int threaded = 0;
                foreach (var st in gameData.RoundStatsList)
                    if (st != null && st.Name == p.Name) { threaded = st.SwitchesThreaded; break; }
                float finish = threaded >= length && length > 0 ? _hits.Elapsed : -1f;
                _hits.Note(p, ai, ai ? (int)gameData.AIDifficultyFor(p) : 0, avoids, blasts, emerg, threaded, finish);
            }
        }

        protected override void OnTurnEndedCustom()
        {
            base.OnTurnEndedCustom();
            if (!IsServer || _hits == null || !_hits.Running) return;
            NoteHits();
            _hits.EndRace(Intensity, CourseSeedUsed);
            _blastAI?.LogFlightStats();
        }

        // ── Blast Run (SWITCHBACK.md "Blast Run") ──────────────────────

        SwitchbackBlastRunRuntime _runtime;
        SwitchbackFeatureLayout _blastLayout;
        CrystalManager _keyManager;
        SwitchbackPathRays _rays;
        SwitchbackBlastAI _blastAI;

        /// <summary>
        /// Blast Run, hung on the course on every peer from the course every peer received (Breakwater's stations are
        /// the same shape): the layout (doors, block fields, movers), its prisms, the key crystals, then the runtime
        /// that moves the movers and logs the run.
        /// </summary>
        protected override void OnCourseRaised()
        {
            int intensity = Intensity;
            Vector3 centre = ResolveCellCentre();
            ResolveShell(out float inner, out _);
            // The nucleus sits inside the course's inner shell (inner = nucleus x innerRadiusNucleusFactor).
            float clearRadius = inner / innerRadiusNucleusFactor + NucleusMargin;

            var layout = LaysBlastRun(intensity)
                ? SwitchbackBlastRun.Layout(_course, intensity, centre, clearRadius, BlastRunGauntlet)
                : new SwitchbackFeatureLayout();
            RaiseBlastRun(layout);
            ApplyFaunaCorridor(intensity);
            // The I4 gauntlet's rays light the way through every blocked gate (empty below I4).
            if (_rays) Destroy(_rays.gameObject);
            _rays = SwitchbackPathRays.Create(layout, _course, pathRayRadius, gameObject.scene);

            Transform container = null;
            if (layout.Prisms.Count > 0)
            {
                if (!featuresPrefab)
                    CSDebug.LogError("[Switchback] No features prefab assigned - intensity " + intensity +
                                     " is missing its Blast Run prisms. Assign SpawnableSwitchbackFeatures on the controller.");
                else
                {
                    var features = Instantiate(featuresPrefab, transform);
                    features.name = "SwitchbackFeatures";
                    features.SetLayout(_course, intensity, layout, centre, clearRadius);
                    GameObject go;
                    using (s_featuresSpawnMarker.Auto()) go = features.Spawn(intensity);
                    if (go)
                    {
                        go.name = "SwitchbackFeatures (prisms)";
                        container = go.transform;
                    }
                }
            }

            _runtime = new GameObject("SwitchbackBlastRun").AddComponent<SwitchbackBlastRunRuntime>();
            _runtime.transform.SetParent(transform, false);
            // The prism sense (dodge any prism, trails included) runs on every course, blocked gates or none; only the
            // blast planning needs stations. (Before 2026-10-29 a course with no blocked gate had no sense at all.)
            if (aiSenseDebug) SwitchbackBlastAI.DebugSense = true;
            bool planAI = IsServer && aiBlastPlanner;
            _runtime.Init(gameData, intensity, IsServer ? CourseSeedUsed : 0, _course.Count, () => RaceLength, layout, container,
                          trackAllPrisms: planAI && layout.Stations.Count > 0);
            RegisterThirdEyeOverlays();
            if (IsServer)
            {
                _hits?.Dispose();
                var rt = _runtime;
                _hits = new SwitchbackHitStats(pr => rt && rt.IsMover(pr));
                SwitchbackAIClock.Reset();
            }
            _blastAI?.Dispose();
            _blastAI = planAI
                ? new SwitchbackBlastAI(new SwitchbackBlastPlanner(layout, _course.Count, intensity, BlastRunGauntlet), _runtime, _course,
                                        RingIndexFor, () => RaceLength, SkillFor, CourseSeedUsed, AvoidSkillFor,
                                        p => (int)gameData.AIDifficultyFor(p))
                {
                    DodgeDangerOnly = aiDodgeDangerOnly,
                    NoDodgeNearRing = aiNoDodgeNearRing,
                    StrikeSetupLeg = aiStrikeSetupLeg,
                }
                : null;
            if (_blastAI != null)
            {
                var ai = _blastAI;
                _runtime.LateTick += () =>
                {
                    long t = SwitchbackAIClock.Begin();
                    ai.LateTick();
                    SwitchbackAIClock.End(t);
                };
            }

            CSDebug.LogVerbose(CSLogChannel.ArcadeMatch,
                $"[Switchback] BLAST RUN intensity {intensity}: {_course.Count} gates, {layout.Stations.Count} blocked gates, " +
                $"{layout.Movers.Count} movers, {layout.Prisms.Count} prisms.");
        }

        /// <summary>
        /// Every peer: register the key crystals (the key blast's wider core reads them on whichever peer detonates).
        /// The server also hands them to the cell's crystal manager - which lays one crystal at each key and respawns it
        /// there, replicated to clients through its slot list. Nothing else of Blast Run is replicated: the block
        /// fields and their movers are a pure function of the course and the shared clock.
        /// </summary>
        void RaiseBlastRun(SwitchbackFeatureLayout layout)
        {
            _blastLayout = layout;
            var keys = new List<Vector3>(layout.Stations.Count);
            foreach (var st in layout.Stations) keys.Add(st.Key);
            BlastRunKeyCrystals.Register(keys);

            if (!IsServer) return;
            _keyManager = Object.FindAnyObjectByType<CrystalManager>(FindObjectsInactive.Include);
            if (_keyManager) _keyManager.SetCourseKeys(keys);
            else
                CSDebug.LogError("[Switchback] BLAST RUN: no CrystalManager in the scene - the " + keys.Count +
                                 " key crystals are not laid, and the doors can only be blasted with other crystals.");
        }

        /// <summary>Per-intensity corridor radius from <see cref="faunaCorridorRadiusByIntensity"/> (clamped index; 0 when unset).</summary>
        public static float CorridorRadiusFor(float[] byIntensity, int intensity)
        {
            if (byIntensity == null || byIntensity.Length == 0) return 0f;
            return Mathf.Max(0f, byIntensity[Mathf.Clamp(intensity - 1, 0, byIntensity.Length - 1)]);
        }

        readonly List<Vector3> _corridorPath = new(32);
        Cell _corridorCell;

        /// <summary>Every peer: fence the course path off from the cell's fauna (an open chain, so not closed).</summary>
        void ApplyFaunaCorridor(int intensity)
        {
            var cell = cellData != null ? Cell.FindByRuntimeData(cellData) : null;
            if (!cell) return;
            float radius = CorridorRadiusFor(faunaCorridorRadiusByIntensity, intensity);
            _corridorPath.Clear();
            for (int i = 0; i < _course.Count; i++) _corridorPath.Add(_course[i].Position);
            cell.SetFaunaPathCorridor(_corridorPath, radius, closed: false, faunaCorridorGoalStandoff);
            _corridorCell = radius > 0f ? cell : null;
            if (radius > 0f)
                CSDebug.LogVerbose(CSLogChannel.ArcadeMatch,
                    $"[Switchback] fauna corridor {radius:0} u round {_course.Count} gates (intensity {intensity}).");
        }

        public override void OnNetworkDespawn()
        {
            if (_corridorCell) _corridorCell.ClearFaunaPathCorridor();
            _corridorCell = null;
            if (_rays) Destroy(_rays.gameObject);
            _rays = null;
            _hits?.Dispose();
            _hits = null;
            if (_blastLayout != null)
            {
                BlastRunKeyCrystals.Clear();
                if (IsServer && _keyManager) _keyManager.ClearCourseKeys();
                _keyManager = null;
                _blastLayout = null;
                _blastAI?.Dispose();
                _blastAI = null;
            }
            UnregisterThirdEyeOverlays();
            base.OnNetworkDespawn();
        }
    }

    /// <summary>One intensity's AI nose follow rates per second, by difficulty (SWITCHBACK.md "Lag by difficulty"):
    /// 1.5 = the fleet lag, higher = faster, 0 = no lag, negative = leave that level on the fleet lag.</summary>
    [System.Serializable]
    public struct SwitchbackNoseFollow
    {
        [Tooltip("Easy's nose follow rate per second.")] public float easy;
        [Tooltip("Medium's nose follow rate per second.")] public float medium;
        [Tooltip("Hard's nose follow rate per second.")] public float hard;
        [Tooltip("Legendary's nose follow rate per second (0 = no lag).")] public float legendary;

        public SwitchbackNoseFollow(float easy, float medium, float hard, float legendary)
        {
            this.easy = easy; this.medium = medium; this.hard = hard; this.legendary = legendary;
        }

        /// <summary>The rate for a level (1 Easy .. 4 Legendary), or -1 (the fleet lag) for any other.</summary>
        public float For(int level) => level switch { 1 => easy, 2 => medium, 3 => hard, 4 => legendary, _ => -1f };
    }
}
