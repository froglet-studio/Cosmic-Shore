using UnityEngine;

namespace CosmicShore.Gameplay
{
    /// <summary>
    /// How a crystal's triangular prisms ride their columns by depth (<see cref="CrystalDepthPrisms"/>). The
    /// crystal itself holds still: the lab's free turn was dropped (2026-10-12), so the pilot flying round a
    /// crystal is the only thing that turns its prisms through the ratchet. The SHAPE of each prism (thickness, face split, how far out the top of a column
    /// is) lives on its material (<c>OmniDepthPrismShader</c>), so the omni and the Mass crystal share this one
    /// profile and differ only in their materials.
    ///
    /// <c>CrystalDepthPrismProfile.asset</c> is GENERATED by <c>Tools/Build/author_omni_crystal_triangles.py</c>
    /// from the look picked in the Omni Shepard Lab (round 7, "Depth ratchet") and the Omni Motion Lab (round 5:
    /// seal at the horizon, rise while hidden, a later descent), and its <c>--check</c> fails if the asset drifts.
    /// Retune in the lab, then in the generator.
    /// </summary>
    [CreateAssetMenu(fileName = "CrystalDepthPrismProfile", menuName = "ScriptableObjects/Crystals/Depth Prism Profile")]
    public class CrystalDepthPrismProfileSO : ScriptableObject
    {
        [Header("Depth")]
        [Tooltip("Depth d = the prism's direction · the camera's direction, in the crystal's own space (+1 faces the camera, 0 on the silhouette, −1 straight behind). At and behind this d a prism sits at the top of its column.")]
        [SerializeField, Range(-1f, 0.9f)] float openDepth = -0.25f;

        [Tooltip("At and in front of this depth a prism is sealed in its hole.")]
        [SerializeField, Range(-0.9f, 1f)] float sealDepth = 1f;

        [Tooltip("Shapes the glide between the two depths: above 1 the prisms stay high until late and drop in near the front; below 1 they drop early.")]
        [SerializeField, Range(0.3f, 3f)] float profilePower = 1f;

        [Header("Ratchet")]
        [Tooltip("A prism going away stays where it got to until it is behind this depth - hidden by the crystal - and then reseats: it fades out in its hole while a new one fades in at the top of its column. An omni column top stands 2x its plate radius out (the Mass crystal's 1.5x since 2026-10-14, so it clears sooner), so seen from far away (nearly orthographic) it clears the silhouette above about −0.87: the lab measured −0.8 seen on 56-73% of reseats at 250 u, −0.87 on none at any distance (round 10). Deeper = fewer reseats; with Rise While Hidden on, the reseat is a fallback and sits at −0.97 (Omni Motion Lab round 3).")]
        [SerializeField, Range(-1f, 0.5f)] float reseatDepth = -0.97f;

        [Tooltip("Seconds a reseat takes. The two prisms dither on complementary pixels, so it never shows a gap.")]
        [SerializeField, Min(0.05f)] float reseatFadeSeconds = 0.6f;

        [Header("Horizon (Omni Motion Lab round 1)")]
        [Tooltip("Seal every prism at the camera's HORIZON instead of at Seal Depth: a plate at radius r faces a camera at distance D once its depth passes r / D, so the seal depth is computed each frame as r / D - Horizon Margin and every prism the camera can see is flush in its hole (no prism visibly part-way out, so none clips into the squares beside it).")]
        [SerializeField] bool sealAtHorizon = true;

        [Tooltip("Seal this much depth before the horizon, so a prism is already flush a little before its plate turns toward the camera.")]
        [SerializeField, Range(0f, 0.3f)] float horizonMargin = 0.05f;

        [Header("Rise while hidden (Omni Motion Lab round 3)")]
        [Tooltip("A prism may also CLIMB its column whenever its column top is hidden behind the crystal's body (a sphere of Occluder Radius), so it is never seen rising. Every hidden prism then stands out, and the ones coming round the edge come in from the top; the reseat becomes a fallback. The lab measured the visible height of prisms standing out going from 1.5 to 7.4 plate radii with this on, with no rise or reseat ever seen.")]
        [SerializeField] bool riseWhileHidden = true;

        [Tooltip("How fast a hidden prism climbs, in column-heights per second.")]
        [SerializeField, Range(0.2f, 6f)] float riseRate = 1.5f;

        [Tooltip("The body the camera cannot see through, as a sphere: x the plates' own radius (the lab's 0.936 = the shell less a plate's thickness and a gap).")]
        [SerializeField, Range(0.5f, 1f)] float occluderRadius = 0.936f;

        [Header("Variety")]
        [Tooltip("Each crystal is turned to its own random pose, seeded from its spawn position (the same on every client; nothing networked): 0 = every crystal in its authored pose, 1 = uniformly random. Depth is read in the crystal's own space, so the rule holds exactly; without this, crystals far away all see the camera from the same direction and show the same columns (lab round 10: neighbours' images correlate 0.60 at 250 u, 0.12 with a pose each). Turns the crystal's models, never its root.")]
        [SerializeField, Range(0f, 1f)] float orientationJitter = 1f;

        public float OpenDepth => openDepth;
        public float SealDepth => sealDepth;
        public float ProfilePower => profilePower;
        public float ReseatDepth => reseatDepth;
        public float ReseatFadeSeconds => reseatFadeSeconds;
        public float OrientationJitter => orientationJitter;
        public bool SealAtHorizon => sealAtHorizon;
        public float HorizonMargin => horizonMargin;
        public bool RiseWhileHidden => riseWhileHidden;
        public float RiseRate => riseRate;
        public float OccluderRadius => occluderRadius;

        public float Seat(float depth) => CosmicShore.Utility.DepthRatchet.Seat(depth, openDepth, sealDepth, profilePower);

        /// <summary>The seat at <paramref name="depth"/> with the seal at <paramref name="seal"/> (the horizon's, when
        /// <see cref="SealAtHorizon"/>).</summary>
        public float Seat(float depth, float seal) => CosmicShore.Utility.DepthRatchet.Seat(depth, openDepth, seal, profilePower);

        /// <summary>The seal depth to use for a plate at <paramref name="plateRadius"/> seen from
        /// <paramref name="cameraDistance"/>, both in the crystal's space.</summary>
        public float SealFor(float plateRadius, float cameraDistance) =>
            sealAtHorizon ? CosmicShore.Utility.DepthRatchet.HorizonSealDepth(plateRadius, cameraDistance, horizonMargin) : sealDepth;
    }
}
