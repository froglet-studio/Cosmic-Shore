using CosmicShore.Utility;
using UnityEngine;

namespace CosmicShore.Gameplay
{
    /// <summary>
    /// What one OMNI COMBINE play reads: the four elemental crystals idling with their own effects, flying in
    /// one after another and turning into their shares of the omni crystal, which wakes with all four effects
    /// (<see cref="OmniCombinePlayer"/>; the Elemental Converter on the Ark screen plays it).
    ///
    /// The motion and the morphs are the Omni Combine Lab's (Docs/Studios/OMNI_COMBINE_LAB.md, round 2), and
    /// the data is the lab's (<c>OmniCombineData.json</c>, from <c>Tools/Build/author_omni_combine_asset.py</c>).
    /// What this adds is VARIETY: every play draws its choreography from the ranges below, so no two plays are
    /// the same film. The defaults keep each crystal's animation SEPARATE and SLOW - the next sets off only as
    /// the last one lands (designer, 2026-10-13: "each movement is hypnotic ... each time you watch it you will
    /// notice something new").
    ///
    /// <c>OmniCombineConfig.asset</c> is GENERATED by <c>Tools/Build/author_elemental_converter.py</c>, and its
    /// <c>--check</c> fails if it drifts. Retune there, or in the inspector and then in the generator.
    /// </summary>
    [CreateAssetMenu(fileName = "OmniCombineConfig", menuName = "ScriptableObjects/Crystals/Omni Combine Config")]
    public class OmniCombineConfigSO : ScriptableObject
    {
        [Header("Data")]
        [Tooltip("OmniCombineData.json: the four crystals, their morph targets and the omni, in Unity's axes (Tools/Build/author_omni_combine_asset.py).")]
        [SerializeField] TextAsset combineData;

        [Header("Materials")]
        [Tooltip("The Charge crystal. ChargeCrystalMaterial: its discharge needs the edge bake, which the player runs on its own mesh.")]
        [SerializeField] Material chargeMaterial;
        [Tooltip("The Space and Time crystals. OmniCrystalBody: the omni's own body material - the same lime pair every elemental crystal ships in - so those plates do not change look when the omni takes over.")]
        [SerializeField] Material shellMaterial;
        [Tooltip("The Mass crystal, as it is drawn in play: MassDepthPrisms (the depth-prism shader). The crystal itself is the game's MassCrystalPrisms mesh, carried in the combine data.")]
        [SerializeField] Material massMaterial;
        [Tooltip("The finished omni crystal's body. OmniCrystalBody.")]
        [SerializeField] Material omniMaterial;
        [Tooltip("The discharge on the omni's twelve pentagons. OmniChargeEdges (additive, drawn over the body).")]
        [SerializeField] Material omniChargeEdgesMaterial;
        [Tooltip("The omni's triangles, as they are drawn in play: OmniDepthPrisms.")]
        [SerializeField] Material omniTrianglesMaterial;

        [Header("Depth prisms (the game's)")]
        [Tooltip("The omni's triangle prisms: OmniCrystalTriangles.asset (Read/Write), turned onto the combine's omni by the rotation in the combine data.")]
        [SerializeField] Mesh omniTrianglesMesh;
        [Tooltip("How the Mass prisms and the omni's triangles ride their columns by depth: the profile CrystalDepthPrisms uses in play.")]
        [SerializeField] CrystalDepthPrismProfileSO depthProfile;

        [Header("Choreography - drawn per play from each range (min, max)")]
        [Tooltip("Seconds the four idle, each doing its own effect, before the first sets off.")]
        [SerializeField] Vector2 lead = new(2.2f, 3.2f);
        [Tooltip("Start distance in omni radii.")]
        [SerializeField] Vector2 spread = new(2.7f, 3.3f);
        [Tooltip("Degrees the whole start layout is turned about the vertical.")]
        [SerializeField] Vector2 layoutYawDegrees = new(0f, 360f);
        [Tooltip("Seconds each crystal takes to arrive and turn into its share.")]
        [SerializeField] Vector2 flight = new(4.4f, 5.4f);
        [Tooltip("Seconds between one crystal setting off and the next, as a fraction of the flight. 1 = the next sets off as the last lands, so each animation plays on its own.")]
        [SerializeField] Vector2 staggerOfFlight = new(0.95f, 1.05f);
        [Tooltip("How far the path bows upward, as a fraction of the start distance.")]
        [SerializeField] Vector2 arc = new(0.25f, 0.55f);
        [Tooltip("Turns the path wraps round the omni on the way in.")]
        [SerializeField] Vector2 swirl = new(-0.15f, 0.15f);
        [Tooltip("Turns each crystal tumbles about its own (seeded) axis in flight; it untwists to land.")]
        [SerializeField] Vector2 tumble = new(0.15f, 0.35f);
        [Tooltip("0: every site of a crystal morphs together. 1: each site starts at its own seeded moment.")]
        [SerializeField] Vector2 siteSpread = new(0.35f, 0.65f);
        [Tooltip("Share of Charge's morph spent sucking each petal's back in before the tips fuse and flatten.")]
        [SerializeField] Vector2 suck = new(0.3f, 0.4f);

        [Header("Choreography - fixed")]
        [Tooltip("Where the four start: 0 the art file's row, 1 a ring, 2 a tetrahedron.")]
        [SerializeField, Range(0, 2)] int layout = 2;
        [Tooltip("Ease in and out of each flight. 1 is constant speed.")]
        [SerializeField, Range(1f, 4f)] float ease = 2f;
        [Tooltip("How far through its flight a crystal starts turning into its share.")]
        [SerializeField, Range(0f, 0.9f)] float morphStart = 0.1f;
        [Tooltip("How much of the flight one site's morph takes.")]
        [SerializeField, Range(0.1f, 1f)] float morphLength = 0.8f;
        [Tooltip("Seconds an idle crystal's effect takes to settle as it sets off, and the omni's to wake.")]
        [SerializeField, Range(0.1f, 2f)] float effectFade = 0.7f;

        [Header("Presentation")]
        [Tooltip("Seconds the four crystals take to fade in when a play starts.")]
        [SerializeField, Range(0f, 3f)] float fadeInSeconds = 1f;
        [Tooltip("Seconds the omni's body takes to dither in over the landed plates before its effects wake.")]
        [SerializeField, Range(0.05f, 2f)] float handOffSeconds = 0.6f;
        [Tooltip("The omni crystal's radius in world units on the stage. Large on purpose: float precision on the off-screen stage is absolute, so a bigger stage shimmers less (ElementalConverterView.StageOrigin).")]
        [SerializeField, Min(0.1f)] float omniWorldRadius = 40f;

        public TextAsset CombineData => combineData;
        public Material ChargeMaterial => chargeMaterial;
        public Material ShellMaterial => shellMaterial;
        public Material OmniMaterial => omniMaterial;
        public Material OmniChargeEdgesMaterial => omniChargeEdgesMaterial;
        public Material MassMaterial => massMaterial;
        public Material OmniTrianglesMaterial => omniTrianglesMaterial;
        public Mesh OmniTrianglesMesh => omniTrianglesMesh;
        public CrystalDepthPrismProfileSO DepthProfile => depthProfile;
        public float FadeInSeconds => fadeInSeconds;
        public float HandOffSeconds => handOffSeconds;
        public float OmniWorldRadius => omniWorldRadius;

        /// <summary>One play's choreography: every ranged knob drawn uniformly, plus a seed for the per-crystal
        /// tumble axes, the per-site morph delays and the flip wave's start vertices.</summary>
        public OmniCombineParams Draw(System.Random rng)
        {
            float Pick(Vector2 r) => Mathf.Lerp(r.x, r.y, (float)rng.NextDouble());
            float fl = Pick(flight);
            return new OmniCombineParams
            {
                Seed = rng.Next(),
                Lead = Pick(lead),
                Layout = layout,
                Spread = Pick(spread),
                LayoutYaw = Pick(layoutYawDegrees) * Mathf.Deg2Rad,
                Flight = fl,
                Stagger = fl * Pick(staggerOfFlight),
                Ease = ease,
                Arc = Pick(arc),
                Swirl = Pick(swirl),
                Tumble = Pick(tumble),
                MorphStart = morphStart,
                MorphLength = morphLength,
                SiteSpread = Pick(siteSpread),
                Suck = Pick(suck),
                EffectFade = effectFade,
                EffectPhase = rng.NextDouble() * 100.0,
            };
        }

        /// <summary>The farthest any crystal starts from the omni's centre, in omni radii, over every draw.</summary>
        public float MaxStartRadii => Mathf.Max(spread.x, spread.y) * (1f + Mathf.Max(arc.x, arc.y)) + 1f;
    }
}
