        [Test]
        public void Pose_IsTheAuthoredPoseAtZero_AndTheSameForTheSameSpawn()
        {
            uint seed = CrystalPoseJitter.SeedOf(new Vector3(12.5f, -3f, 400.25f));
            Assert.AreEqual(seed, CrystalPoseJitter.SeedOf(new Vector3(12.5f, -3f, 400.25f)));
            Assert.AreEqual(seed, CrystalPoseJitter.SeedOf(new Vector3(12.5012f, -3.0004f, 400.2499f)), "float noise below 5 mm must not change the pose");
            Assert.AreNotEqual(seed, CrystalPoseJitter.SeedOf(new Vector3(37.5f, -3f, 400.25f)), "the next pickup in a row must get its own pose");
            var still = CrystalPoseJitter.Pose(seed, 0f);
            Assert.AreEqual(0f, Vector3.Distance(still * new Vector3(0.3f, 0.5f, -0.8f), new Vector3(0.3f, 0.5f, -0.8f)), 1e-6f);
            var q = CrystalPoseJitter.Pose(seed, 1f);
            Assert.AreEqual(1f, q.x * q.x + q.y * q.y + q.z * q.z + q.w * q.w, 1e-5f, "not a unit quaternion");
        }

        /// <summary>The JS twin (<c>window.__lab.poseOfSeed</c> in OmniShepardLab.html), measured 2026-10-13: the same
