using CosmicShore.Utility;
using NUnit.Framework;
using UnityEngine;

namespace CosmicShore.Tests
{
    /// <summary>
    /// The depth prisms' pure maths: <see cref="DepthRatchet"/> (Omni Shepard Lab round 7) and the per-crystal pose
    /// <see cref="CrystalPoseJitter"/> (round 10). These pin the ratchet's two promises - in view a prism only
    /// ever moves down, and it is replaced only behind the crystal - with and without a random pose per crystal.
    /// No editor dependencies: <c>Tools/Build/crystal_depth_harness</c> compiles and runs this file headlessly.
    /// </summary>
    public class DepthRatchetTests
    {
        // The shipped profile (CrystalDepthPrismProfile.asset, generated by author_omni_crystal_triangles.py).
        const float Open = -0.88f, Seal = 1f, Power = 1f, Reseat = -0.87f, Fade = 0.6f;

        [Test]
        public void Seat_IsTopBehindTheOpenDepth_SealedFromTheSealDepth_AndMonotonic()
        {
            Assert.AreEqual(0f, DepthRatchet.Seat(-1f, -0.88f, 1f, 1f), 1e-6f);
            Assert.AreEqual(0f, DepthRatchet.Seat(-0.88f, -0.88f, 1f, 1f), 1e-6f);
            Assert.AreEqual(1f, DepthRatchet.Seat(1f, -0.88f, 1f, 1f), 1e-6f);
            float last = -1f;
            for (float d = -1f; d <= 1f; d += 0.01f)
            {
                float seat = DepthRatchet.Seat(d, -0.88f, 1f, 1f);
                Assert.GreaterOrEqual(seat, last - 1e-6f, $"seat fell at depth {d}");
                last = seat;
            }
        }

        /// <summary>
        /// A column carried round and round the crystal (its depth a cosine of the turn), for several orbits that
        /// pass behind and several that never do. Its place may FALL (rise up the column) only at the instant a
        /// reseat starts, which only happens behind the reseat depth, and every reseat finishes its fade.
        /// </summary>
        [Test]
        public void Ratchet_OnlyEverDescendsInView_AndReseatsOnlyBehind()
        {
            const float dt = 1f / 60f;
            int reseats = 0;
            foreach (float tilt in new[] { 0f, 0.3f, 0.6f, 0.95f })   // 0: passes straight behind; 0.95: never gets there
            {
                float Depth(float t) => Mathf.Cos(tilt) * Mathf.Cos(t * 0.6f) + Mathf.Sin(tilt) * 0.2f;
                var c = DepthRatchet.Column.At(DepthRatchet.Seat(Depth(0f), Open, Seal, Power));
                for (float t = dt; t < 60f; t += dt)
                {
                    float depth = Depth(t);
                    reseats += StepAndCheck(ref c, depth, depth, dt, Reseat, Fade, $"tilt {tilt}");
                }
            }
            Assert.Greater(reseats, 0, "no orbit ever reseated - the test would pass on a ratchet that never resets");
        }

        [Test]
        public void Ratchet_ReseatFadeTakesItsSeconds()
        {
            var c = DepthRatchet.Step(DepthRatchet.Column.At(1f), -0.95f, 0f, 0f, -0.8f, 0.6f);
            Assert.AreEqual(0f, c.Fade, "behind the reseat depth a sealed prism must start to reseat");
            for (int i = 0; i < 29; i++) c = DepthRatchet.Step(c, -0.95f, 0f, 0.02f, -0.8f, 0.6f);
            Assert.Less(c.Fade, 1f, "the fade finished early");
            c = DepthRatchet.Step(c, -0.95f, 0f, 0.02f, -0.8f, 0.6f);
            Assert.AreEqual(1f, c.Fade, 1e-4f, "the fade did not finish after 0.6 s");
        }

        // ------------------------------------------------------------------ round 10: a pose per crystal

        [Test]
        public void Pose_IsTheAuthoredPoseAtZero_AndTheSameForTheSameSpawn()
        {
            uint seed = CrystalPoseJitter.SeedOf(new Vector3(12.5f, -3f, 400.25f));
            Assert.AreEqual(seed, CrystalPoseJitter.SeedOf(new Vector3(12.5f, -3f, 400.25f)));
            Assert.AreEqual(seed, CrystalPoseJitter.SeedOf(new Vector3(12.5012f, -3.0004f, 400.2499f)), "float noise below 5 mm must not change the pose");
            Assert.AreNotEqual(seed, CrystalPoseJitter.SeedOf(new Vector3(37.5f, -3f, 400.25f)), "the next pickup in a row must get its own pose");
            var still = CrystalPoseJitter.Pose(seed, 0f);
            Assert.AreEqual(0f, Vector3.Distance(still * new Vector3(0.3f, 0.5f, -0.8f), new Vector3(0.3f, 0.5f, -0.8f)), 1e-6f);
            var q = CrystalPoseJitter.Pose(seed, 1f);
            Assert.AreEqual(1f, q.x * q.x + q.y * q.y + q.z * q.z + q.w * q.w, 1e-5f, "not a unit quaternion");
        }

        /// <summary>The JS twin (<c>window.__lab.poseOfSeed</c> in OmniShepardLab.html), measured 2026-10-13: the same
        /// seed turns X and Y to the same place. If this fails, the lab and the game no longer draw the same poses.</summary>
        [TestCase(1u, 1f, 0.2174373361f, 0.2248389792f, 0.9498254778f, -0.1992030611f, 0.9628487546f, -0.1823195442f)]
        [TestCase(123456789u, 1f, -0.9255088233f, -0.3772395070f, -0.0335227133f, -0.1557945177f, 0.4599055725f, -0.8741938759f)]
        [TestCase(3735928559u, 1f, -0.8482489722f, -0.2698992230f, -0.4556622549f, 0.2447572924f, -0.9627826875f, 0.1146445134f)]
        [TestCase(42u, 0.5f, 0.4931157683f, -0.7024510085f, 0.5132245315f, 0.5377541866f, 0.7098538067f, 0.4548934028f)]
        public void Pose_MatchesTheLab(uint seed, float amount, float xx, float xy, float xz, float yx, float yy, float yz)
        {
            var q = CrystalPoseJitter.Pose(seed, amount);
            Assert.AreEqual(0f, Vector3.Distance(q * new Vector3(1f, 0f, 0f), new Vector3(xx, xy, xz)), 2e-6f, "X axis");
            Assert.AreEqual(0f, Vector3.Distance(q * new Vector3(0f, 1f, 0f), new Vector3(yx, yy, yz)), 2e-6f, "Y axis");
        }

        [Test]
        public void Pose_IsUniform_NotBiasedTowardAnyDirection()
        {
            // A uniform rotation sends +Y anywhere on the sphere with equal chance: the mean over many spawns is ~0,
            // and each hemisphere of every axis gets about half.
            var sum = Vector3.zero;
            int up = 0, n = 4000;
            for (int i = 0; i < n; i++)
            {
                var v = CrystalPoseJitter.Pose(CrystalPoseJitter.SeedOf(new Vector3(i * 25f, 0f, (i % 7) * 25f)), 1f) * Vector3.up;
                sum += v;
                if (v.y > 0f) up++;
            }
            Assert.Less((sum / n).magnitude, 0.05f, $"mean direction {sum / n}");
            Assert.AreEqual(0.5f, up / (float)n, 0.03f, "the poses favour one hemisphere");
        }

        /// <summary>
        /// A row of crystals, each turned to its own pose, and a camera orbiting them all. Each crystal's ratchet reads
        /// depth in its own space (what CrystalDepthPrisms does), which must equal the depth seen in the world - the
        /// rule holds exactly under a pose - and every column keeps both promises.
        /// </summary>
        [Test]
        public void Ratchet_WithAPoseEachCrystal_KeepsBothPromises()
        {
            const float dt = 1f / 30f;
            var plates = FibonacciSphere(60);
            int reseats = 0;
            for (int k = 0; k < 8; k++)
            {
                var centre = new Vector3(k * 25f, 0f, 0f);
                var pose = CrystalPoseJitter.Pose(CrystalPoseJitter.SeedOf(centre), 1f);
                var inverse = Quaternion.Inverse(pose);
                var columns = new DepthRatchet.Column[plates.Length];
                for (float t = 0f; t < 40f; t += dt)
                {
                    var eye = new Vector3(87.5f + 120f * Mathf.Cos(t * 0.3f), 40f * Mathf.Sin(t * 0.17f), 120f * Mathf.Sin(t * 0.3f));
                    var toCameraWorld = (eye - centre).normalized;
                    var toCameraLocal = inverse * toCameraWorld;
                    for (int j = 0; j < plates.Length; j++)
                    {
                        float local = Vector3.Dot(plates[j], toCameraLocal);
                        float world = Vector3.Dot(pose * plates[j], toCameraWorld);
                        Assert.AreEqual(world, local, 1e-5f, "depth in the crystal's own space must be the depth the camera sees");
                        if (t == 0f) { columns[j] = DepthRatchet.Column.At(DepthRatchet.Seat(local, Open, Seal, Power)); continue; }
                        reseats += StepAndCheck(ref columns[j], local, world, dt, Reseat, Fade, $"crystal {k} plate {j}");
                    }
                }
            }
            Assert.Greater(reseats, 0, "nothing reseated - the orbit never took a column behind");
        }

        /// <summary>One step of one column, asserting both promises. Returns 1 when a reseat started.</summary>
        static int StepAndCheck(ref DepthRatchet.Column c, float depth, float worldDepth, float dt, float reseat, float fade, string where)
        {
            float seat = DepthRatchet.Seat(depth, Open, Seal, Power);
            var next = DepthRatchet.Step(c, depth, seat, dt, reseat, fade);
            int started = 0;
            if (c.Fade >= 1f && next.Fade < 1f)
            {
                started = 1;
                Assert.Less(worldDepth, reseat, $"a reseat started in view (depth {worldDepth}, {where})");
                Assert.AreEqual(c.Place, next.LeavingPlace, 1e-6f, "the leaving prism must fade where the old one sat");
            }
            else if (next.Fade >= 1f && c.Fade >= 1f)
            {
                Assert.GreaterOrEqual(next.Place, c.Place - 1e-6f, $"a settled prism rose at depth {depth} ({where})");
            }
            c = next;
            return started;
        }

        static Vector3[] FibonacciSphere(int n)
        {
            var dirs = new Vector3[n];
            float golden = Mathf.PI * (3f - Mathf.Sqrt(5f));
            for (int i = 0; i < n; i++)
            {
                float y = 1f - 2f * (i + 0.5f) / n, r = Mathf.Sqrt(1f - y * y), a = golden * i;
                dirs[i] = new Vector3(r * Mathf.Cos(a), y, r * Mathf.Sin(a));
            }
            return dirs;
        }
    }
