        [Test]
        public void Pose_IsUniform_NotBiasedTowardAnyDirection()
        {
            // A uniform rotation sends +Y anywhere on the sphere with equal chance: the mean over many spawns is ~0,
            // and each hemisphere of every axis gets about half.
            var sum = Vector3.zero;
            int up = 0, n = 4000;
            for (int i = 0; i < n; i++)
            {
                var v = CrystalPoseJitter.Pose(CrystalPoseJitter.SeedOf(new Vector3(i * 25f, 0f, (i % 7) * 25f)), 1f) * Vector3.up;
                sum += v;
                if (v.y > 0f) up++;
            }
            Assert.Less((sum / n).magnitude, 0.05f, $"mean direction {sum / n}");
            Assert.AreEqual(0.5f, up / (float)n, 0.03f, "the poses favour one hemisphere");
        }

        /// <summary>
        /// A row of crystals, each turned to its own pose, and a camera orbiting them all. Each crystal's ratchet reads
        /// depth in its own space (what CrystalDepthPrisms does), which must equal the depth seen in the world - the
        /// rule holds exactly under a pose - and every column keeps both promises.
        /// </summary>
        [Test]
        public void Ratchet_WithAPoseEachCrystal_KeepsBothPromises()
        {
            const float dt = 1f / 30f;
            var plates = FibonacciSphere(60);
            int reseats = 0;
            for (int k = 0; k < 8; k++)
            {
                var centre = new Vector3(k * 25f, 0f, 0f);
                var pose = CrystalPoseJitter.Pose(CrystalPoseJitter.SeedOf(centre), 1f);
                var inverse = Quaternion.Inverse(pose);
                var columns = new DepthRatchet.Column[plates.Length];
                for (float t = 0f; t < 40f; t += dt)
                {
                    var eye = new Vector3(87.5f + 120f * Mathf.Cos(t * 0.3f), 40f * Mathf.Sin(t * 0.17f), 120f * Mathf.Sin(t * 0.3f));
                    var toCameraWorld = (eye - centre).normalized;
                    var toCameraLocal = inverse * toCameraWorld;
                    for (int j = 0; j < plates.Length; j++)
                    {
                        float local = Vector3.Dot(plates[j], toCameraLocal);
                        float world = Vector3.Dot(pose * plates[j], toCameraWorld);
                        Assert.AreEqual(world, local, 1e-5f, "depth in the crystal's own space must be the depth the camera sees");
                        if (t == 0f) { columns[j] = DepthRatchet.Column.At(DepthRatchet.Seat(local, Open, Seal, Power)); continue; }
                        reseats += StepAndCheck(ref columns[j], local, world, dt, Reseat, Fade, $"crystal {k} plate {j}");
                    }
                }
            }
            Assert.Greater(reseats, 0, "nothing reseated - the orbit never took a column behind");
        }

        /// <summary>One step of one column, asserting both promises. Returns 1 when a reseat started.</summary>
        static int StepAndCheck(ref DepthRatchet.Column c, float depth, float worldDepth, float dt, float reseat, float fade, string where)
        {
            float seat = DepthRatchet.Seat(depth, Open, Seal, Power);
            var next = DepthRatchet.Step(c, depth, seat, dt, reseat, fade);
            int started = 0;
            if (c.Fade >= 1f && next.Fade < 1f)
            {
                started = 1;
                Assert.Less(worldDepth, reseat, $"a reseat started in view (depth {worldDepth}, {where})");
                Assert.AreEqual(c.Place, next.LeavingPlace, 1e-6f, "the leaving prism must fade where the old one sat");
            }
            else if (next.Fade >= 1f && c.Fade >= 1f)
            {
                Assert.GreaterOrEqual(next.Place, c.Place - 1e-6f, $"a settled prism rose at depth {depth} ({where})");
            }
            c = next;
            return started;
        }

        static Vector3[] FibonacciSphere(int n)
        {
            var dirs = new Vector3[n];
            float golden = Mathf.PI * (3f - Mathf.Sqrt(5f));
            for (int i = 0; i < n; i++)
            {
                float y = 1f - 2f * (i + 0.5f) / n, r = Mathf.Sqrt(1f - y * y), a = golden * i;
                dirs[i] = new Vector3(r * Mathf.Cos(a), y, r * Mathf.Sin(a));
            }
            return dirs;
        }
