// ExportCourse.cs - writes the Regatta circuit, as the GAME builds it, for the Regatta AI page (course.js).
// Compiled by export_course.sh against the same three pure course files and UnityEngine stub that
// Tools/Build/regatta_course_harness uses, so the page's gates and rails are RegattaCourse's own output:
// per intensity, the 8 gates (position, axis, radius), the three braided lanes (one point per prism, every 8 u,
// lane domains Jade / Ruby / Gold) and the spine length. Nothing here is retyped by hand.
using System;
using System.Globalization;
using System.Text;
using CosmicShore.Gameplay;
using UnityEngine;

public static class ExportCourse
{
    static string F(float v) => v.ToString("0.#", CultureInfo.InvariantCulture);
    static string V(Vector3 v) => "[" + F(v.x) + "," + F(v.y) + "," + F(v.z) + "]";
    static string A(Vector3 v) => "[" + v.x.ToString("0.###", CultureInfo.InvariantCulture) + "," + v.y.ToString("0.###", CultureInfo.InvariantCulture) + "," + v.z.ToString("0.###", CultureInfo.InvariantCulture) + "]";

    public static int Main()
    {
        var sb = new StringBuilder();
        sb.Append("/* GENERATED by Docs/Studios/RegattaAI/export_course.sh from RegattaCourse.BuildGates / BuildRails\n");
        sb.Append("   (Assets/_Scripts/Controller/Arcade/Regatta/RegattaCourse.cs, seed RegattaCourse.DefaultSeed). Do not edit. */\n");
        sb.Append("window.REGATTA_COURSE = {\n");
        var rs = RegattaCourse.DefaultRails;
        sb.Append("  laneOffset: " + F(rs.LaneOffset) + ", prismSpacing: " + F(rs.PrismSpacing) + ", laneDomains: ['jade','ruby','gold'],\n");
        for (int i = 1; i <= 4; i++)
        {
            var gates = RegattaCourse.BuildGates(RegattaCourse.DefaultSeed, i);
            var rails = RegattaCourse.BuildRails(gates, rs);
            sb.Append("  " + i + ": { seed: " + RegattaCourse.SeedForIntensity(RegattaCourse.DefaultSeed, i) + ", spine: " + F(rails.SpineLength) + ",\n    gates: [");
            for (int g = 0; g < gates.Count; g++) sb.Append((g > 0 ? "," : "") + "{p:" + V(gates[g].Position) + ",a:" + A(gates[g].Axis) + ",r:" + F(gates[g].Radius) + "}");
            sb.Append("],\n    lanes: [");
            for (int l = 0; l < rails.LanePositions.Count; l++)
            {
                sb.Append(l > 0 ? ",\n      [" : "\n      [");
                var lp = rails.LanePositions[l];
                for (int k = 0; k < lp.Length; k++) sb.Append((k > 0 ? "," : "") + F(lp[k].x) + "," + F(lp[k].y) + "," + F(lp[k].z));
                sb.Append("]");
            }
            sb.Append("] },\n");
        }
        sb.Append("};\n");
        Console.Out.Write(sb.ToString());
        return 0;
    }
}
