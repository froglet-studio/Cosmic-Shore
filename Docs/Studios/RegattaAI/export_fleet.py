#!/usr/bin/env python3
"""export_fleet.py - writes fleet.js, every vessel class's flight numbers for the Regatta AI training page.

    python3 Docs/Studios/RegattaAI/export_fleet.py            # rewrite fleet.js
    python3 Docs/Studios/RegattaAI/export_fleet.py --check    # exit 1 if fleet.js is stale

GENERATED data, never edited by hand: each hull's VesselTransformer numbers are read off its shipped prefab
(Assets/_Prefabs/Spacevessels/<Hull>.prefab) with Tools/Build/regatta_balance.py's own reader, so the page and the
balance model can never disagree about a hull. `onCard` marks the hulls ArcadeGameRegatta.asset seats; the page
flies those on their modelled speed verbs and every other hull on a generic drive it labels as such.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'Tools', 'Build'))
import regatta_balance as rb  # noqa: E402

# VesselClassType order (Assets/_Scripts/Data/Enums/VesselClassType.cs), every class with a prefab.
HULLS = ['Manta', 'Dolphin', 'Rhino', 'Urchin', 'Grizzly', 'Squirrel', 'Serpent', 'Termite', 'Falcon', 'Shrike',
         'Sparrow', 'Scarab', 'Butterfly', 'Thresher', 'Stoat', 'BrittleStar']
CARD = 'Assets/_SO_Assets/Games/ArcadeGameRegatta.asset'


def card_hulls():
    """The hull names the Regatta card seats: its Vessels guids resolved to their SO_Vessel assets' Class."""
    text = open(os.path.join(ROOT, CARD), encoding='utf-8').read()
    guids = re.findall(r'guid: ([0-9a-f]{32})', text.split('  Vessels:', 1)[1].split('MinPlayersAllowed', 1)[0])
    names = set()
    for dirpath, _, files in os.walk(os.path.join(ROOT, 'Assets')):
        for f in files:
            if not f.endswith('.asset.meta'):
                continue
            meta = open(os.path.join(dirpath, f), encoding='utf-8', errors='ignore').read()
            m = re.search(r'guid: ([0-9a-f]{32})', meta)
            if m and m.group(1) in guids:
                asset = open(os.path.join(dirpath, f[:-5]), encoding='utf-8', errors='ignore').read()
                c = re.search(r'^  Class: (-?\d+)', asset, re.M)
                if c and 1 <= int(c.group(1)) <= len(HULLS):
                    names.add(HULLS[int(c.group(1)) - 1])
    return names


def roll(name):
    t = open(os.path.join(ROOT, 'Assets', '_Prefabs', 'Spacevessels', name + '.prefab'), encoding='utf-8').read()
    m = re.search(r'^  RollScaler:\s*(-?[0-9.]+)\s*$', t, re.M)
    return float(m.group(1)) if m else 90.0


def build():
    card = card_hulls()
    rows = []
    for n in HULLS:
        v = rb.read_vessel(n)
        rows.append({'key': n[0].lower() + n[1:], 'name': 'Brittle Star' if n == 'BrittleStar' else n,
                     'ms': v['ms'], 'ts': v['ts'], 'p': v['pitch'], 'y': v['yaw'], 'r': roll(n), 'rts': v['rts'],
                     'boost': v['boost'], 'onCard': n in card, 'src': 'Spacevessels/' + n + '.prefab'})
    body = json.dumps(rows, indent=1)
    return ('// GENERATED by export_fleet.py from the shipped vessel prefabs. Do not edit by hand.\n'
            'window.REGATTA_FLEET = ' + body + ';\n')


def main():
    out = build()
    path = os.path.join(HERE, 'fleet.js')
    if '--check' in sys.argv:
        cur = open(path, encoding='utf-8').read() if os.path.exists(path) else ''
        if cur != out:
            print('fleet.js: STALE (run export_fleet.py)')
            return 1
        print('fleet.js: up to date')
        return 0
    open(path, 'w', encoding='utf-8').write(out)
    print('wrote', os.path.relpath(path, ROOT))
    return 0


if __name__ == '__main__':
    sys.exit(main())
