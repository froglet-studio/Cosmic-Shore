// Writes the Voyage Board's deep-zoom sky as the plain data table the game's galaxy map reads
// (Assets/Resources/Voyages/HyperSeaSky.txt, read by HyperSeaSky.cs; Docs/Voyages/VOYAGE_BOARD.md §4b).
// Usage: node Docs/Voyages/VoyageBoard/export_sky.js [--check]
//
// It runs the board's own code: the sea model (from "Canon numbers" to "Crew") for its places, and deepzoom/deepzoom.js
// over the catalogue embedded in voyage-board.html, so every star, cluster and landmark the table holds is the one the
// board draws, with the drawing level the board gives it (the place-name filter and the famous cluster names applied).
// The model's own stars are not in the table: the game generates them per tile from the same seeds (HyperSeaSky.cs).
// With --check it writes nothing and exits 1 when the committed table differs.
"use strict";
const fs = require("fs"), path = require("path");
const ROOT = path.resolve(__dirname, "../../..");
const OUT = path.join(ROOT, "Assets/Resources/Voyages/HyperSeaSky.txt");
const html = fs.readFileSync(path.join(__dirname, "voyage-board.html"), "utf8");
const dz = fs.readFileSync(path.join(__dirname, "deepzoom/deepzoom.js"), "utf8");

const from = html.indexOf("// ── Canon numbers"), to = html.indexOf("// ── Crew (voyage_slice.json)");
if (from < 0 || to < 0) throw new Error("the board's model markers moved: update export_sky.js");
// The tiles' random numbers are the board's own rng, defined after the model.
const rngLine = (html.match(/^function rng\(seed\).*$/m) || [])[0];
if (!rngLine) throw new Error("the board's rng moved: update this script");
const model = html.slice(from, to).replace("const LANES_ON = true;", "const LANES_ON = false;") + "\n" + rngLine;
const tag = '<script type="application/json" id="realsky">';
const ti = html.indexOf(tag);
if (ti < 0) throw new Error("no embedded catalogue in voyage-board.html: run deepzoom/assemble.py first");
const data = html.slice(ti + tag.length, html.indexOf("</script>", ti));

// deepzoom.js reads only these from the page at load; the exports below are its own internals.
const exportsLine = "return { draw, TIERS,";
if (!dz.includes(exportsLine)) throw new Error("deepzoom.js's return moved: update export_sky.js and golden.js");
const dzOpen = dz.replace(exportsLine, "return { real, clusters: () => clusters, SRC: () => SRC, SY1, SY2, draw, TIERS,");
const document = { getElementById: id => (id === "realsky" ? { textContent: data } : null) };
const m = new Function("document", model + "\n" + dzOpen + "\nreturn { P, EXP, DZ };")(document);
const { P, EXP, DZ } = m;

const SY3 = (dz.match(/\? a \+ b \+ " " \+ \[([^\]]+)\]/) || [])[1];
if (!SY3) throw new Error("deepzoom.js's invented-name suffixes moved: update export_sky.js");
const suffixes = JSON.parse("[" + SY3 + "]");

// The game's fonts carry Latin text only: Greek letters (Bayer names such as "τ Phe") are spelled out, and the board's
// middle dot becomes a dash.
const GREEK = { α: "Alpha", β: "Beta", γ: "Gamma", δ: "Delta", ε: "Epsilon", ζ: "Zeta", η: "Eta", θ: "Theta", ι: "Iota",
  κ: "Kappa", λ: "Lambda", μ: "Mu", ν: "Nu", ξ: "Xi", ο: "Omicron", π: "Pi", ρ: "Rho", σ: "Sigma", τ: "Tau", υ: "Upsilon",
  φ: "Phi", χ: "Chi", ψ: "Psi", ω: "Omega" };
const clean = s => String(s ?? "").replace(/[\t\r\n]+/g, " ").replace(/[α-ω]/g, c => GREEK[c] || c).replace(/ · /g, " - ")
  .replace(/·/g, "-").trim();
const n1 = v => (Math.round(v * 10) / 10).toFixed(1).replace(/\.0$/, "");
const n4 = v => String(Math.round(v * 1e4) / 1e4);
const SRC = DZ.SRC();
const lines = [];
lines.push("# The HyperSea sky for the Voyage window's galaxy map (HyperSeaSky.cs). GENERATED by");
lines.push("# Docs/Voyages/VoyageBoard/export_sky.js from the Voyage Board (https://claude.ai/artifact/25CvRSxBrjcxEUngEiCzEn);");
lines.push("# edit the board and rerun, never this file. Positions in light years, galactic centre at the origin, Sol at");
lines.push("# (0, 26000, 65); y runs from the centre toward Sol. Columns are tab-separated.");
lines.push("#");
lines.push("# Stars within 1,600 ly of Sol: HYG v4.1 by David Nash / astronexus (Hipparcos, Yale, Gliese), licensed");
lines.push("# CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/). This star table is adapted from it (positions");
lines.push("# turned to galactic light years, a drawing level added) and is shared under the same licence, as plain data.");
lines.push("# Globular clusters: Harris 1996, 2010 edition (McMaster), free with credit. Open clusters: Hunt & Reffert 2024,");
lines.push("# A&A 686, A42 (CDS VizieR): re-pull from CDS before shipping (Docs/Voyages/VOYAGE_BOARD.md §4a, Licences).");
lines.push("# Landmarks: the board's places, with their lines [S] real, [A] proposed (Garrett decides).");
lines.push("@src\tstars\t" + clean(SRC.stars));
lines.push("@src\tglobs\t" + clean(SRC.globs));
lines.push("@src\tocs\t" + clean(SRC.ocs));
// invented names for the brightest model stars near Tumult [A]: first part, second part, suffixes (one in three names)
lines.push("@names1\t" + DZ.SY1.map(clean).join("\t"));
lines.push("@names2\t" + DZ.SY2.map(clean).join("\t"));
lines.push("@names3\t" + suffixes.map(clean).join("\t"));
// the kinds of place: id, the label a reader sees
for (const [k, v] of Object.entries(EXP)) lines.push(`@kind\t${k}\t${clean(v.label)}`);
// landmarks: id, name, kind, region, source tag, x, y, z, line, sub
lines.push("@landmarks");
for (const p of P)
  lines.push([p.id, clean(p.name), p.exp, p.region || "", p.tag || "S", n1(p.x), n1(p.y), n1(p.z), clean(p.fact), clean(p.sub)].join("\t"));
// stars: x, y, z, absolute magnitude, B-V colour, name rank (0-3), drawing level, name, designation
lines.push("@stars");
const stars = [];
for (const list of DZ.real.values()) for (const s of list) stars.push(s);
stars.sort((a, b) => a.lvl - b.lvl || a.x - b.x || a.y - b.y || a.z - b.z);
for (const s of stars) lines.push([n1(s.x), n1(s.y), n1(s.z), n1(s.M), n1(s.ci), s.rank, n4(s.lvl), clean(s.name), clean(s.desig)].join("\t"));
// clusters: x, y, z, absolute magnitude, 1 globular / 0 open, drawing level, name, the name its label shows (the board
// labels "NGC 104 · 47 Tuc" as "47 Tuc"), catalogue id, members, log10 age, distance from Sol (ly)
lines.push("@clusters");
for (const c of DZ.clusters())
  lines.push([n1(c.x), n1(c.y), n1(c.z), n1(c.M), c.glob ? 1 : 0, n4(c.lvl), clean(c.name),
    clean(c.name.split(" · ")[c.name.includes(" · ") ? 1 : 0]), clean(c.id || ""), c.n || 0,
    c.age ? n4(c.age) : 0, Math.round(c.dly || 0)].join("\t"));
const out = lines.join("\n") + "\n";

if (process.argv.includes("--check")) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (have !== out) { console.log(`DRIFT: ${path.relative(ROOT, OUT)} differs from the board; rerun export_sky.js`); process.exit(1); }
  console.log(`check: ${path.relative(ROOT, OUT)} matches the board (${stars.length} stars, ${DZ.clusters().length} clusters, ${P.length} landmarks)`);
} else {
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${stars.length} stars, ${DZ.clusters().length} clusters, ${P.length} landmarks, ${out.length} bytes`);
}
